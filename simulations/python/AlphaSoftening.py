"""
Путь 10: бег alpha как размягчение среды (пункт T-6).

Гипотеза: alpha содержит скорость волны, скорость падает с избытком дрожания,
значит бег alpha есть профиль размягчения. Модуль доводит гипотезу до
проверяемых утверждений и проверяет те, что проверяются сразу.

Разделы:
  1. знак: от чего он зависит и сходится ли
  2. мнимое противоречие «1/r против логарифма» и его снятие
  3. что бег требует от дисперсии среды
  4. насколько среда размягчена на своём же масштабе ячейки
  5. обычная решёточная дисперсия ИСКЛЮЧЕНА
  6. обращение: alpha из коэффициента размягчения, и с какой точностью
  7. что осталось вычислить

Расчёты к подглаве theory/04-14-puti-k-alpha.md, раздел 4.14.2б.
Запуск:  python AlphaSoftening.py
"""

import math

ALPHA = 7.2973525693e-3
INV_ALPHA = 1.0 / ALPHA
INV_ALPHA_MZ = 128.95
LAMBDABAR_C = 3.8615926796e-13   # м, приведённая комптоновская электрона
L_PL = 1.616255e-35              # м, планковская длина = размер ячейки
M_E_GEV = 0.51099895000e-3
M_Z_GEV = 91.1876

# softening per e-fold: из однопетлевого бега 1/alpha = 1/alpha_0 - (2/3pi) ln(...)
S_EFOLD = 2.0 * ALPHA / (3.0 * math.pi)


def head(t):
    print()
    print("=" * 78)
    print(t)
    print("=" * 78)


# ------------------------------------------------------------ 1. знак

def sign_check():
    head("1. ЗНАК: ОТ ЧЕГО ЗАВИСИТ И СХОДИТСЯ ЛИ")
    print("""
  Отождествления модели (3.5): E = -du/dt, B = rot u, A = kappa * u.
  Сопоставление плотностей энергии даёт

      eps_0 = rho / kappa^2,      mu_0 = kappa^2 / G,      eps_0 mu_0 = rho/G

  Отсюда постоянная связи выражается через свойства среды:

      alpha = e^2 / (4 pi eps_0 hbar c) = e^2 kappa^2 / (4 pi hbar sqrt(rho G))

  ПРЕМИССА ПУТИ, и она единственная: нормировка kappa при размягчении
  НЕ меняется. Тогда при постоянной rho

      alpha ~ 1 / sqrt(G) ~ 1 / c

  и размягчение (G вниз) даёт рост alpha. ЗНАК СХОДИТСЯ с наблюдаемым бегом.

  Проверка не тавтологична. Если бы фиксированной величиной среды была
  не kappa, а mu_0, вышло бы alpha ~ mu_0 c ~ c, то есть alpha ПАДАЛА бы
  с энергией — путь закрылся бы немедленно. Разделение eps_0 и mu_0 по
  отдельности есть незакрытый пункт T-28, поэтому премисса пути честно
  помечается как премисса, а не как вывод.
""")


# --------------------------------- 2. «1/r против логарифма» — снятие

def resolve_form():
    head("2. МНИМОЕ ПРОТИВОРЕЧИЕ «1/r ПРОТИВ ЛОГАРИФМА»")
    print("""
  Возражение звучит так: вокруг массы диффузия даёт профиль 1/r, а бег
  alpha логарифмичен, значит один и тот же отклик среды двух этих законов
  дать не может.

  Возражение снимается: сравниваются РАЗНЫЕ величины.

    гравитация  —  зависимость от ПОЛОЖЕНИЯ: d<u^2>(r) от расстояния до
                   локализованного источника. Функция Грина стационарной
                   диффузии в трёх измерениях даёт 1/r.

    бег alpha   —  зависимость от МАСШТАБА ЗОНДИРОВАНИЯ: c(k) от волнового
                   числа. Это дисперсионное соотношение, а не профиль поля.

  Это два разных сечения одной среды: одно в координатном пространстве,
  другое в импульсном. Требовать от них одинаковой функциональной формы
  оснований нет, и противоречия между ними тоже нет.

  Сверх того, они лежат в разных областях спектра: профиль 1/r отвечает
  в импульсном представлении 1/k^2, то есть сосредоточен на МАЛЫХ k
  (длинные волны), тогда как бег живёт на БОЛЬШИХ k. Гравитация и бег
  константы связи используют противоположные концы одного спектра.
""")


# ------------------------------ 3. что бег требует от дисперсии

def dispersion_requirement():
    head("3. ЧТО БЕГ ТРЕБУЕТ ОТ ДИСПЕРСИИ СРЕДЫ")
    print("  Из alpha ~ 1/c и однопетлевого бега:")
    print()
    print("      c(k) / c_inf  =  alpha_inf / alpha(k)  =  1 - s * ln(k * lambdabar_C)")
    print()
    print(f"  коэффициент размягчения на е-кратность масштаба:")
    print(f"      s = 2 alpha / 3 pi = {S_EFOLD:.6e}")
    print(f"      на октаву (k вдвое):  s ln2 = {S_EFOLD*math.log(2):.6e}")
    print()
    print("  Проверка на измеренной точке — масштаб Z-бозона:")
    L = math.log(M_Z_GEV / M_E_GEV)
    pred = 1.0 - S_EFOLD * L
    meas = INV_ALPHA_MZ / INV_ALPHA
    print(f"      ln(M_Z/m_e) = {L:.4f}")
    print(f"      c/c_inf предсказано (только электронная петля) = {pred:.4f}")
    print(f"      c/c_inf измерено (полный набор частиц)         = {meas:.4f}")
    print("      выше порогов новых частиц бег быстрее — в среде это значит,")
    print("      что открываются дополнительные каналы размягчения:")
    print(f"      эффективное s по измеренной точке = {(1-meas)/L:.6e}"
          f"  (в {((1-meas)/L)/S_EFOLD:.2f} раза больше)")
    print("""
  Существенно: требуется ЛОГАРИФМ по волновому числу, то есть равный вклад
  с каждой октавы масштаба. Это подпись масштабно-инвариантной среды.""")


# ------------------ 4. насколько среда размягчена на масштабе ячейки

def softening_at_cell():
    head("4. НАСКОЛЬКО СРЕДА РАЗМЯГЧЕНА НА СВОЁМ ЖЕ МАСШТАБЕ ЯЧЕЙКИ")
    L = math.log(LAMBDABAR_C / L_PL)
    d = S_EFOLD * L
    print(f"  ln(lambdabar_C / l_Pl) = {L:.4f}   ({L/math.log(10):.1f} порядков)")
    print(f"  избыток дрожания на масштабе ячейки:")
    print(f"      d<u^2>/<u^2>_L = s * ln(...) = {d:.4f}   то есть {d*100:.1f}%")
    print(f"      c/c_inf = {1-d:.4f},   mu/mu_inf = {(1-d)**2:.4f}")
    print(f"      1/alpha на масштабе ячейки = {INV_ALPHA*(1-d):.2f}")
    print()
    print(f"  где среда расплавилась бы (d<u^2> = <u^2>_L):")
    print(f"      ln(lambdabar_C/r) = 1/s = {1.0/S_EFOLD:.1f}")
    print(f"      это {1.0/S_EFOLD/math.log(10):.0f} порядков — полюс Ландау")
    print("""
  Числа осмысленные и внутренне непротиворечивые: за все 22 порядка от
  комптоновской длины до ячейки среда проходит лишь 8 процентов пути к
  плавлению. Полюс Ландау лежит на 280 порядков ниже ячейки, то есть
  недостижим — ячеистая структура вмешивается несравненно раньше.

  Это ОБЪЯСНЯЕТ, почему путь 5 (полюс на масштабе ячейки) закрылся.
  Он требовал 100% размягчения на ячейке, тогда как бег даёт 8%: промах
  в 1/0.0798 = 12.5 раза. Тот же порядок, что промах пути 5 по 1/alpha.""")
    return d


# ------------------- 5. обычная решёточная дисперсия исключена

def lattice_ruled_out():
    head("5. ОБЫЧНАЯ РЕШЁТОЧНАЯ ДИСПЕРСИЯ ИСКЛЮЧЕНА")
    print("""
  У обычного кристалла дисперсия при малых ka квадратична:

      c(k) / c_0 = 1 - beta (k a)^2

  Проверим, может ли такой закон изобразить логарифм на 22 порядках.
""")
    ratio = L_PL / LAMBDABAR_C
    print(f"  a / lambdabar_C = {ratio:.4e}")
    print(f"  (a / lambdabar_C)^2 = {ratio**2:.4e}")
    print()
    print(f"  Нормируем beta так, чтобы на масштабе ячейки (ka = 1) получалось")
    print(f"  требуемое размягчение {S_EFOLD*math.log(LAMBDABAR_C/L_PL)*100:.1f}%:")
    beta = S_EFOLD * math.log(LAMBDABAR_C / L_PL)
    print(f"      beta = {beta:.4f}")
    print()
    print(f"  {'масштаб':>26} {'логарифм':>14} {'квадрат':>16} {'отношение':>14}")
    for name, r in (("комптоновская длина", LAMBDABAR_C),
                    ("1e-6 от неё", LAMBDABAR_C * 1e-6),
                    ("1e-12 от неё", LAMBDABAR_C * 1e-12),
                    ("ячейка", L_PL)):
        k = 1.0 / r
        lg = S_EFOLD * math.log(LAMBDABAR_C / r)
        sq = beta * (L_PL / r) ** 2
        rel = (lg / sq) if sq > 0 else float("inf")
        print(f"  {name:>26} {lg:>14.4e} {sq:>16.4e} {rel:>14.3e}")
    print("""
  Квадратичный закон даёт размягчение, СОСРЕДОТОЧЕННОЕ у самой ячейки:
  на десять порядков выше неё он отстаёт от логарифма в 3e20 раз, а на
  комптоновской длине — в 1e46 раз. Изобразить равномерный по октавам
  вклад он не может в принципе: вся его величина набирается в последней
  октаве перед ячейкой.

  ВЫВОД, и он сильный: среда модели НЕ МОЖЕТ быть обычным кристаллом с
  дебаевской дисперсией. Логарифмический бег требует масштабной
  инвариантности, то есть КРИТИЧЕСКОЙ среды. У модели такая среда и
  постулирована — предельно заклиненная (маргинально заклиненная)
  аморфная упаковка (1.5), а маргинальное заклинивание есть критическая
  точка с аномальной фононной дисперсией.

  Путь 10 тем самым связывает alpha не с чем-то новым, а с УЖЕ ПРИНЯТЫМ
  постулатом о структуре среды.""")


# --------------------------------- 6. обращение и требуемая точность

def inversion():
    head("6. ОБРАЩЕНИЕ: alpha ИЗ КОЭФФИЦИЕНТА РАЗМЯГЧЕНИЯ")
    print("      s = 2 alpha / (3 pi)      =>      alpha = 3 pi s / 2")
    print()
    print(f"  требуемое s = {S_EFOLD:.8e}")
    print("  (значение относится к диапазону, где вклад даёт только электрон,")
    print("   между комптоновской длиной электрона и мюона; выше открываются")
    print("   дополнительные каналы, и эффективное s растёт)")
    print(f"  обратно:  alpha = {3*math.pi*S_EFOLD/2:.8e},  1/alpha = "
          f"{1.0/(3*math.pi*S_EFOLD/2):.4f}   (контроль тождества)")
    print()
    print("  Чувствительность: относительная ошибка переносится один к одному,")
    print("  d(alpha)/alpha = d(s)/s. Отсюда требования к расчёту s:")
    print()
    print(f"  {'нужная точность 1/alpha':>26} {'допустимая ошибка s':>22}")
    for tol in (0.10, 0.01, 0.001):
        print(f"  {tol*100:>24.1f}% {tol*100:>21.1f}%")
    print("""
  Это существенно мягче, чем кажется. Чтобы попасть в 137.0 с точностью
  10 процентов, достаточно вычислить долю размягчения на е-кратность
  масштаба с точностью 10 процентов. Для расчёта фононной дисперсии
  заклиненной упаковки это выполнимая задача, а не безнадёжная.

  И проверка на подгонку встроена: s есть ОДНО число, а проверяемых
  следствий два — величина alpha и логарифмическая форма бега. Выходов
  больше, чем входов, то есть методологические ворота 4.14.7 путь проходит.""")


# ------------------------------------------ 7. что осталось вычислить

def whats_left():
    head("7. ЧТО ОСТАЛОСЬ ВЫЧИСЛИТЬ")
    print("""
  Задача сведена к одному расчёту по физике твёрдого тела, и он
  формулируется без единого упоминания квантовой электродинамики:

      Дана маргинально заклиненная аморфная упаковка. Найти долю s,
      на которую падает скорость поперечной волны при увеличении
      волнового числа в e раз.

  Три подзадачи:

  (а) дисперсия c(k) маргинально заклиненной упаковки. Известно, что у
      таких систем она аномальна (бозонный пик, избыток мягких мод), но
      нужен именно коэффициент при логарифме, а не факт аномальности.

  (б) диапазон логарифмичности. Он обязан начинаться на комптоновской
      длине солитона и продолжаться до ячейки; за его пределами закон
      обязан меняться, иначе бег не остановился бы на alpha(0).

  (в) связь с порогом Линдемана. Величина <u^2>_L входит и сюда, и в
      коэффициент гравитации (T-4). Она обязана быть ОДНОЙ И ТОЙ ЖЕ —
      это перекрёстная проверка, связывающая T-6 и T-4 одним числом.

  Пункт (в) — главное приобретение пути. Он превращает две независимые
  критические задачи в одну с двумя проверками.""")


def report():
    sign_check()
    resolve_form()
    dispersion_requirement()
    softening_at_cell()
    lattice_ruled_out()
    inversion()
    whats_left()

    head("СВОДКА ПО ПУТИ 10")
    print(f"""
  ЧТО ПРОВЕРЕНО И СОШЛОСЬ

  1. Знак. alpha ~ 1/c при фиксированной нормировке kappa: размягчение
     даёт рост alpha с энергией. Совпадает с наблюдаемым бегом. Могло
     не совпасть — при другом разделении eps_0 и mu_0 знак обратный.

  2. Возражение о форме СНЯТО. Профиль 1/r (гравитация) — зависимость от
     положения; логарифм (бег) — зависимость от масштаба зондирования.
     Это разные сечения одной среды, а не противоречие. Более того, они
     лежат на противоположных концах спектра: 1/r отвечает малым k,
     бег — большим.

  3. Величины осмысленны. За 22 порядка от комптоновской длины до ячейки
     среда проходит {S_EFOLD*math.log(LAMBDABAR_C/L_PL)*100:.1f}% пути к плавлению; полюс Ландау лежит
     на 280 порядков ниже ячейки и потому недостижим.

  ЧТО ПУТЬ ИСКЛЮЧАЕТ

  4. Обычная дебаевская дисперсия c(k) = c_0(1 - beta (ka)^2) логарифм
     изобразить не может: вся её величина набирается в последней октаве
     перед ячейкой, а на десять порядков выше она отстаёт от логарифма
     в 3e20 раз. Среда ОБЯЗАНА
     быть критической — и она такой в модели и постулирована (1.5).

  ЧТО ОСТАЛОСЬ

  5. Одно число: доля размягчения s на е-кратность волнового числа.
     alpha = 3 pi s / 2. Требуемая точность 10% на s даёт 10% на 1/alpha.

  6. Перекрёстная проверка: порог Линдемана <u^2>_L входит и в s, и в
     коэффициент гравитации (T-4). Одно число, две проверки.
""")


if __name__ == "__main__":
    report()
