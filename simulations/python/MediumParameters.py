"""
Параметры среды: что данные определяют, а что остаётся свободным (пункт T-40).

Постановка: физика среды неизвестна, но неизвестна не вся. Наблюдаемые
фиксируют не отдельные величины (плотность, шаг упаковки, модуль), а их
КОМБИНАЦИИ. Модуль выясняет, какие именно, и куда честно относится
остаток незнания.

Разделы:
  1. инвентарь параметров и счёт безразмерных групп
  2. что фиксируется точно: скорость сдвиговой волны
  3. что фиксируется через hbar
  4. что фиксируется через G: единственная комбинация, которую видит гравитация
  5. ГЛАВНЫЙ РЕЗУЛЬТАТ: шаг упаковки против планковской длины
  6. устойчивость: как сильно незнание портит предсказания
  7. плоские направления: чего данные не определяют вовсе

Расчёты к подглаве theory/01-8-parametry-sredy.md.
Запуск:  python MediumParameters.py
"""

import math

G_N = 6.67430e-11
HBAR = 1.054571817e-34
C = 2.99792458e8
ALPHA = 7.2973525693e-3
LAMBDABAR_C = 3.8615926796e-13

L_PL = math.sqrt(HBAR * G_N / C**3)
S_EFOLD = 2.0 * ALPHA / (3.0 * math.pi)


def head(t):
    print()
    print("=" * 78)
    print(t)
    print("=" * 78)


# --------------------------------------------------- 1. инвентарь

def inventory():
    head("1. ИНВЕНТАРЬ ПАРАМЕТРОВ И СЧЁТ БЕЗРАЗМЕРНЫХ ГРУПП")
    print(f"  {'параметр':>26} {'размерность':>16} {'смысл':>30}")
    for a, b, c in (
        ("rho", "M/L^3", "плотность среды"),
        ("mu = G_сдвиг", "M/(L T^2)", "модуль сдвига"),
        ("K", "M/(L T^2)", "объёмный модуль"),
        ("a", "L", "размер самой ячейки"),
        ("d", "L", "ШАГ упаковки (между ячейками)"),
        ("<u^2>_L", "L^2", "линдемановский порог"),
        ("ell", "L", "длина свободного пробега фонона"),
    ):
        print(f"  {a:>26} {b:>16} {c:>30}")
    n, dims = 7, 3
    print()
    print(f"  параметров: {n}, базовых размерностей: {dims}")
    print(f"  => безразмерных групп: {n} - {dims} = {n-dims}")
    print("""
  Три размерные комбинации уходят в выбор системы единиц и физического
  содержания не несут. Остаются ЧЕТЫРЕ безразмерных числа, и только они
  могут что-то предсказывать:

      eps      = mu / K              параметр несжимаемости
      delta    = d / a               шаг упаковки к размеру ячейки
      lambda_L = <u^2>_L / d^2       линдемановский параметр
      L_mfp    = ell / d             пробег в шагах упаковки

  Существенно, что РАЗМЕР ЯЧЕЙКИ a входит только в delta. Ни одна
  наблюдаемая величина от него отдельно не зависит: спектр обрезается на
  ШАГЕ упаковки d, а не на размере ячейки. Устройство ячейки становится
  наблюдаемым лишь выше этого обрезания.
""")


# --------------------------------------- 2. что фиксируется точно

def fixed_exactly():
    head("2. ЧТО ФИКСИРУЕТСЯ ТОЧНО")
    print("""
      c = sqrt(mu / rho) = 2.998e8 м/с

  Это единственная комбинация, известная без всяких допущений. Она
  связывает mu и rho, но ни ту, ни другую по отдельности не задаёт.
""")


# ----------------------------------------- 3. что фиксируется через hbar

def via_hbar():
    head("3. ЧТО ФИКСИРУЕТСЯ ЧЕРЕЗ hbar")
    print("""
  Действие имеет размерность M L^2 / T. Из параметров среды такую
  размерность даёт единственная комбинация:

      hbar = eta * rho * c * d^4        (eta — безразмерное число порядка 1)

  Отсюда rho = hbar / (eta c d^4): плотность НЕ независима, она задаётся
  шагом упаковки. Это и есть ответ на вопрос, связаны ли шаг упаковки и
  упругие свойства: связаны жёстко, через hbar.
""")
    for d_over_lpl in (1.0, 10.0, 1e3, 1e5):
        d = d_over_lpl * L_PL
        rho = HBAR / (C * d**4)
        mu = rho * C**2
        print(f"    d = {d_over_lpl:>8.0e} l_Pl:   rho = {rho:.3e} кг/м^3,"
              f"   mu = {mu:.3e} Па")
    print("""
  Видно, насколько жёсткая связь: шаг упаковки вчетверо входит в плотность.
  Сдвиг d на пять порядков роняет плотность на двадцать — ровно то
  соотношение, которое встретилось при сверке заклинивания.
""")


# ------------------------------ 4. что фиксируется через G

def via_G():
    head("4. ЧТО ФИКСИРУЕТСЯ ЧЕРЕЗ G: КОМБИНАЦИЯ, КОТОРУЮ ВИДИТ ГРАВИТАЦИЯ")
    print("""
  Механизм T-4: солитон накачивает дрожание с темпом S = s_0 * M,
  дрожание диффундирует с коэффициентом D, размягчение идёт по
  линдемановскому порогу. Стационарный профиль:

      d<u^2>(r) = S / (4 pi D r)

  Приравнивая требуемому d<u^2>/<u^2>_L = 2GM/(r c^2):

      G = s_0 c^2 / (8 pi D <u^2>_L)

  Подставляя D = c * ell / 3 (диффузия фононов):

      G = 3 s_0 c / (8 pi * ell * <u^2>_L)

  ВАЖНО: гравитация видит ПРОИЗВЕДЕНИЕ ell * <u^2>_L, а не каждую
  величину порознь. Это и есть та совместная величина, в которую честно
  относится незнание:

      Lambda_грав = ell * <u^2>_L
""")


# ------------------------- 5. главный результат: d против l_Pl

def main_result():
    head("5. ГЛАВНЫЙ РЕЗУЛЬТАТ: ШАГ УПАКОВКИ ПРОТИВ ПЛАНКОВСКОЙ ДЛИНЫ")
    print("""
  Соберём всё вместе. Пусть s_0 = sigma * c * d / rho (единственная
  комбинация нужной размерности), ell = L_mfp * d, <u^2>_L = lambda_L * d^2,
  и rho = hbar/(eta c d^4). Тогда

      G = 3 sigma eta c^3 d^2 / (8 pi lambda_L L_mfp hbar)

  а поскольку G hbar / c^3 = l_Pl^2, получается соотношение, в котором
  всё незнание собрано в ОДНО число:

      (d / l_Pl)^2 = (8 pi / 3) * Theta,      Theta = lambda_L * L_mfp / (sigma * eta)
""")
    print(f"  {'Theta':>14} {'d / l_Pl':>14} {'смысл':>34}")
    for th, note in ((1e-4, "все числа малы"),
                     (1e-2, ""),
                     (1.0, "ВСЕ ЧИСЛА ПОРЯДКА ЕДИНИЦЫ"),
                     (1e2, ""),
                     (1e4, "все числа велики")):
        d_ratio = math.sqrt(8 * math.pi / 3 * th)
        print(f"  {th:>14.0e} {d_ratio:>14.3f} {note:>34}")
    d_nat = math.sqrt(8 * math.pi / 3)
    print()
    print(f"  При Theta = 1:  d = {d_nat:.3f} * l_Pl")
    print("""
  ЭТО СУЩЕСТВЕННО. Если все безразмерные числа среды порядка единицы —
  линдемановский параметр, пробег в шагах упаковки, темп накачки,
  нормировка hbar, — то шаг упаковки ПЛАНКОВСКИЙ с точностью до
  множителя три. Ожидание d ~ l_Pl не постулируется, а ВЫВОДИТСЯ из
  требования Theta ~ 1.

  И обратно: если расчёт когда-нибудь потребует другого d, это скажет
  ровно одно — какое из четырёх чисел не порядка единицы.
""")
    return d_nat


# --------------------------- 6. устойчивость предсказаний

def robustness(d_nat):
    head("6. УСТОЙЧИВОСТЬ: НАСКОЛЬКО НЕЗНАНИЕ ПОРТИТ ПРЕДСКАЗАНИЯ")
    print("""
  Незнание Theta входит в наблюдаемые только через логарифм, потому что
  все спектральные величины считаются по числу октав между обрезаниями:

      delta_max = s * ln(lambdabar_C / d),    d = l_Pl sqrt(8 pi Theta / 3)
      =>  delta_max = s * [ ln(lambdabar_C/l_Pl) - (1/2) ln(8 pi Theta/3) ]
""")
    print(f"  {'Theta':>14} {'d/l_Pl':>12} {'ln(lC/d)':>12} {'delta_max':>12} {'сдвиг':>10}")
    base = None
    for th in (1e-6, 1e-3, 1.0, 1e3, 1e6):
        d = L_PL * math.sqrt(8 * math.pi / 3 * th)
        L = math.log(LAMBDABAR_C / d)
        dm = S_EFOLD * L
        if base is None:
            base = dm
        print(f"  {th:>14.0e} {d/L_PL:>12.3g} {L:>12.3f} {dm:>12.5f}"
              f" {(dm/base-1)*100:>9.1f}%")
    dlog = S_EFOLD / 2.0
    print()
    print(f"  чувствительность:  d(delta_max)/d(ln Theta) = -s/2 = -{dlog:.2e}")
    need = 0.10 * S_EFOLD * math.log(LAMBDABAR_C / L_PL) / dlog
    print(f"  чтобы сдвинуть delta_max на 10%, Theta должна измениться")
    print(f"  на exp({need:.1f}) = {math.exp(need):.1e} раз")
    print("""
  ВЫВОД, и он ободряющий: Theta может быть неизвестна на ЧЕТЫРЕ ПОРЯДКА,
  а предсказание сдвинется на десять процентов. Логарифм сжимает незнание.

  Это и оправдывает подход: работать не с отдельными параметрами среды,
  которых мы не знаем, а с их комбинацией, к которой наблюдаемые почти
  нечувствительны.
""")


# ------------------------------ 7. плоские направления

def flat_directions():
    head("7. ПЛОСКИЕ НАПРАВЛЕНИЯ: ЧЕГО ДАННЫЕ НЕ ОПРЕДЕЛЯЮТ ВОВСЕ")
    print(f"  {'величина':>34} {'статус':>40}")
    for a, b in (
        ("c = sqrt(mu/rho)", "ОПРЕДЕЛЕНА точно"),
        ("rho при заданном d", "ОПРЕДЕЛЕНА через hbar"),
        ("mu при заданном d", "ОПРЕДЕЛЕНА (= rho c^2)"),
        ("Theta = lambda_L L_mfp/(sigma eta)", "ОПРЕДЕЛЕНА через G и d"),
        ("eps = mu/K", "ОГРАНИЧЕНА сверху: -> 0 при заклинивании"),
        ("lambda_L и L_mfp по отдельности", "НЕ ОПРЕДЕЛЕНЫ, только произведение"),
        ("sigma и eta по отдельности", "НЕ ОПРЕДЕЛЕНЫ, только произведение"),
        ("a — размер самой ячейки", "НЕ ОПРЕДЕЛЁН ВООБЩЕ"),
        ("delta = d/a", "НЕ ОПРЕДЕЛЁН ВООБЩЕ"),
        ("что между ячейками", "НЕ ОПРЕДЕЛЕНО ВООБЩЕ"),
    )        :
        print(f"  {a:>34} {b:>40}")
    print("""
  Последние три строки — честная граница модели. Устройство ячейки в
  наблюдаемые НЕ ВХОДИТ, и это не пробел, а результат: спектр обрезается
  на ШАГЕ упаковки, поэтому всё, что мельче шага, наблюдениям недоступно.

  Практическое следствие для T-40: вопрос «что такое ячейка» не является
  препятствием для остальных расчётов. Его можно отложить, не блокируя
  ни путь 10 к alpha, ни коэффициент гравитации. Достаточно оперировать
  шагом упаковки d и совместной величиной Theta.
""")


def report():
    inventory()
    fixed_exactly()
    via_hbar()
    via_G()
    d_nat = main_result()
    robustness(d_nat)
    flat_directions()

    head("СВОДКА")
    print(f"""
  1. Параметров среды семь, безразмерных групп четыре: eps = mu/K,
     delta = d/a, lambda_L = <u^2>_L/d^2, L_mfp = ell/d.

  2. Шаг упаковки d и упругие свойства СВЯЗАНЫ ЖЁСТКО, через hbar:
     rho = hbar/(eta c d^4). Выбор шага задаёт плотность, а с ней и
     модуль mu = rho c^2. Догадка верна: это не независимые величины.

  3. Гравитация видит не отдельные величины, а ПРОИЗВЕДЕНИЕ ell * <u^2>_L.
     Это и есть совместная величина, в которую относится незнание.

  4. ГЛАВНОЕ: всё незнание собирается в ОДНО число

         (d/l_Pl)^2 = (8 pi/3) * Theta,   Theta = lambda_L L_mfp/(sigma eta)

     При Theta = 1 выходит d = {d_nat:.2f} l_Pl. То есть планковский шаг
     упаковки не постулируется, а СЛЕДУЕТ из требования, чтобы все
     безразмерные числа среды были порядка единицы.

  5. Предсказания устойчивы: Theta входит только логарифмически.
     Незнание на четыре порядка сдвигает delta_max на десять процентов.

  6. Устройство ячейки (a, что между ячейками) в наблюдаемые НЕ ВХОДИТ:
     спектр обрезается на шаге упаковки. T-40 можно отложить, не блокируя
     остальные расчёты.
""")


if __name__ == "__main__":
    report()
