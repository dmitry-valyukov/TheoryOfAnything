"""Защита от радиационных поправок (T-1): что защищает, что нет.

Возражение Коллинза и др. (2004): в теории с обрезанием Lambda оператор
нарушения ЛИ размерности 6 порождает в петле оператор размерности 4 с
коэффициентом ~alpha/pi, а не (E/Lambda)^2. Оператор размерности 4 —
это delta c/c между СЕКТОРАМИ: разная предельная скорость у разных
полей (электрон против фотона и т. п.). Наблюдательные пределы 1e-19..1e-23.

Здесь разбирается, что из уже установленного в модели на этот довод
отвечает, а что нет — по трём линиям.

  1. ГИПЕРОДНОРОДНОСТЬ (T-14) НЕ ЗАЩИЩАЕТ. Она подавляет S(k) при
     k -> 0, а петлевой интеграл доминируется k ~ Lambda, где S(k) ~ 1.
     Гипероднородность лечит рассеяние на беспорядке (T-14), не петли.
     Проверка: интеграл int S(k) k^3 dk для пуассоновского и
     гипероднородного S(k) — доля от k > Lambda/10.

  2. ЧТО ДЕЛАЕТ ОДНА СРЕДА. Ключевая структурная посылка Коллинза —
     секторов НЕСКОЛЬКО, с независимыми UV-структурами; delta c между
     ними ничем не защищена. В модели И фотон, И материя — возбуждения
     ОДНОЙ поперечной ветви ОДНОЙ среды. Тогда:
       (a) есть ровно одна предельная скорость c_T на всю физику по
           построению — оператора delta c/c между секторами не
           существует, ему неоткуда взяться: нет второго c в UV;
       (b) остаётся ЛН ВНУТРИ ветви: анизотропия c(k^) и дисперсия
           c(|k|) — операторы dim-4 anизотропии и dim-6 дисперсии.
     Проверка (a) на минимайзерах: солитон движется — его скорость
     ограничена c_T той же среды (это и есть релятивистская кинематика
     Лоренца — Пуанкаре для дефектов в упругой среде, «лоренцево
     сокращение» дислокаций). (b) — считается ниже.

  3. АНИЗОТРОПИЯ ВНУТРИ ВЕТВИ: изотропия аморфной упаковки. Оператор
     dim-4 внутри одной ветви — это c(k^) != const (зависимость от
     направления). Для аморфной среды средняя анизотропия нулевая
     ТОЖДЕСТВЕННО (нет выделенных осей), а флуктуационная — это и есть
     рассеяние, подавленное гипероднородностью. Дисперсия c(|k|) — dim-6,
     подавлена (k d)^2, и петли её в dim-4 НЕ переводят внутри одной
     ветви: изотропный оператор dim-4 — это перенормировка самого c_T,
     единого для всех, то есть ненаблюдаемая величина.

     Численно: спектр поперечных мод случайной (аморфной) сетки пружин —
     изотропия c по направлениям и расщепление двух поперечных
     поляризаций при k -> 1/d.

Вердикт: то, чего боится T-1, — dim-4 delta c/c между секторами — в модели
не имеет носителя: сектор один. Остаток ЛН — dim-6 дисперсия одной ветви,
подавленная (E d)^2 без петлевого усиления в dim-4 (перенормируется
только общее c). Это не доказательство ЛИ модели, а ТОЧНАЯ ЛОКАЛИЗАЦИЯ
того, что в ней остаётся проверять: изотропия и единственность
поперечной ветви вплоть до k ~ 1/d, плюс мода давления (продольная
ветвь = связь, T-12) как второй возможный носитель c.

Запуск: python LorentzProtection.py
"""

