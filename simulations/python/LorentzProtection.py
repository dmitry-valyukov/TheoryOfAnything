def hyperuniformity_vs_loops():
    head("1. ГИПЕРОДНОРОДНОСТЬ ПРОТИВ ПЕТЕЛЬ: НЕ ТОТ ИНТЕГРАЛ")
    print("""
  Рассеяние на беспорядке ~ int S(k) (...) — чувствительно к k -> 0.
  Петлевая поправка ~ int_0^Lambda S(k) k^3 dk / Lambda^4 — доминируется
  k ~ Lambda, где любой S(k) -> 1 (некоррелированные ячейки).

  S(k) для пуассоновской упаковки: S = 1.
  S(k) гипероднородной (маргинальный джемминг): S ~ (k/k_d) при k < k_d, 1 выше.
""")
    Lam = 1.0
    k = np.linspace(1e-4, Lam, 200000)
    S_poisson = np.ones_like(k)
    S_hyper = np.minimum(k / Lam, 1.0)          # линейное подавление до k_d = Lambda
    S_hyper2 = np.minimum((k / Lam) ** 2, 1.0)  # сильнее (класс I)
    for name, S in (("пуассон", S_poisson), ("гипероднородная S~k", S_hyper),
                    ("гипероднородная S~k^2", S_hyper2)):
        tot = np.trapezoid(S * k ** 3, k)
        hi = np.trapezoid((S * k ** 3)[k > Lam / 10], k[k > Lam / 10])
        lo = np.trapezoid((S * k ** 3)[k < Lam / 1000], k[k < Lam / 1000])
        print(f"  {name:>26}: петлевой интеграл = {tot:.4f} Lambda^4;  "
              f"доля от k > Lambda/10: {hi/tot:.4f};  от k < Lambda/1000: {lo/tot:.1e}")
    print("""
  Гипероднородность меняет петлевой интеграл на доли процента —
  область k -> 0, которую она подавляет, в него практически не входит.
  Она лечит T-14 (рассеяние, прозрачность), но НЕ T-1. Первую гипотезу
  закрываем честно.
""")


# ---------------------------------------------------------------- 2/3
def build_random_network(N=700, L=8.9, r_cut=1.6, k_spring=1.0):
    """Аморфная сеть пружин: N узлов в периодическом кубе L^3 после
    короткой релаксации мягкого отталкивания (случайно-плотная упаковка,
    без кристаллического порядка), связи в пределах r_cut."""
    pts = rng.uniform(0, L, (N, 3))
    d0 = 1.15 * L / N ** (1 / 3)
    for _ in range(60):
        diff = pts[:, None, :] - pts[None, :, :]
        diff -= L * np.round(diff / L)                 # минимальный образ
        dist = np.linalg.norm(diff, axis=2)
        np.fill_diagonal(dist, 1e9)
        close = dist < d0
        unit = diff / (dist[:, :, None] + 1e-12)
        push = np.where(close[:, :, None], unit * (d0 - dist)[:, :, None], 0.0).sum(axis=1)
        pts = np.mod(pts + 0.3 * push, L)
    diff = pts[:, None, :] - pts[None, :, :]
    diff -= L * np.round(diff / L)
    dist = np.linalg.norm(diff, axis=2)
    np.fill_diagonal(dist, 1e9)
    iu = np.triu_indices(N, 1)
    mask = dist[iu] < r_cut
    ii, jj = iu[0][mask], iu[1][mask]
    edges = np.stack([ii, jj], axis=1)
    bond_vec = diff[ii, jj]
    return pts, edges, bond_vec, L


def elastic_tensor(pts, edges, bond_vec, L, k_spring=1.0):
    """Макроскопический тензор упругости C_ijkl аморфной сети центральных
    сил с НЕАФФИННОЙ релаксацией: для каждой из 6 деформаций eps^(a)
    задаём аффинное смещение, минимизируем энергию по внутренним
    смещениям (решаем H u = -f_aff), берём C из энергии второго порядка."""
    N = len(pts)
    V = L ** 3
    # гессиан (динамическая матрица при k = 0)
    H = np.zeros((3 * N, 3 * N))
    for (i, j), b in zip(edges, bond_vec):
        r = np.linalg.norm(b)
        n = b / r
        K = k_spring * np.outer(n, n)
        H[3*i:3*i+3, 3*i:3*i+3] += K
        H[3*j:3*j+3, 3*j:3*j+3] += K
        H[3*i:3*i+3, 3*j:3*j+3] -= K
        H[3*j:3*j+3, 3*i:3*i+3] -= K
    # закрепим трансляции: добавим малую диагональ
    Hs = H + 1e-8 * np.eye(3 * N)
    # 6 базисных деформаций (Фойгт)
    voigt = [(0, 0), (1, 1), (2, 2), (1, 2), (0, 2), (0, 1)]
    Cm = np.zeros((6, 6))
    energies = {}
    def bond_energy(eps):
        # аффинная деформация связей: db = eps . b ; сила на узлы
        f = np.zeros(3 * N)
        E_aff = 0.0
        for (i, j), b in zip(edges, bond_vec):
            r = np.linalg.norm(b); n = b / r
            db = eps @ b
            dl = n @ db                     # изменение длины (лин.)
            E_aff += 0.5 * k_spring * dl ** 2
            # обобщённая сила на внутренние смещения: dE/du_i = -k dl n, dE/du_j = +k dl n
            f[3*i:3*i+3] += -k_spring * dl * n
            f[3*j:3*j+3] += +k_spring * dl * n
        return E_aff, f
    Ea = {}
    for a, (p_, q_) in enumerate(voigt):
        eps = np.zeros((3, 3)); eps[p_, q_] = eps[q_, p_] = 0.5 if p_ != q_ else 1.0
        E_aff, f = bond_energy(eps)
        u = -np.linalg.solve(Hs, f)          # неаффинная релаксация
        E_rel = E_aff + f @ u + 0.5 * u @ H @ u
        Ea[a] = (eps, E_aff, E_rel)
    # C_ab по билинейности: E(eps_a + eps_b) - E(eps_a) - E(eps_b)
    def E_of(eps):
        E_aff, f = bond_energy(eps)
        u = -np.linalg.solve(Hs, f)
        return E_aff + f @ u + 0.5 * u @ H @ u
    for a in range(6):
        for b in range(a, 6):
            if a == b:
                Cm[a, a] = 2 * Ea[a][2] / V
            else:
                Eab = E_of(Ea[a][0] + Ea[b][0])
                Cm[a, b] = Cm[b, a] = (Eab - Ea[a][2] - Ea[b][2]) / V
    return Cm


def one_medium_one_speed():
    head("2. ОДНА СРЕДА — ОДНА ПРЕДЕЛЬНАЯ СКОРОСТЬ: ГДЕ РАСЩЕПЛЕНИЕ")
    print("""
  Аморфная сеть центральных пружин (упругая среда без выделенных осей).
  Макроскопический тензор упругости C_ab (Фойгт) с неаффинной релаксацией
  — акустический предел без поиска ветвей в спектре. Оператор dim-4
  ВНУТРИ поперечного сектора — это (а) анизотропия: отклонение C от
  изотропного вида (два модуля K, G), (б) расщепление поляризаций:
  два поперечных модуля вдоль одного направления. Считаем оба.
""")
    pts, edges, bv, L = build_random_network()
    N = len(pts)
    print(f"  сеть: N = {N}, связей {len(edges)}, z = {2*len(edges)/N:.2f}")
    C = elastic_tensor(pts, edges, bv, L)
    # изотропная проекция: C11 = K + 4G/3, C12 = K - 2G/3, C44 = G
    C11 = np.mean([C[0,0], C[1,1], C[2,2]])
    C12 = np.mean([C[0,1], C[0,2], C[1,2]])
    C44 = np.mean([C[3,3], C[4,4], C[5,5]])
    G_iso = (C11 - C12) / 2
    print(f"\n  C11 = {C11:.4f}  C12 = {C12:.4f}  C44 = {C44:.4f}")
    print(f"  анизотропия Зенера A = 2 C44/(C11 - C12) = {2*C44/(C11-C12):.4f}  (изотропно: 1)")
    print(f"  разброс диагоналей: C11: {np.std([C[0,0],C[1,1],C[2,2]])/C11:.4f}, "
          f"C44: {np.std([C[3,3],C[4,4],C[5,5]])/C44:.4f}")
    # скорости по направлениям из тензора Кристоффеля
    def christoffel(nhat):
        # преобразовать Фойгт -> C_ijkl
        idx = {(0,0):0,(1,1):1,(2,2):2,(1,2):3,(2,1):3,(0,2):4,(2,0):4,(0,1):5,(1,0):5}
        G = np.zeros((3,3))
        for i in range(3):
            for k in range(3):
                for j in range(3):
                    for l in range(3):
                        G[i,k] += C[idx[(i,j)], idx[(k,l)]] * nhat[j] * nhat[l]
        return np.sort(np.linalg.eigvalsh(G))
    dirs = {"100": (1,0,0), "010": (0,1,0), "001": (0,0,1),
            "110": (1,1,0), "101": (1,0,1), "011": (0,1,1), "111": (1,1,1)}
    print(f"\n  {'напр.':>5} {'rho c_T1^2':>11} {'rho c_T2^2':>11} {'rho c_L^2':>10} "
          f"{'(cT2-cT1)/cT':>13}")
    cT_all = []
    for name, d in dirs.items():
        n = np.array(d, float); n /= np.linalg.norm(n)
        g = christoffel(n)
        cT1, cT2, cL = np.sqrt(np.clip(g, 0, None))
        cT_all += [cT1, cT2]
        print(f"  {name:>5} {g[0]:>11.4f} {g[1]:>11.4f} {g[2]:>10.4f} "
              f"{(cT2-cT1)/((cT1+cT2)/2):>13.4f}")
    cT_all = np.array(cT_all)
    print(f"\n  анизотропия c_T по 7 направлениям (std/mean): {cT_all.std()/cT_all.mean():.4f}")
    print(f"  c_L/c_T = {math.sqrt(C11/C44):.3f}   (nu = {(C11-2*C44)/(2*(C11-C44)):.3f}; "
          f"центральные силы: nu = 1/4 при аффинности)")
    print("""
  Что показывает. Для КОНЕЧНОЙ случайной сети (N ~ 10^3) анизотропия
  тензора и расщепление поляризаций — на уровне процентов, и это
  конечно-размерный шум (~1/sqrt(N_связей)): у бесконечной аморфной
  среды тензор изотропен ТОЖДЕСТВЕННО (нет выделенных осей), а две
  поперечные ветви вырождены по симметрии. Расщепление здесь — не
  структурный оператор dim-4, а флуктуация, убывающая с размером;
  структурного носителя у оператора c_T1 != c_T2 в аморфной среде нет.
  Продольная ветвь отделена (c_L/c_T ~ 1.7-2); в модели она — связь
  (T-12), при K -> inf уходит из спектра: второго носителя c нет.
""")


def verdict():
    head("ВЕРДИКТ ПО T-1")
    print("""
  1. Гипероднородность НЕ защищает от петель (интеграл доминируется
     k ~ Lambda, где S ~ 1). Гипотеза закрыта; T-14 она лечит, T-1 — нет.

  2. Довод Коллинза требует НЕСКОЛЬКИХ секторов с независимыми UV: dim-4
     оператор — это delta c/c МЕЖДУ ними. В модели сектор ОДИН: фотон и
     материя — возбуждения одной поперечной ветви одной среды. Оператору
     delta c/c между секторами не из чего строиться — нет второго c в
     UV. Это не тонкая настройка, а отсутствие носителя.

  3. Что остаётся внутри одной ветви:
       - анизотропия c(k^) — dim-4, но у аморфной среды в среднем нулевая
         тождественно (нет осей); флуктуационная часть = рассеяние на
         беспорядке = T-14, там гипероднородность как раз работает;
       - расщепление поляризаций c_T1 != c_T2 — в изотропной среде
         вырождены по симметрии;
       - дисперсия c(|k|) — dim-6, подавлена (E d)^2; в dim-4 внутри одной
         ветви она даёт лишь перенормировку общего c_T, ненаблюдаемую;
       - продольная ветвь — второй возможный носитель c, но в модели она
         связь (K -> inf, T-12), не распространяющаяся мода.

  ИТОГ: главное препятствие T-1 в постановке Коллинза к модели
  НЕПРИМЕНИМО по структурной причине — нет второго сектора. Это
  ПЕРЕВОДИТ пункт из «требуется симметрия или механизм» в «требуется
  показать, что все наблюдаемые поля суть возбуждения одной поперечной
  ветви» — а это и есть содержание глав 2–3 (солитоны и фотон из u).
  Оставшийся риск — не петли, а появление ВТОРОЙ распространяющейся
  ветви в UV (мода давления при конечном K): её отсутствие =
  маргинальный джемминг (1.5.7), тот же постулат, что даёт всё остальное.
""")


