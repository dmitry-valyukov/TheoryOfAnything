def exponent_budget():
    head("7. БЮДЖЕТ ПОКАЗАТЕЛЯ: ЧТО ОБЯЗАНА ДАТЬ ЛЮБАЯ ТОПОЛОГИЧЕСКАЯ НУМЕРАЦИЯ")
    print(f"  требуется:  m_mu/m_e = {R_MU:.3f},   m_tau/m_e = {R_TAU:.2f}")
    print()
    print(f"  {'нумерация':>34} {'индексы 1,2,3':>18} {'p (по mu)':>10} {'p (по tau)':>11} {'расх.':>7}")

    def budget(name, idx):
        i1, i2, i3 = idx
        p_mu = math.log(R_MU) / math.log(i2 / i1)
        p_tau = math.log(R_TAU) / math.log(i3 / i1)
        d = abs(p_mu - p_tau) / max(p_mu, p_tau)
        print(f"  {name:>34} {str(idx):>18} {p_mu:>10.3f} {p_tau:>11.3f} {d:>6.1%}")
        return p_mu, p_tau

    budget("порядковый номер n", (1, 2, 3))
    budget("индекс Хопфа H = 2 n^2", (2, 8, 18))
    budget("H = pq по узлам (2,3),(2,5),(2,7)", (6, 10, 14))
    budget("число радиальных узлов+1", (1, 2, 3))
    print("""
  Показатель, требуемый от нумерации порядковым номером, около 7.6; от
  нумерации индексом Хопфа — ровно вдвое меньше, около 3.8. Это НЕ новая
  физика, а замена переменной (H ~ n^2), и внутренняя несогласованность
  между mu и tau от неё не меняется — те же ~4 %.
""")
    print(f"  {'семейство солитонов':>44} {'E ~ Q^p':>9} {'n=2':>10} {'n=3':>12}")
    fams = [
        ("хопфион, оценка Вакуленко — Капитанского", 0.75),
        ("скирмион E ~ B", 1.0),
        ("Q-шар тонкостенный", 1.0),
        ("Q-шар толстостенный", 5.0 / 6.0),
        ("радиальные узлы (посчитано, T-7)", 4.0),
        ("ТРЕБУЕТСЯ при нумерации индексом Хопфа", math.log(R_MU) / math.log(4.0)),
        ("ТРЕБУЕТСЯ при нумерации номером", math.log(R_MU) / math.log(2.0)),
    ]
    for name, p in fams:
        print(f"  {name:>44} {p:>9.3f} {2**p:>10.3f} {3**p:>12.1f}")
    print("""
  Вывод раздела. Все известные семейства дают показатель в полосе
  0.75...1, единственное исключение — радиальные узлы с 4, и оно уже
  закрыто по другой причине (T-7). Требуемое лежит выше всей полосы при
  любой разумной нумерации.

  Это довод не за «поискать ещё семейство», а против самой посылки:
  ПОКОЛЕНИЯ, ВЕРОЯТНО, НЕ ТОПОЛОГИЧЕСКОЕ СЕМЕЙСТВО. Косвенно это
  подтверждается тем, что ЧИСЛО поколений в модели уже получено (4.14.11)
  вовсе не из топологии, а из бега alpha и собственных зарядов.
""")


