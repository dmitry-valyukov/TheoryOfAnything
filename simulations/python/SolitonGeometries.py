def beltrami_spheromak():
    head("5. БЕЛЬТРАМИЕВ МИНИМУМ: СФЕРОМАК И КОРНИ tan x = x")
    print("""
  Для поля Бельтрами rot u = lambda u выполняется E = (lambda/2) H, поэтому
  при фиксированной спиральности минимум энергии — это минимум |lambda|,
  а он задаётся геометрией области. Для шара радиуса a решения
  Чандрасекара — Кендалла дают условие  tan(x) = x,  x = lambda a.
""")
    roots = []
    for n in range(0, 8):
        lo = n * math.pi + math.pi / 2 + 1e-9
        hi = n * math.pi + 1.5 * math.pi - 1e-9
        try:
            roots.append(brentq(lambda x: math.tan(x) - x, lo, hi, xtol=1e-14))
        except ValueError:
            pass
    roots = roots[:6]
    print("  корни tan x = x:      " + ", ".join(f"{r:.5f}" for r in roots))
    print("  отношения к первому:  " + ", ".join(f"{r/roots[0]:.4f}" for r in roots))
    print(f"""
  Основное состояние lambda_1 a = {roots[0]:.5f}. Это единственное место во
  всей конструкции, где геометрия ОБЛАСТИ сама даёт число, без подгонки.

  Но как механизм поколений эта лестница не работает: при E = lambda H / 2
  и фиксированной спиральности отношения энергий возбуждённых сферомаков
  равны отношениям корней, {roots[1]/roots[0]:.3f} и {roots[2]/roots[0]:.3f},
  тогда как требуется {R_MU:.1f} и {R_TAU:.1f}. Разрыв — два порядка.
""")


