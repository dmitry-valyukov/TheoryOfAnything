"""
Раунд оценок: какие геометрии солитона допускает несжимаемая среда.

Вопрос, на который отвечает модуль: тор был выбран из-за удобства матаппарата,
шар — из-за ещё большего удобства. Что из этого допускает сама среда?

Жёсткие ограничения среды (не выбираются, а следуют):
  C1  поле смещений соленоидально:  div u = 0   (маргинальный джемминг, 1.5.7)
  C2  конфигурация локализована, энергия конечна
  C3  статики нет (теорема Деррика) — конфигурация обязана колебаться
  C4  спин 1/2: замыкание 4pi, pi_1(SO(3)) = Z_2
  C5  топологическая защита: непрерывное распрямление запрещено

Разделы:
  1. сферическая симметрия ПОЛЯ исключена точно
  2. шаровая ОБЛАСТЬ разрешена, но поле внутри неё тороидально (вихрь Хилла)
  3. спиральный базис: соленоидальное поле = 2 скаляра, спиральность диагональна
  4. теорема Арнольда: инвариантные торы типичны; исключение — бельтрамиевы поля
  5. бельтрамиев минимум: сферомак, корни tan x = x, E = lambda*H/2
  6. семейство торических узлов (p,q): спин от чётности, индекс Хопфа от pq
  7. бюджет показателя: что обязана дать любая топологическая нумерация
  8. сводная таблица допустимости

Расчёты к подглаве theory/02-7-geometriya-solitona.md.
Запуск:  python SolitonGeometries.py
"""

