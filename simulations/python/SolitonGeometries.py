def sphere_excluded():
    head("1. СФЕРИЧЕСКАЯ СИММЕТРИЯ ПОЛЯ ИСКЛЮЧЕНА ТОЧНО")
    print("""
  Векторное поле на R^3, инвариантное относительно ОДНОВРЕМЕННОГО поворота
  точки и вектора, обязано иметь вид  u = f(r) e_r  («ёж»). Других нет:
  любая непрадиальная компонента задаёт выделенное направление.

  Для такого поля       div u = (1/r^2) d(r^2 f)/dr.
  Условие C1 даёт       r^2 f = const  =>  f = A/r^2.

  При A != 0 поле расходится в нуле и не локализуемо (энергия
  int |u|^2 r^2 dr = A^2 int dr/r^2 расходится на нижнем пределе).
  При A = 0 поле тождественно нулевое.
""")
    # численная иллюстрация: сколько ни подбирай локализованный профиль,
    # невязка дивергенции остаётся величиной ПОРЯДКА самого градиента.
    # Безразмерная мера: N = ||div u|| / ||grad u||, оба в L2 с весом r^2.
    r = np.linspace(1e-4, 12.0, 200000)
    trials = {
        "гауссиан  f = exp(-r^2)": np.exp(-(r ** 2)),
        "профиль Q-шара f = sech(r)": 1.0 / np.cosh(r),
        "ступенька f = (1-r^2)_+": np.clip(1 - r ** 2, 0, None),
        "оболочка f = r^2 exp(-r^2)": r ** 2 * np.exp(-(r ** 2)),
        "точное решение f = 1/r^2": 1.0 / r ** 2,
    }
    print(f"  {'пробный профиль':>30} {'||div u||/||grad u||':>21} {'энергия':>12} {'локализ.':>10}")
    for name, f in trials.items():
        div = np.gradient(r ** 2 * f, r) / r ** 2
        # |grad u|^2 для u = f e_r равно f'^2 + 2 f^2 / r^2
        g2 = np.gradient(f, r) ** 2 + 2.0 * f ** 2 / r ** 2
        nd = math.sqrt(np.trapezoid(div ** 2 * r ** 2, r))
        ng = math.sqrt(np.trapezoid(g2 * r ** 2, r))
        e = np.trapezoid(f ** 2 * r ** 2, r)
        loc = "да" if e < 1e2 else "НЕТ"
        print(f"  {name:>30} {nd/ng:>21.4f} {e:>12.4e} {loc:>10}")
    print("""
  Отношение равно ЕДИНИЦЕ для любого локализованного профиля, и это точное
  тождество, а не совпадение. При u = f e_r
      |grad u|^2 = f'^2 + 2 f^2 / r^2,     div u = f' + 2 f / r,
  а интегрирование по частям члена 4 f f' r даёт для локализованного f
      int (div u)^2 r^2 dr = int |grad u|^2 r^2 dr = int f'^2 r^2 dr + 2 int f^2 dr.
  То есть у сферически-симметричного поля ВЕСЬ градиент сидит в дивергенции.
  Промежуточных, «почти несжимаемых» вариантов не бывает: условие C1
  уничтожает такую конфигурацию целиком, а не подправляет её.

  Единственный профиль с нулевой дивергенцией — тот, что не локализуется.
  Вывод: сфера для электрона не «другой объект», а НЕВОЗМОЖНЫЙ объект.
  Всё, что посчитано в 2.5 (радиальный скалярный профиль), к векторному
  полю смещений в несжимаемой среде отношения не имеет.
""")


