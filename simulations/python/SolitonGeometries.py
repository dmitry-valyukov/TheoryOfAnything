def ball_support_allowed():
    head("2. ШАРОВАЯ ОБЛАСТЬ РАЗРЕШЕНА — НО ПОЛЕ В НЕЙ ТОРОИДАЛЬНО")
    print("""
  Исключена симметрия ПОЛЯ, а не шаровая форма ОБЛАСТИ. Контрпример
  классический: сферический вихрь Хилла — соленоидальное течение,
  строго обнуляющееся вне шара радиуса a.

  Функция тока (внутри шара):   psi = -(3/4) U w^2 (1 - r^2/a^2),
  где w = r sin(theta),  u_w = -(1/w) dpsi/dz,  u_z = (1/w) dpsi/dw.
""")
    a, U = 1.0, 1.0
    n = 401
    w = np.linspace(1e-4, 1.4 * a, n)
    z = np.linspace(-1.4 * a, 1.4 * a, n)
    W, Z = np.meshgrid(w, z, indexing="ij")
    R2 = W ** 2 + Z ** 2
    psi = np.where(R2 <= a ** 2, -0.75 * U * W ** 2 * (1 - R2 / a ** 2), 0.0)

    dw, dz = w[1] - w[0], z[1] - z[0]
    u_w = -np.gradient(psi, dz, axis=1) / W
    u_z = np.gradient(psi, dw, axis=0) / W
    div = np.gradient(W * u_w, dw, axis=0) / W + np.gradient(u_z, dz, axis=1)

    inner = (R2 < (0.9 * a) ** 2)
    print(f"  max|div u| внутри шара                 = {np.max(np.abs(div[inner])):.3e}")
    print(f"  max|u| вне шара (r > 1.1 a)            = "
          f"{np.max(np.abs(u_w[R2 > (1.1*a)**2])):.3e}")

    # стагнационное кольцо: dpsi/dz = 0 -> z = 0 ; dpsi/dw = 0 -> w = a/sqrt2
    w_core = a / math.sqrt(2.0)
    print(f"  керновое кольцо (аналитически)         w = a/sqrt(2) = {w_core:.5f} a, z = 0")
    print("""
  Линии тока внутри — вложенные замкнутые петли вокруг КОЛЬЦА радиуса
  a/sqrt(2). То есть шар, заполненный вложенными торами.

  СУЩЕСТВЕННО: шар и тор — не альтернативы. Соленоидальное локализованное
  течение с шаровым носителем ВНУТРИ устроено тороидально. Спор «шар или
  тор» неверно поставлен: спрашивать надо не про форму области, а про
  топологию семейства орбит поля.

  Замечание: чистый вихрь Хилла полоидален, спиральность его равна нулю,
  топологической защиты (C5) нет. Защита появляется при добавлении
  тороидальной закрутки — то есть при переходе к семейству (p, q).
""")


