def arnold_structure():
    head("4. ТЕОРЕМА АРНОЛЬДА: ТОР — НЕ УДОБСТВО, А ТИПИЧНЫЙ СЛУЧАЙ")
    print("""
  Структурная теорема Арнольда (1965) для стационарных решений уравнения
  Эйлера: если поле аналитично, соленоидально, стационарно и НЕ всюду
  параллельно своему ротору, то область разбивается на инвариантные
  ТОРЫ (либо кольца/цилиндры), а орбиты на них — прямолинейные обмотки.

  То есть тороидальная топология орбит не выбрана «из-за удобного
  матаппарата». Для стационарного соленоидального локализованного поля
  она ТИПИЧНА — иных вариантов теорема не оставляет.

  Ровно одно исключение: поля Бельтрами (u параллельно rot u), для которых
  теорема неприменима и орбиты могут быть хаотическими. Проверяется прямо
  на потоке ABC:  x' = A sin z + C cos y, y' = B sin x + A cos z,
                  z' = C sin y + B cos x.
""")

    def abc_rhs(t, s, A, B, C):
        x, y, z = s[0], s[1], s[2]
        v = np.array([A * math.sin(z) + C * math.cos(y),
                      B * math.sin(x) + A * math.cos(z),
                      C * math.sin(y) + B * math.cos(x)])
        # вариационное уравнение
        J = np.array([
            [0.0, -C * math.sin(y), A * math.cos(z)],
            [B * math.cos(x), 0.0, -A * math.sin(z)],
            [-B * math.sin(x), C * math.cos(y), 0.0],
        ])
        d = s[3:6]
        return np.concatenate([v, J @ d])

    T, NSEED = 500.0, 40

    def ftle(A, B, C, seed=11):
        rng = np.random.default_rng(seed)
        acc = []
        for _ in range(NSEED):
            s = np.zeros(6)
            s[:3] = rng.uniform(0, 2 * math.pi, 3)
            s[3:] = np.array([1.0, 0.0, 0.0])
            lam, t0 = 0.0, 0.0
            step = 5.0
            while t0 < T:
                sol = solve_ivp(abc_rhs, (t0, t0 + step), s, args=(A, B, C),
                                rtol=1e-10, atol=1e-12, method="DOP853")
                s = sol.y[:, -1]
                nrm = np.linalg.norm(s[3:])
                lam += math.log(nrm)
                s[3:] /= nrm
                t0 += step
            acc.append(lam / T)
        return np.array(acc)

    floor = math.log(T) / T
    print(f"  На регулярных торах касательный вектор растёт ЛИНЕЙНО, что даёт")
    print(f"  ложный пол ln(T)/T = {floor:.4f} при T = {T:.0f}. Хаос — это превышение пола.")
    print()
    print(f"  {'поток':>28} {'max lambda':>11} {'доля хаоса':>12}   вердикт")
    for label, (A, B, C) in (
        ("ABC, C = 0  (интегрируемый)", (1.0, 1.0, 0.0)),
        ("ABC, C = 0.5", (1.0, 1.0, 0.5)),
        ("ABC, C = 1  (классический)", (1.0, 1.0, 1.0)),
    ):
        a = ftle(A, B, C)
        frac = float((a > 2 * floor).mean())
        verdict = "только торы" if frac == 0.0 else "хаотическая паутина"
        print(f"  {label:>28} {a.max():>11.4f} {frac:>12.0%}   {verdict}")

    print("""
  Итог раздела и главная развилка модели:

    ветвь Арнольда   — не-бельтрамиево стационарное поле: орбиты ложатся
                       на вложенные торы, топология тора ВЫНУЖДЕНА;
    ветвь Бельтрами  — минимум энергии при фиксированной спиральности,
                       но орбиты могут быть хаотическими, и разбиения на
                       торы нет.

  Обе ветви соленоидальны и обе допустимы средой. Различаются они не
  удобством, а тем, есть ли у солитона регулярная тороидальная намотка.
  Модель обязана выбрать ветвь явно — сейчас она выбирает первую молча.
""")


