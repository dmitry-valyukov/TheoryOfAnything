def helical_basis():
    head("3. СПИРАЛЬНЫЙ БАЗИС: СОЛЕНОИДАЛЬНОЕ ПОЛЕ = 2 СКАЛЯРА")
    print("""
  Общая рамка для соленоидальных полей — разложение тороидаль/полоидаль
  (разложение Ми):   u = rot(Psi r) + rot rot(Phi r).
  Три компоненты сводятся к ДВУМ скалярам — ровно столько же, сколько
  поперечных поляризаций у волны в среде (7.5). Это не совпадение: оба
  счёта суть одно и то же условие k . u = 0.

  В Фурье то же самое выглядит как спиральный базис h_+(k), h_-(k):
  rot h_pm = pm |k| h_pm. Проверка на случайном соленоидальном поле.
""")
    rng = np.random.default_rng(20260814)
    N = 32
    k1 = np.fft.fftfreq(N, d=1.0 / N)
    KX, KY, KZ = np.meshgrid(k1, k1, k1, indexing="ij")
    K2 = KX ** 2 + KY ** 2 + KZ ** 2
    K = np.sqrt(K2)

    # случайное поле, спроецированное на соленоидальное подпространство
    f = (rng.normal(size=(3, N, N, N)) + 1j * rng.normal(size=(3, N, N, N)))
    env = np.exp(-K2 / 40.0)
    f = f * env
    kdotf = KX * f[0] + KY * f[1] + KZ * f[2]
    with np.errstate(invalid="ignore", divide="ignore"):
        f[0] -= np.where(K2 > 0, KX * kdotf / K2, 0)
        f[1] -= np.where(K2 > 0, KY * kdotf / K2, 0)
        f[2] -= np.where(K2 > 0, KZ * kdotf / K2, 0)
    f[:, 0, 0, 0] = 0

    kdotf = np.abs(KX * f[0] + KY * f[1] + KZ * f[2])
    print(f"  соленоидальность max|k.u|              = {kdotf.max():.3e}")

    # спиральный базис
    e1 = np.zeros((3,) + K.shape)
    ref = np.array([0.0, 0.0, 1.0])
    tmp = np.stack([KY * ref[2] - KZ * ref[1],
                    KZ * ref[0] - KX * ref[2],
                    KX * ref[1] - KY * ref[0]])
    bad = np.linalg.norm(tmp, axis=0) < 1e-12
    tmp[0][bad], tmp[1][bad], tmp[2][bad] = 1.0, 0.0, 0.0
    e1 = tmp / np.linalg.norm(tmp, axis=0)
    e2 = np.stack([KY * e1[2] - KZ * e1[1],
                   KZ * e1[0] - KX * e1[2],
                   KX * e1[1] - KY * e1[0]])
    with np.errstate(invalid="ignore", divide="ignore"):
        e2 = np.where(K > 0, e2 / np.where(K > 0, K, 1), 0)

    hp = (e1 + 1j * e2) / math.sqrt(2.0)
    hm = (e1 - 1j * e2) / math.sqrt(2.0)
    ap = np.sum(np.conj(hp) * f, axis=0)
    am = np.sum(np.conj(hm) * f, axis=0)

    rec = ap * hp + am * hm
    print(f"  восстановление из 2 амплитуд, max err  = {np.max(np.abs(rec - f)):.3e}")

    E = 0.5 * np.sum(np.abs(ap) ** 2 + np.abs(am) ** 2)
    H = np.sum(K * (np.abs(ap) ** 2 - np.abs(am) ** 2))
    # спиральность в прямом пространстве для контроля
    om = np.stack([KY * f[2] - KZ * f[1],
                   KZ * f[0] - KX * f[2],
                   KX * f[1] - KY * f[0]]) * 1j
    H_dir = np.real(np.sum(np.conj(f) * om))
    print(f"  спиральность: спектрально {H:.6e}, напрямую {H_dir:.6e}, "
          f"отн. расх. {abs(H - H_dir)/max(abs(H),1e-30):.2e}")

    kmax = K[K > 0].max()
    print(f"""
  Отсюда неравенство реализуемости |H| <= 2 E / k_min, то есть при
  фиксированной спиральности энергия снизу ограничена. Минимум достигается,
  когда ВСЯ энергия сидит в одном знаке спиральности — а это ровно условие
  Бельтрами rot u = lambda u.

  для этого поля: |H|/(2E) = {abs(H)/(2*E):.4f},  диапазон k = [{K[K>0].min():.3f}, {kmax:.3f}]
  насыщение неравенства => все амплитуды одного знака => бельтрамиево поле
""")


