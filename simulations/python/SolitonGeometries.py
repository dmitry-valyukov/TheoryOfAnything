def torus_knots():
    head("6. СЕМЕЙСТВО (p, q): СПИН ОТ ЧЁТНОСТИ, ИНДЕКС ХОПФА ОТ ПРОИЗВЕДЕНИЯ")
    print("""
  Намотка на торе задаётся парой целых (p, q): p оборотов по малому кругу
  на q оборотов по большому. Мёбиусово условие модели phi = theta/2 —
  это класс q = 2p, но НЕ обязательно (1, 2).

  Два независимых числа, которые модель до сих пор не различала:

    спин         определяется дробью p/q приведённой, точнее её чётностью:
                 замыкание 4pi даёт любая пара с q/p = 2;
    индекс Хопфа спиральность намотки, H = p q.

  Значит существует целое семейство с ОДНИМ И ТЕМ ЖЕ спином 1/2 и разными
  топологическими зарядами: (n, 2n), n = 1, 2, 3, ...  Это ровно то, на что
  указывает наблюдение «спин 1/2 есть не только у 2/4, но и у 3/6».
""")
    print(f"  {'(p,q)':>8} {'d=НОД':>6} {'компонент':>10} {'q/p':>6} {'спин':>6} {'H=pq':>6} {'H/H_1':>7}")
    base = None
    for n in (1, 2, 3, 4, 5):
        p, q = n, 2 * n
        d = math.gcd(p, q)
        H = p * q
        if base is None:
            base = H
        print(f"  {f'({p},{q})':>8} {d:>6} {d:>10} {q/p:>6.1f} {'1/2':>6} {H:>6} {H/base:>7.2f}")
    print("""
  Замечание о честности: (n, 2n) при n > 1 есть не узел, а ЗАЦЕПЛЕНИЕ из n
  компонент, каждая из которых — обычная (1,2)-обмотка. Попарное число
  зацепления pq/d^2 = 2 одинаково для всех n; растёт число компонент.
  Физически это означает не «более туго завязанный электрон», а n
  сцепленных копий одного и того же узла. Как кандидат в поколения это
  вызывает сразу вопрос о заряде: n копий несут заряд n e, чего нет.

  Иначе говоря, семейство (n, 2n) даёт правильный спин, но неправильный
  заряд. Настоящие УЗЛЫ со спином 1/2 требуют НОД(p, q) = 1, а тогда q/p
  никогда не равно 2, и мёбиусово условие в исходной форме не выполняется.
""")
    print(f"  {'(p,q) узлы, НОД=1':>20} {'H=pq':>6} {'q/p':>8}")
    for p, q in ((2, 3), (2, 5), (3, 4), (2, 7), (3, 5), (4, 5), (3, 7), (5, 6)):
        if math.gcd(p, q) == 1:
            print(f"  {f'({p},{q})':>20} {p*q:>6} {q/p:>8.4f}")
    print("""
  Ни одно нечётное/взаимно простое (p, q) не даёт q/p = 2. Следовательно
  либо мёбиусово условие phi = theta/2 надо ослабить до «нечётного числа
  полуоборотов репера вдоль орбиты» (что даёт спин 1/2 у ЛЮБОГО узла с
  нечётным фреймингом), либо электрон не есть торический узел.

  Первое сильнее и дешевле: спин 1/2 в модели вообще не нуждается в
  торическом узле, он следует из pi_1(SO(3)) = Z_2 для репера среды (2.4).
  Тогда (p, q) свободны, и топологический заряд перестаёт быть привязан
  к спину.
""")


