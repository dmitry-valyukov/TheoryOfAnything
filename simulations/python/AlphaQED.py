"""
AlphaQED.py — аудит вывода постоянной тонкой структуры и её БЕГА по энергии.

Не путать с `alpha_running.py`: тот считает космологический дрейф alpha по
эпохам, а настоящий модуль — обычный КЭД-бег по переданному импульсу,

    1/alpha(s) = 1/alpha(0) - (1/3pi) * SUM_f N_c Q_f^2 [ ln(s/m_f^2) - 5/3 ]

Модуль отвечает на три вопроса (theory/04-10):

  1. Какое именно значение alpha претендует вывести модель — alpha(0),
     alpha(m_Z) или голый заряд? Их нельзя смешивать.
  2. Не входит ли измеренная alpha в цепочку вывода (проверка на цикличность)?
  3. Что именно модель обязана воспроизвести, чтобы «вывести бег», —
     и может ли она это сделать без подгоночных параметров?

Запуск:  python AlphaQED.py
"""

import numpy as np

# ----------------------------------------------------------------------------
# Константы
# ----------------------------------------------------------------------------

ALPHA_0_GEOM = 1.0 / (48.0 * np.pi)      # «голый» топологический заряд модели
ALPHA_THOMSON = 7.2973525693e-3          # alpha(q^2 = 0), CODATA
INV_ALPHA_MZ = 127.951                   # 1/alpha(m_Z), PDG
M_Z = 91187.6                            # МэВ

# Заряженный фермионный состав: (символ, масса МэВ, число цветов, заряд)
FERMIONS = [
    ("e",   0.51099895,  1, -1.0),
    ("u",   2.16,        3, +2 / 3),
    ("d",   4.67,        3, -1 / 3),
    ("s",   93.4,        3, -1 / 3),
    ("mu",  105.6583755, 1, -1.0),
    ("c",   1270.0,      3, +2 / 3),
    ("tau", 1776.86,     1, -1.0),
    ("b",   4180.0,      3, -1 / 3),
    ("t",   172690.0,    3, +2 / 3),
]

DELTA_ALPHA_HAD_MZ = (0.02766, 0.00010)  # адронный вклад из данных e+e-


# ----------------------------------------------------------------------------
# 1. Коэффициент бета-функции
# ----------------------------------------------------------------------------

def beta_coefficient(active=None):
    """SUM N_c * Q^2 по активным (легче порога) фермионам.

    Именно эта безразмерная сумма задаёт наклон бега. В модели она собирается
    из величин, которые сами претендуют быть выведенными:
      Q = 2/3, 1/3  — дефицит размерности обхода (theory/05-2)  ВЫВОДИТСЯ
      N_c = 3       — трёхмерность пространства (theory/05-1)   ВЫВОДИТСЯ
      n_f = 3       — число поколений                    ВЗЯТО ИЗ ЭКСПЕРИМЕНТА

    Существенно (theory/04-11): выводится вклад ОДНОГО поколения b_пок = 8/3,
    а полный коэффициент b = (8/3) * n_f требует независимого определения n_f.
    Сверху n_f ограничено условием «полюс Ландау выше планковского обрезания»:
    n_f <= 5 (см. generations_bound()).
    """
    if active is None:
        active = [f[0] for f in FERMIONS]
    return sum(nc * q * q for sym, m, nc, q in FERMIONS if sym in active)


def beta_breakdown():
    """Разложение коэффициента по семействам."""
    lep = sum(nc * q * q for s, m, nc, q in FERMIONS if nc == 1)
    up = sum(nc * q * q for s, m, nc, q in FERMIONS if nc == 3 and q > 0)
    down = sum(nc * q * q for s, m, nc, q in FERMIONS if nc == 3 and q < 0)
    return {"лептоны": lep, "верхние кварки": up, "нижние кварки": down,
            "итого": lep + up + down}


# ----------------------------------------------------------------------------
# 2. Бег в однопетлевом приближении
# ----------------------------------------------------------------------------

def delta_alpha_leptonic(s, alpha=ALPHA_THOMSON):
    """Лептонный вклад в Delta alpha(s). Считается точно, без данных."""
    tot = 0.0
    for sym, m, nc, q in FERMIONS:
        if nc != 1:
            continue
        if s <= m * m:
            continue
        tot += alpha / (3.0 * np.pi) * nc * q * q * (np.log(s / (m * m)) - 5.0 / 3.0)
    return tot


def inv_alpha_at(s, include_hadronic=True):
    """1/alpha(s) в однопетлевом приближении."""
    d = delta_alpha_leptonic(s)
    if include_hadronic and s >= M_Z ** 2:
        d += DELTA_ALPHA_HAD_MZ[0]
    return (1.0 / ALPHA_THOMSON) * (1.0 - d)


def active_flavours(mu):
    """Какие фермионы активны на масштабе mu (МэВ)."""
    return [s for s, m, nc, q in FERMIONS if mu > m]


def running_table(scales=None):
    """Коэффициент наклона по порогам."""
    if scales is None:
        scales = [0.1, 0.51099895, 2.16, 4.67, 93.4, 105.6583755,
                  1270.0, 1776.86, 4180.0, 172690.0, 1e6]
    out = []
    for mu in scales:
        act = active_flavours(mu)
        out.append((mu, len(act), beta_coefficient(act), ",".join(act) or "—"))
    return out


# ----------------------------------------------------------------------------
# 3. Проверки цепочки вывода модели
# ----------------------------------------------------------------------------

DERIVATION_CHAIN = [
    ("alpha_0 = 1/(48 pi)", "счёт 3 осей x 2 полоид. обхода x 8pi", False),
    ("cosh eta_0 = (2 pi / alpha_0)^(1/4)", "только alpha_0", False),
    ("швингеровский множитель 1 - alpha_0/(2 pi)", "только alpha_0", False),
    ("eta_eff", "предыдущие", False),
    ("tau_n, Gamma_n", "eta_eff", False),
]


def circularity_check():
    """Входит ли ИЗМЕРЕННАЯ alpha в цепочку вывода? (третий элемент кортежа)"""
    return any(uses_measured for _, _, uses_measured in DERIVATION_CHAIN)


def sign_check():
    """Лежит ли alpha_0 модели в физически достижимой области?

    alpha растёт с энергией и замораживается ниже массы электрона, поэтому
    alpha(0) = 1/137.036 есть АБСОЛЮТНЫЙ МИНИМУМ бегущей константы.
    """
    below_floor = ALPHA_0_GEOM < ALPHA_THOMSON
    needed = ALPHA_THOMSON / ALPHA_0_GEOM
    return below_floor, needed


# ----------------------------------------------------------------------------
# Отчёт
# ----------------------------------------------------------------------------

def report():
    print("=" * 76)
    print("АУДИТ: ПОСТОЯННАЯ ТОНКОЙ СТРУКТУРЫ И ЕЁ БЕГ")
    print("=" * 76)

    print("\n1. Три значения, которые нельзя смешивать")
    print(f"   alpha_0 = 1/(48 pi) (модель) : 1/{1/ALPHA_0_GEOM:.3f}")
    print(f"   alpha(0)  Томсоновский предел : 1/{1/ALPHA_THOMSON:.3f}")
    print(f"   alpha(m_Z)                    : 1/{INV_ALPHA_MZ:.3f}")

    print("\n2. Проверка на цикличность")
    print(f"   {'шаг':>44}  использует измеренную alpha?")
    for name, src, uses in DERIVATION_CHAIN:
        print(f"   {name:>44}  {'ДА' if uses else 'нет':>4}   ({src})")
    print(f"   ИТОГ: цикличность {'ОБНАРУЖЕНА' if circularity_check() else 'отсутствует'}")

    print("\n3. Проверка знака")
    below, needed = sign_check()
    print(f"   alpha растёт с энергией и заморожена ниже m_e")
    print(f"   => alpha(0) = 1/137.036 — АБСОЛЮТНЫЙ МИНИМУМ бегущей константы")
    print(f"   alpha_0 модели ниже этого минимума: {below}")
    print(f"   требуется УСИЛЕНИЕ в {needed:.6f} раз (+{(needed-1)*100:.3f} %)")
    print(f"   исходник даёт Gamma_int = 0.048287 — ПОДАВЛЕНИЕ в {1/0.048287:.2f} раз")
    print(f"   расхождение по модулю {needed/0.048287:.2f} раз И по знаку эффекта")

    print("\n4. Коэффициент бега — что модель обязана воспроизвести")
    for k, v in beta_breakdown().items():
        print(f"   {k:>18}: {v:.4f}")
    print("   Q (theory/05-2) и N_c = 3 (theory/05-1) ВЫВОДЯТСЯ;")
    print("   n_f = 3 ВЗЯТО ИЗ ЭКСПЕРИМЕНТА — см. theory/04-11.")
    print(f"   Выводится вклад одного поколения: b_пок = {B_PER_GENERATION:.4f} = 8/3")

    print("\n5. Пороги: коэффициент наклона по масштабам")
    print(f"   {'mu, МэВ':>12} {'активных':>9} {'SUM N_c Q^2':>12}  состав")
    for mu, n, b, act in running_table():
        print(f"   {mu:12.3f} {n:9d} {b:12.4f}  {act}")

    print("\n6. Значение при m_Z")
    lep = delta_alpha_leptonic(M_Z ** 2)
    had = DELTA_ALPHA_HAD_MZ[0]
    print(f"   Delta alpha_lep = {lep:.6f}  (точный расчёт, данных не требует)")
    print(f"   Delta alpha_had = {had:.6f} +- {DELTA_ALPHA_HAD_MZ[1]:.5f}  (из данных)")
    print(f"   1/alpha(m_Z) однопетлевое = {inv_alpha_at(M_Z**2):.3f}")
    print(f"   измерено                   = {INV_ALPHA_MZ:.3f}")

    generations_report()

    print("\nВЕРДИКТ")
    print("  Цепочка alpha_0 -> eta_eff чиста: измеренная alpha в неё не входит.")
    print("  Но alpha_0 = 1/150.796 лежит НИЖЕ физического минимума 1/137.036,")
    print("  и потому значением бегущей константы быть не может ни при какой")
    print("  энергии. Требуется усиление на 10.04 %, а модель даёт подавление.")
    print("  Вклад ОДНОГО поколения b_пок = 8/3 модель выводит без подгонки,")
    print("  но само n_f = 3 берётся из эксперимента (theory/04-11).")
    print("  Сверху n_f ограничено полюсом Ландау: n_f <= 5.")




# ----------------------------------------------------------------------------
# 4. Полюс Ландау и ограничение на число поколений (theory/04-11)
# ----------------------------------------------------------------------------

E_PLANCK = 1.220890e19        # ГэВ
M_Z_GEV = 91.1876             # ГэВ
HBAR_C_MEV_FM = 197.3269804   # МэВ * фм
B_PER_GENERATION = 1.0 + 3.0 * (2 / 3) ** 2 + 3.0 * (1 / 3) ** 2   # = 8/3


def screening_radius(m_mev=0.51099895):
    """Внешний радиус поляризационной шубы: hbar / (2 m c), фм.

    Виртуальная пара имеет конечный размер, поэтому у облака экранирования
    есть внешняя граница. Пробник с длиной волны больше неё находится целиком
    снаружи и нового экранирования уже не встречает — бег замирает.
    """
    return HBAR_C_MEV_FM / (2.0 * m_mev)


def gap_energy(m_mev=0.51099895):
    """Энергетическая щель диэлектрика: рождение пары узел--антиузел, МэВ."""
    return 2.0 * m_mev


def landau_pole(b, inv_alpha_ref=INV_ALPHA_MZ, mu_ref=M_Z_GEV):
    """Масштаб, на котором 1/alpha обращается в нуль (однопетлевое)."""
    return mu_ref * np.exp(3.0 * np.pi * inv_alpha_ref / (2.0 * b))


def generations_bound(cutoff=E_PLANCK, inv_alpha_ref=INV_ALPHA_MZ,
                      mu_ref=M_Z_GEV, b_gen=B_PER_GENERATION):
    """Верхняя граница на число поколений из условия «полюс Ландау выше
    обрезания». Обрезание у модели физическое — планковский масштаб ячейки
    (theory/06-3), поэтому довод внутренний, а не заимствованный.
    """
    b_crit = 3.0 * np.pi * inv_alpha_ref / (2.0 * np.log(cutoff / mu_ref))
    return b_crit, b_crit / b_gen


def generations_report():
    print("=" * 76)
    print("ПОЛЮС ЛАНДАУ И ЧИСЛО ПОКОЛЕНИЙ")
    print("=" * 76)
    print(f"\nРадиус поляризационной шубы: {screening_radius():.1f} фм"
          f"  (= половина приведённой комптоновской длины электрона)")
    print(f"Энергетическая щель:         {gap_energy():.3f} МэВ"
          f"  (рождение пары узел--антиузел)")
    print(f"\nВклад одного поколения: b_пок = 1 + 4/3 + 1/3 = {B_PER_GENERATION:.4f}")
    print(f"\n{'поколений':>10} {'b':>9} {'mu_L, ГэВ':>13} {'mu_L/E_Pl':>12}  статус")
    for n in range(1, 9):
        b = B_PER_GENERATION * n
        mu = landau_pole(b)
        ok = "ok" if mu > E_PLANCK else "НИЖЕ ОБРЕЗАНИЯ"
        print(f"{n:10d} {b:9.4f} {mu:13.3e} {mu/E_PLANCK:12.3e}  {ok}")
    b_crit, n_crit = generations_bound()
    print(f"\nГраница: b < {b_crit:.3f}  =>  n_f < {n_crit:.3f}  =>  n_f <= {int(n_crit)}")
    print(f"При чисто лептонном расширении (вклад 1 на лептон):"
          f" до {int(b_crit - 8)} дополнительных заряженных лептонов")
    print("\nЭто ВЕРХНЯЯ ГРАНИЦА, а не вывод числа 3. Пятое поколение")
    print("самосогласованности модели не противоречит; шестое — противоречит.")


if __name__ == "__main__":
    report()
