"""Шумовой термостат как правило отбора уровней (T-31): выписать баланс и
проверить, выделяет ли он дискретные амплитуды.

Постановка. Солитон — нелинейная мода в ванне поперечных фононов среды.
Он излучает (сток) и поглощает из шума на своей частоте (накачка).
Стационарность:  P_погл(A) = P_изл(A). Вопрос T-15/T-31: даёт ли это
уравнение ДИСКРЕТНЫЙ набор корней по амплитуде A (то есть по энергии),
и от чего зависит их число.

Модель, минимально верная физике:
  - мода: кубично-квинтический осциллятор  x'' + Omega^2 x - g x^3 + h x^5,
    та же нелинейность, что у солитона (2.5, 2.8); частота зависит от
    амплитуды: Omega_A = Omega(A) — окно частот моды;
  - сток: излучение в поперечную ветвь с темпом Gamma(omega) (радиационное
    затухание, ~omega^2 у точечного излучателя, ~omega^0 в среде с
    плоской плотностью состояний джемминга — оба варианта);
  - накачка: сила Ланжевена с одно-сторонним спектром S_F(omega) шума
    среды. Два вида шума:
        (a) ФДТ-согласованный (термостат при T = 0): S_F = 2 hbar omega
            Gamma(omega) m — «нулевые колебания» самой ванны;
        (b) шум с ВНЕШНИМ спектром: J(omega) с обрезкой на omega_c
            (порог рождения пар / шаг упаковки) и структурой.

Разделы:
  1. аналитика: усреднённый по циклу баланс мощностей;
     ФДТ-случай (a) — теорема: для линейного отклика баланс есть
     ТОЖДЕСТВО по амплитуде (нет отбора), для нелинейной моды —
     единственный корень (основное состояние, как у Бойера);
  2. численно: кривая P_погл(A) - P_изл(A) для (a) и (b), число корней;
  3. что нужно, чтобы корней стало три: спектр J(omega) с тремя
     максимумами в окне моды — и что это означает для модели;
  4. вердикт: правило отбора термостатом = структура спектра среды.

Запуск:  python ThermostatSelection.py [--plot]
"""

import math
import sys

import numpy as np
from scipy.integrate import solve_ivp, quad
from scipy.optimize import brentq

G, H, OMEGA0 = 2.0, 1.0, 1.0        # тот же (g, h) режим, что в TorusBVP
HBAR, M = 0.05, 1.0                 # hbar << глубины ямы: уровень E = hbar Omega
                                    # обязан лежать ВНУТРИ окна амплитуд


def head(t):
    print()
    print("=" * 78)
    print(t)
    print("=" * 78)


# ---------------------------------------------------------------- мода
def potential_force(x):
    return -OMEGA0 ** 2 * x + G * x ** 3 - H * x ** 5


def frequency_of_amplitude(A):
    """Период кубично-квинтического осциллятора при амплитуде A (энергия
    E = U(A)), U = Omega^2 x^2/2 - g x^4/4 + h x^6/6."""
    def U(x):
        return 0.5 * OMEGA0 ** 2 * x ** 2 - G * x ** 4 / 4 + H * x ** 6 / 6
    E = U(A)
    # подстановка x = A sin(theta) убирает интегрируемую особенность
    def integrand(th):
        x = A * math.sin(th)
        dU = E - U(x)
        if dU <= 0:
            return 0.0
        return A * math.cos(th) / math.sqrt(2.0 * dU / M)
    T = 4.0 * quad(integrand, 0.0, math.pi / 2, limit=200)[0]
    return 2.0 * math.pi / T


def amplitude_window():
    """Окно амплитуд, где мода связана: U растёт до края, потом яма
    сваливается — потолок по A там, где dU/dx = 0 (кроме нуля)."""
    # корни Omega^2 - g x^2 + h x^4 = 0
    disc = G ** 2 - 4 * H * OMEGA0 ** 2
    if disc < 0:
        return 0.0, 3.0
    x2 = (G - math.sqrt(disc)) / (2 * H)
    return 0.0, math.sqrt(x2) * 0.999


# ---------------------------------------------------------------- баланс
def gamma_rad(omega, law):
    """Радиационное затухание. 'dipole': ~omega^2 (точечный излучатель в
    3D среде); 'flat': плоская плотность состояний джемминга ~omega^0."""
    if law == "dipole":
        return 0.02 * omega ** 2
    return 0.02


def spectrum_fdt(omega, law):
    """ФДТ при T = 0: S_F = 2 hbar omega m Gamma(omega) (нулевые колебания)."""
    return 2.0 * HBAR * omega * M * gamma_rad(omega, law)


def spectrum_external(omega, kind):
    """Внешний спектр среды: обрезка на omega_c и структура."""
    if kind == "cutoff":
        return 2.0 * HBAR * omega * M * 0.02 * (1.0 if omega < 0.9 else 0.0)
    if kind == "peaks3":
        s = 0.0
        for w0 in (0.55, 0.75, 0.93):
            s += 2.0 * HBAR * w0 * M * 0.02 * 3.0 * math.exp(-((omega - w0) / 0.03) ** 2)
        return s
    return 0.0


def balance(A, law="dipole", spec="fdt", kind="cutoff"):
    """Усреднённые по циклу мощности на нелинейной моде амплитуды A.

    Излучение: P_изл = m Gamma(Omega_A) <v^2> = m Gamma Omega_A^2 A^2 / 2.
    Поглощение из шума на резонансе: P_погл = S_F(Omega_A) / (2 m)  —
    для белого/окрашенного ланжевеновского шума мощность накачки не
    зависит от амплитуды (сила диффузии энергии D = S_F/2m).
    """
    Om = frequency_of_amplitude(A)
    P_rad = M * gamma_rad(Om, law) * Om ** 2 * A ** 2 / 2.0
    S = spectrum_fdt(Om, law) if spec == "fdt" else spectrum_external(Om, kind)
    P_abs = S / (2.0 * M)
    return P_abs, P_rad, Om


# ---------------------------------------------------------------- разделы
def section_analytics():
    head("1. АНАЛИТИКА БАЛАНСА")
    print("""
  Мода амплитуды A с амплитудно-зависимой частотой Omega(A). Усреднённые
  по циклу мощности:

      P_изл(A) = m Gamma(Omega_A) Omega_A^2 A^2 / 2          (сток ~ A^2)
      P_погл(A) = S_F(Omega_A) / (2 m)                        (накачка: не
                                                              зависит от A)

  Стационарность P_погл = P_изл даёт

      A^2 = S_F(Omega_A) / (m^2 Gamma(Omega_A) Omega_A^2).            (*)

  СЛУЧАЙ ФДТ (T = 0), S_F = 2 hbar omega m Gamma:
      A^2 = 2 hbar / (m Omega_A)  =>  E = m Omega_A^2 A^2 / 2 = hbar Omega_A.
  Это баланс Бойера: ОДИН корень — состояние с энергией hbar Omega
  («нулевые колебания моды»). Оно от структуры Gamma(omega) не зависит
  вовсе — Gamma сокращается. Для линейной моды (Omega = const) (*) не
  уравнение на A, а тождество, если приписать амплитуду шуму: отбора нет.
  Для нелинейной — единственное решение E = hbar Omega(A). Дискретного
  НАБОРА уровней ФДТ-термостат не даёт, в точности как СЭД: основное
  состояние есть, возбуждённых нет.

  СЛУЧАЙ ВНЕШНЕГО СПЕКТРА J(omega): корней у (*) столько, сколько раз
  функция S_F(Omega_A) / (Gamma Omega_A^2) пересекает m^2 A^2. Гладкий
  спектр с одной обрезкой — снова один корень (либо ноль). Три корня
  требуют ТРЁХ максимумов S_F в окне частот моды.
""")


def section_numeric(do_plot):
    head("2. ЧИСЛЕННО: ЧИСЛО КОРНЕЙ БАЛАНСА")
    a_lo, a_hi = amplitude_window()
    A_grid = np.linspace(0.05, a_hi, 400)
    print(f"  окно амплитуд связанной моды: A in (0, {a_hi:.3f}); "
          f"частота Omega(A): {frequency_of_amplitude(0.05):.4f} -> "
          f"{frequency_of_amplitude(a_hi):.4f}\n")

    cases = [
        ("ФДТ, Gamma ~ omega^2 (диполь)", "dipole", "fdt", ""),
        ("ФДТ, Gamma плоская (джемминг)", "flat", "fdt", ""),
        ("внешний, одна обрезка omega_c", "flat", "ext", "cutoff"),
        ("внешний, три пика в окне", "flat", "ext", "peaks3"),
    ]
    results = {}
    for name, law, spec, kind in cases:
        diff = []
        for A in A_grid:
            pa, pr, om = balance(A, law, spec, kind)
            diff.append(pa - pr)
        diff = np.array(diff)
        roots = []
        for i in range(len(A_grid) - 1):
            if diff[i] * diff[i + 1] < 0:
                r = brentq(lambda a: balance(a, law, spec, kind)[0]
                           - balance(a, law, spec, kind)[1],
                           A_grid[i], A_grid[i + 1])
                roots.append(r)
        # устойчивость: dP/dA < 0 (излучение растёт быстрее накачки)
        stable = []
        for r in roots:
            d1 = np.interp(r * 1.01, A_grid, diff) - np.interp(r * 0.99,
                                                              A_grid, diff)
            stable.append(d1 < 0)
        results[name] = (A_grid, diff, roots, stable)
        Es = [0.5 * M * frequency_of_amplitude(r) ** 2 * r ** 2 for r in roots]
        print(f"  {name:>34}: корней {len(roots)}  "
              + "  ".join(f"A={r:.3f}{'*' if s else ''}(E={e:.3f})"
                          for r, s, e in zip(roots, stable, Es)))
    print("""
  (* — устойчивый корень: излучение растёт с амплитудой быстрее накачки;
   корень у самого края окна A -> A_max — краевой артефакт: там
   Omega(A) -> 0 и обе мощности зануляются, это не уровень, а край ямы)

  ФДТ-термостат при обоих законах затухания — ровно один устойчивый
  корень, E = hbar Omega (Gamma сокращается, число одинаково для диполя
  и для плоской плотности состояний). Внешний спектр с одной обрезкой —
  ни одного внутреннего корня. Несколько корней появляются только
  тогда, когда в окно частот моды ВПИСАНЫ пики спектра среды.
""")
    if do_plot:
        import os
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        FG, BG, MUT = "#111111", "#ffffff", "#555555"
        COL = ["#0072B2", "#E69F00", "#009E73", "#CC79A7"]
        fig, ax = plt.subplots(figsize=(8.4, 5.0), facecolor=BG)
        for (name, (Ag, diff, roots, stable)), c in zip(results.items(), COL):
            ax.plot(Ag, diff, color=c, lw=2, label=name)
            for r, s in zip(roots, stable):
                ax.plot([r], [0], "o", color=c, mfc=(BG if not s else c),
                        ms=7, mew=1.6)
        ax.axhline(0, color=MUT, lw=0.8)
        ax.set_xlabel("амплитуда моды $A$", color=FG)
        ax.set_ylabel(r"$P_{\rm погл} - P_{\rm изл}$", color=FG)
        ax.set_title("Баланс с термостатом: корней столько, сколько пиков "
                     "спектра в окне", color=FG, fontsize=12)
        ax.legend(frameon=False, fontsize=9)
        ax.set_facecolor(BG)
        ax.tick_params(colors=MUT)
        for s in ax.spines.values():
            s.set_color(MUT)
        fig.text(0.005, 0.005, "ThermostatSelection.py (T-31)", color=MUT,
                 fontsize=8)
        out = os.path.abspath(os.path.join(os.path.dirname(__file__), "..",
                                           "..", "theory", "images",
                                           "thermostat-balance.png"))
        os.makedirs(os.path.dirname(out), exist_ok=True)
        fig.savefig(out, dpi=150, facecolor=BG, bbox_inches="tight")
        print("  написан", out)


def section_requirements():
    head("3. ЧТО НУЖНО, ЧТОБЫ КОРНЕЙ СТАЛО ТРИ")
    print("""
  Из (*): три устойчивых уровня <=> спектр накачки S_F(omega) имеет три
  максимума внутри окна частот моды (mu_inf, 0) — на языке 2.9. То есть
  правило отбора термостатом НЕ есть свойство солитона: оно есть
  СТРУКТУРА СПЕКТРА СРЕДЫ, перенесённая на солитон.

  Что модель знает о спектре среды (1.5, 1.7, 4.11):
    - плато плотности состояний маргинального джемминга (бозонный пик) —
      ОДИН максимум, у нижней границы;
    - обрезка на пороге рождения пар 2 m_e c^2 и накопление у края щели
      (каскад 1.7.7) — ОДИН край;
    - обрезка на шаге упаковки d — ещё один край, планковский.
  Итого у спектра среды в модели одна структура в области лептонных
  масс: край щели. Трёх пиков в окне у него нет — и взяться им неоткуда,
  если только сами лептоны не структурируют спектр (замкнутый круг:
  спектр среды складывается из вкладов заряженных мод — 4.10, бег alpha).

  Замкнутый круг, впрочем, и есть единственный честный выход: спектр
  поляризации вакуума J(omega) имеет пороги ровно на 2 m_l c^2 для каждого
  заряженного лептона (это измеряемо: изломы бега alpha стоят на массах).
  Самосогласованность «уровни задают спектр, спектр отбирает уровни» —
  задача с неподвижной точкой, но БЕЗ гарантии единственности и БЕЗ
  внутреннего масштаба: любая тройка масс порождает спектр с порогами
  на себе. Такая схема ложится на любые три массы — то же, что T-20
  установил для лестницы.
""")


