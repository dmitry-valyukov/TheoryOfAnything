    print(f"  размер солитона (комптоновская длина) = {c['lambda_fm']:.2f} фм")
    print(f"  планковская ячейка                    = {c['l_planck_fm']:.4e} фм")
    print(f"  отношение                             = {c['ratio']:.3e}")
    print(f"  ячеек в трёхмерной решётке            = {c['cells_3d']:.2e}")
    print(f"                                        = 1e{c['log10_cells']:.0f}")
    print()
    print("  Для сравнения: всех данных, произведённых человечеством, порядка")
    print(f"  1e21 байт. Решётка превышает это в 1e{c['log10_cells']-21:.0f} раз.")
    print("  Планковская решётка не «дорога» — она невозможна с запасом")
    print("  в полсотни порядков.")
    print()
    print("  Но она и НЕ НУЖНА. Разделение масштабов в 22 порядка (1.5)")
