"""SolitonExistence.py — что в существовании солитона выводится аналитически.

Расчёты к подглавам theory/02-4-sushchestvovanie-solitona.md
и theory/04-12-elektron-v-atome.md.

Вопрос автора: можно ли вывести вечное самоколебание волны вокруг ядра массы
аналитически, или это доступно только дорогой симуляции на планковской решётке.

Короткий ответ, который здесь обосновывается числами:

  * период 4*pi (спин 1/2) — ЧИСТАЯ ТОПОЛОГИЯ, pi_1(SO(3)) = Z_2,
    динамика не нужна вовсе;
  * необходимость внутреннего колебания — ТЕОРЕМА ДЕРРИКА: статических
    локализованных решений в 3D с двухпроизводными членами не существует,
    значит солитон ОБЯЗАН быть нестатическим;
  * кубическая нелинейность в 3D надкритична и даёт коллапс, а не
    устойчивый солитон: нужна насыщающая (квинтическая) добавка;
  * профиль и масса — РАДИАЛЬНАЯ КРАЕВАЯ ЗАДАЧА В ОДНОМ ИЗМЕРЕНИИ,
    порядка 1e3 узлов, а вовсе не решётка;
  * планковская решётка потребовала бы 1e67 ячеек — не «дорого»,
    а невозможно, и главное НЕ НУЖНО.

Запуск:
    python SolitonExistence.py
"""

from __future__ import annotations

import math

HBAR_C = 197.3269804          # МэВ*фм
M_E = 0.51099895              # МэВ
ALPHA = 7.2973525693e-3
A0_FM = 5.29177210903e4       # боровский радиус, фм
L_PLANCK_FM = 1.616255e-20    # фм

# экспериментальные пределы на структуру электрона
LIMIT_G2_FM = 1e-5            # из аномального магнитного момента
LIMIT_EE_FM = 1e-4            # из e+e- рассеяния при высоких энергиях


def lambda_bar_e() -> float:
    return HBAR_C / M_E


# ---------------------------------------------------------------------------
# 1. Скейлинг Деррика
# ---------------------------------------------------------------------------

def derrick_exponents(D: int = 3) -> dict:
    """Показатели масштабирования членов энергии при u(x) -> u(x/lambda).

    Член с n производными: |d^n u|^2 даёт lambda^(D - 2n).
    Потенциал (0 производных): lambda^D.
    Кинетический член нестатического решения ~ omega^2 |u|^2: тоже lambda^D.
    """
    return {
        "потенциал V(u)": D,
        "градиентный |du|^2": D - 2,
        "скирмовский |du|^4 / |d^2 u|^2": D - 4,
        "кинетический omega^2 |u|^2": D,
    }


def derrick_verdict(D: int = 3) -> str:
    e = derrick_exponents(D)
    a, b = e["градиентный |du|^2"], e["потенциал V(u)"]
    # E(l) = A l^a + B l^b, A, B > 0 для статики -> нет стационарной точки
    return (f"в D={D}: E(l) = A*l^{a} + B*l^{b}, оба показателя положительны "
            f"при A,B>0 -> dE/dl > 0 всюду, минимума нет")


# ---------------------------------------------------------------------------
# 2. Критичность нелинейности
# ---------------------------------------------------------------------------

def criticality(power: int, D: int = 3) -> str:
    """Критическая размерность для нелинейности |u|^(p-1) u в НУШ.

    Массово-критическая размерность: D_c = 2/(p-1) при нелинейности
    степени p. Для кубической p=3 -> D_c = 1 (массово-критическая
    в 1D), энергетически критическая D = 4. В 3D кубическая
    НАДкритична по массе: солитон существует, но неустойчив (коллапс).
    """
    d_mass = 2.0 / (power - 1)
    d_energy = 2.0 * power / (power - 1)
    if D < d_mass:
        st = "подкритична — солитон устойчив"
    elif abs(D - d_mass) < 1e-9:
        st = "критична — порог коллапса"
    else:
        st = "НАДкритична по массе — коллапс, устойчивого солитона нет"
    return f"p={power}: D_крит(масса)={d_mass:.2f}, D_крит(энергия)={d_energy:.2f} -> в D={D} {st}"


# ---------------------------------------------------------------------------
# 3. Цена решётки против радиальной задачи
# ---------------------------------------------------------------------------

def lattice_cost() -> dict:
    lam = lambda_bar_e()
    ratio = lam / L_PLANCK_FM
    cells = ratio ** 3
    return {
        "lambda_fm": lam,
        "l_planck_fm": L_PLANCK_FM,
        "ratio": ratio,
        "cells_3d": cells,
        "log10_cells": 3.0 * math.log10(ratio),
    }


# ---------------------------------------------------------------------------
# 4. Электрон в атоме
# ---------------------------------------------------------------------------

def atomic_scales() -> dict:
    lam = lambda_bar_e()
    return {
        "lambda_bar_fm": lam,
        "a0_fm": A0_FM,
        "ratio": A0_FM / lam,
        "inv_alpha": 1.0 / ALPHA,
        "rel_diff": abs(A0_FM / lam - 1.0 / ALPHA) / (1.0 / ALPHA),
    }


# ---------------------------------------------------------------------------

def report() -> None:
    lam = lambda_bar_e()

    print("=" * 78)
    print("SolitonExistence: что выводится аналитически, а что требует счёта")
    print("=" * 78)
