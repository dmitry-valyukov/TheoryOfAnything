    print("  omega. Это ~1e3 узлов, то есть доли секунды на ноутбуке.")
    print(f"  Выигрыш против решётки: 1e{c['log10_cells']-3:.0f} раз.")
    print()
    print("  Модель уже решает задачу такого типа — спектральное условие на")
    print("  конических функциях Лежандра (4.3). Не хватает не мощности,")
