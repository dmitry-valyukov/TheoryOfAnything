    print("-" * 78)
    print()
    print("  Параметр порядка среды — локальный репер Картана (1.3), то есть")
    print("  элемент SO(3). Фундаментальная группа pi_1(SO(3)) = Z_2, поэтому")
    print("  петля с поворотом репера на 2pi НЕ стягиваема, а спинорный подъём")
    print("  возвращается только после 4pi. Это фокус с ремнём Дирака.")
    print()
    print("  Ключевое: утверждение КИНЕМАТИЧЕСКОЕ. Оно не зависит ни от вида")
    print("  нелинейности, ни от уравнения движения, ни от размера ячейки.")
    print("  Спин 1/2 в модели выводится, и никакой симуляции для этого не надо.")
    print()

    print("-" * 78)
    print("2. ВЕЧНОЕ КОЛЕБАНИЕ: ТЕОРЕМА ДЕРРИКА ЕГО ТРЕБУЕТ")
    print("-" * 78)
    print()
    print("  Показатели масштабирования при u(x) -> u(x/l), D = 3:")
    for k, v in derrick_exponents(3).items():
        print(f"    {k:<34s} l^{v:+d}")
    print()
    print(f"  {derrick_verdict(3)}")
    print()
    print("  Значит СТАТИЧЕСКОГО локализованного решения в 3D нет. Солитон")
    print("  обязан быть нестатическим — с внутренним периодическим движением.")
    print("  «Волна вечно самоколеблется вокруг ядра массы» — не дополнительное")
    print("  допущение модели, а СЛЕДСТВИЕ запрета на статику.")
    print()
    print("  Два законных выхода из теоремы Деррика:")
    print("    (а) внутреннее вращение фазы (Q-шар): кинетический член ~ omega^2")
    print("        даёт третий масштабный вклад и открывает минимум;")
    print("    (б) член с четырьмя производными (скирмовский, l^-1) —")
    print("        в упругости это градиентная теория с масштабом ячейки.")
