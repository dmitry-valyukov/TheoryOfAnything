    print()
    print("  (Показатели даны для ФОКУСИРУЮЩЕЙ нелинейности. Квинтический член,")
    print("   о котором речь ниже, входит с ОБРАТНЫМ знаком — как насыщение,")
    print("   а не как ещё одна фокусирующая добавка; критерий критичности к нему")
    print("   в этом виде неприменим.)")
    print()
    print("  Кубический член — тот самый, что даёт кручение в уравнении")
    print("  Хехла — Датты (1.3) и Дуффинг в 6.2. В трёх измерениях он")
    print("  НАДкритичен: решение существует, но неустойчиво к коллапсу.")
    print()
    print("  Для устойчивости нужна НАСЫЩАЮЩАЯ добавка — квинтический член")
    print("  с обратным знаком. У модели такой механизм есть: слом закона Гука")
    print("  на планковском масштабе, sigma ~ exp(eps) (3.4). Кубически-")
    print("  квинтическая среда в 3D устойчивые солитоны имеет — это известный")
    print("  результат. Но коэффициент насыщения в модели не выписан, и потому")
    print("  СУЩЕСТВОВАНИЕ решения пока не установлено, а лишь не запрещено.")
    print()

    print("-" * 78)
    print("4. ЦЕНА СЧЁТА: РЕШЁТКА ПРОТИВ РАДИАЛЬНОЙ ЗАДАЧИ")
    print("-" * 78)
    print()
