"""
Маргинальное заклинивание как единый постулат: сверка по всей модели.

Установлено (4.14.10), что предел G/B -> 0 маргинально заклиненной упаковки
тождествен условию nu -> 1/2, то есть постулату несжимаемости. Два постулата
модели — структура среды (1.5) и несжимаемость (1.6) — оказываются одним.

Настоящий модуль проверяет, что ЕЩЁ из этого следует, по всем главам.

Разделы:
  1. что даёт маргинальное заклинивание (список фактов)
  2. сокращение числа постулатов
  3. КОЛИЧЕСТВЕННОЕ ПРОТИВОРЕЧИЕ: K и G оба планковские
  4. следствие: либо плотность, либо ячейка не планковские
  5. что это меняет в пути 10
  6. гипероднородность: T-14 получает обоснование, T-4 — затруднение
  7. бозонный пик: спектр нулевых колебаний 1.7 придётся пересчитать
  8. изостатическое число 2D = 6 и множитель 3*2 в 48pi
  9. горизонт как переход РАСКЛИНИВАНИЯ

Расчёты к подглаве theory/01-5-struktura-sredy.md, раздел 1.5.4.
Запуск:  python JammingConsequences.py
"""

import math

# --- фундаментальные постоянные -----------------------------------------
G_N = 6.67430e-11
HBAR = 1.054571817e-34
C = 2.99792458e8
ALPHA = 7.2973525693e-3
LAMBDABAR_C = 3.8615926796e-13

L_PL = math.sqrt(HBAR * G_N / C**3)
M_PL = math.sqrt(HBAR * C / G_N)
RHO_PL = M_PL / L_PL**3
P_PL = RHO_PL * C**2

K_BULK_6_3 = 1.0e113          # подглава 6.3
EPS_REQUIRED = 1.0e-20        # T-3: G/K <= 1e-20

S_EFOLD = 2.0 * ALPHA / (3.0 * math.pi)


def head(t):
    print()
    print("=" * 78)
    print(t)
    print("=" * 78)


def facts():
    head("1. ЧТО ДАЁТ МАРГИНАЛЬНОЕ ЗАКЛИНИВАНИЕ")
    print(f"  {'свойство':>40} {'значение':>18} {'откуда':>16}")
    for a, b, c in (
        ("изостатическое число контактов z_c", "2D = 6", "из D = 3"),
        ("предел G/B", "0", "критич. точка"),
        ("коэффициент Пуассона nu", "1/2", "из G/B -> 0"),
        ("плотность упаковки phi_J", "~0.639", "универсальна"),
        ("плотность мод при малых omega", "плато, не omega^2", "бозонный пик"),
        ("структурный фактор S(k -> 0)", "-> 0", "гипероднородность"),
        ("длина ell* ", "~ 1/dz", "расходится"),
        ("устойчивость", "маргинальная", "критич. точка"),
    ):
        print(f"  {a:>40} {b:>18} {c:>16}")


def postulate_reduction():
    head("2. СОКРАЩЕНИЕ ЧИСЛА ПОСТУЛАТОВ")
    print("""
      nu = (3B - 2G) / (2(3B + G))   ->   1/2   при G/B -> 0

  Постулат 1.5 (предельно заклиненная аморфная упаковка) и постулат 1.6
  (несжимаемость, K/G -> бесконечность) — ОДНО И ТО ЖЕ условие.

  Это не украшение: несжимаемость несла в модели четыре независимых
  мотива (1.6.1) — гравитацию, конфайнмент, электродинамику и неравенства
  Белла. Все четыре теперь опираются не на отдельное допущение, а на уже
  принятую структуру среды. Постулатов на один меньше при том же числе
  следствий.
""")
    for gb in (1.0, 0.1, 1e-3, 1e-10, 0.0):
        nu = (3.0 - 2.0 * gb) / (2.0 * (3.0 + gb))
        print(f"    G/B = {gb:<10.0e}   nu = {nu:.6f}")


def quantitative_conflict():
    head("3. КОЛИЧЕСТВЕННОЕ ПРОТИВОРЕЧИЕ: K И G ОБА ПЛАНКОВСКИЕ")
    print("""
  Заклинивание ТРЕБУЕТ G << K. Проверим, выполнимо ли это при принятых
  в модели численных значениях. Модуль сдвига не свободен: скорость
  поперечной волны есть скорость света, значит

      c = sqrt(G/rho)   =>   G_сдвиг = rho c^2

  Если плотность среды планковская, то G_сдвиг есть планковское ДАВЛЕНИЕ.
""")
    print(f"    l_Pl              = {L_PL:.4e} м")
    print(f"    rho_Pl            = {RHO_PL:.4e} кг/м^3")
    print(f"    G_сдвиг = rho c^2 = {P_PL:.4e} Па   (планковское давление)")
    print(f"    K_bulk из 6.3     = {K_BULK_6_3:.4e} Па")
    print()
    eps = P_PL / K_BULK_6_3
    print(f"    eps = G/K         = {eps:.4e}")
    print(f"    требуется (T-3)   = {EPS_REQUIRED:.0e}")
    print(f"    ПРОМАХ            = {eps/EPS_REQUIRED:.2e}  раз, то есть "
          f"{math.log10(eps/EPS_REQUIRED):.0f} порядков")
    print("""
  Подглава 6.3 сама отмечает, что K_bulk совпадает с планковским давлением
  «с точностью до множителя 4.6». Но G_сдвиг при планковской плотности
  РАВЕН планковскому давлению по построению. Значит K и G совпадают
  по порядку, то есть nu ~ 0.25 — обыкновенное твёрдое тело, ничего
  похожего на несжимаемость.

  T-3 формулировал это противоречие качественно. В числах оно составляет
  ДВАДЦАТЬ ПОРЯДКОВ и не снимается оговоркой про «регулятор у обрезания»:
  при K ~ G продольная ветвь есть полноценная мода на ВСЕХ масштабах,
  а не только у ячейки.
""")
    return eps


def resolution():
    head("4. СЛЕДСТВИЕ: ЛИБО ПЛОТНОСТЬ, ЛИБО ЯЧЕЙКА НЕ ПЛАНКОВСКИЕ")
    print("""
  Противоречие разрешимо ровно одним способом: отказаться от того, что
  среда планковская И по плотности, И по размеру ячейки одновременно.
  Посмотрим, куда сдвигаются величины, если удержать K = P_Pl и
  потребовать G/K <= 1e-20.
""")
    G_req = K_BULK_6_3 * EPS_REQUIRED
    rho_req = G_req / C**2
    a_req = (HBAR / (rho_req * C)) ** 0.25
    print(f"    G_сдвиг <= {G_req:.4e} Па      (в {P_PL/G_req:.2e} раз ниже планковского)")
    print(f"    rho     <= {rho_req:.4e} кг/м^3  (в {RHO_PL/rho_req:.2e} раз ниже планковской)")
    print(f"    из hbar = rho a^4 c:   a = {a_req:.4e} м")
    print(f"    то есть a / l_Pl = {a_req/L_PL:.3e}")
    print("""
  Вывод: если несжимаемость держать всерьёз, ячейка среды примерно на ПЯТЬ
  порядков КРУПНЕЕ планковской длины, а плотность на двадцать порядков ниже
  планковской. Утверждение «размер ячейки планковский» (1.5, 6.3) с
  несжимаемостью несовместимо.

  Это самостоятельный результат сверки: два постулата модели, каждый
  правдоподобный по отдельности, вместе дают конкретное числовое
  расхождение, и разрешить его можно только сдвинув масштаб ячейки.
""")
    return a_req


def effect_on_route10(a_req):
    head("5. ЧТО ЭТО МЕНЯЕТ В ПУТИ 10")
    for name, a in (("ячейка = l_Pl (как принято)", L_PL),
                    ("ячейка из условия несжимаемости", a_req)):
        L = math.log(LAMBDABAR_C / a)
        print(f"  {name:>34}:  a = {a:.3e} м")
        print(f"  {'':>34}   ln(lambdabar_C/a) = {L:.3f}"
              f"   delta_max = {S_EFOLD*L:.4f}")
    print("""
  Сдвиг ячейки на пять порядков меняет delta_max на четверть. Это не
  разрушает путь 10 — качественная картина цела, — но показывает, что
  требуемое значение delta_max зависит от того, где стоит УФ-обрезание.
  Значит расчёт delta_max из физики упаковки обязан идти вместе с
  фиксацией размера ячейки, а не после неё.
""")


def hyperuniformity():
    head("6. ГИПЕРОДНОРОДНОСТЬ: T-14 ПОЛУЧАЕТ ОБОСНОВАНИЕ, T-4 — ЗАТРУДНЕНИЕ")
    print("""
  Заклиненные упаковки ГИПЕРОДНОРОДНЫ: S(k) -> 0 при k -> 0. Отсюда сразу
  два следствия противоположного знака.

  ДЛЯ T-14 — ХОРОШО, и это перестаёт быть надеждой. Подглава T-14 держала
  гипероднородность как возможный спасительный механизм («подавления
  рассеяния может хватить»). Теперь она НЕ ОПЦИОНАЛЬНА: раз среда
  заклинена, она гипероднородна по построению, и релеевское рассеяние на
  беспорядке подавлено обязательно. Прогноз непрозрачности выше 46 ТэВ
  соответственно ослабевает или снимается — но снимается ЗАКОНОМЕРНО, а
  не по случайности.

  ДЛЯ T-4 — ЗАТРУДНЕНИЕ. Диффузионный перенос дрожания, дающий профиль
  1/r и потому ньютоновский потенциал, ТРЕБУЕТ рассеяния. Без рассеяния
  перенос баллистический, и от точечного источника в трёх измерениях
  получается

      баллистически:  n ~ 1/r^2      (плотность = поток / скорость)
      диффузионно:    n ~ 1/r        <- нужно для гравитации

  То есть гипероднородность, спасающая T-14, угрожает T-4.

  РАЗРЕШЕНИЕ, и оно нетривиально. Гипероднородность подавляет рассеяние
  на МАЛЫХ k (длинные волны). Дрожание же среды набирается на БОЛЬШИХ k:
  для линейной дисперсии <u^2> ~ int k dk, то есть определяется верхним
  пределом. Коротковолновые моды рассеиваются нормально и переносятся
  диффузионно, тогда как наблюдаемый свет — длинноволновый и проходит
  без рассеяния.

  Одна и та же среда НЕПРОЗРАЧНА для собственного УФ-дрожания и
  ПРОЗРАЧНА для длинноволнового света. Гипероднородность и есть то, что
  делает такое разделение возможным.
""")


def boson_peak():
    head("7. БОЗОННЫЙ ПИК: СПЕКТР НУЛЕВЫХ КОЛЕБАНИЙ 1.7 ПРИДЁТСЯ ПЕРЕСЧИТАТЬ")
    print("""
  У маргинально заклиненной упаковки плотность состояний при малых
  частотах выходит на ПЛАТО вместо дебаевского omega^2 — это и есть
  бозонный пик, избыток мягких мод.

  Подглава 1.7 считает спектр нулевых колебаний и полную их плотность в
  дебаевском приближении. При заклинивании приближение неверно: мягких
  мод больше, значит энергия нулевых колебаний ВЫШЕ дебаевской оценки.

  Что затрагивается:
    - уровень собственного шума среды и доля насыщения предела Швингера
      (тождество f = alpha/pi), то есть путь 4 к alpha;
    - оценка космологической постоянной, где сравнивается плотность
      энергии нулевых колебаний;
    - порог Линдемана <u^2>_L, входящий и в T-4, и в путь 10.

  Это не опровержение, а обязательство: 1.7 обязана быть пересчитана с
  плотностью состояний заклиненной упаковки, а не дебаевской.
""")


def isostatic_and_48pi():
    head("8. ИЗОСТАТИЧЕСКОЕ ЧИСЛО 2D = 6 И МНОЖИТЕЛЬ 3*2 В 48pi")
    print(f"    z_c = 2D = {2*3} при D = 3")
    print(f"    множитель в alpha_0 = 1/(48 pi):  48 = 3 * 2 * 8,  3*2 = 6")
    print("""
  Оба числа равны 2D и оба происходят из размерности пространства: три
  плоскости вращения на две поляризации есть тот же счёт, что даёт
  изостатическое условие Максвелла. Это не независимое совпадение, а одно
  и то же вычисление, записанное дважды.

  Практическое следствие для пути 6: множитель 6 в 48pi получает
  механическое прочтение — это число контактов, при котором упаковка
  становится жёсткой. Остаётся обосновать 8pi, а не 48pi целиком.

  ОГОВОРКА. Утверждение пока на уровне совпадения счёта, а не вывода:
  чтобы оно стало доводом, надо показать, что нормировка константы связи
  действительно идёт через число контактов, а не просто содержит то же
  число. Без этого шага пункт остаётся зацепкой, а не результатом.
""")


def horizon():
    head("9. ГОРИЗОНТ КАК ПЕРЕХОД РАСКЛИНИВАНИЯ")
    print("""
  Подглава 8.1 трактует горизонт как плавление: mu -> 0, критерий Борна.
  В языке заклинивания это точнее: mu -> 0 есть РАСКЛИНИВАНИЕ (unjamming),
  то есть обратный переход через ту же критическую точку, у которой
  среда и находится.

  Уточнение содержательное. Плавление есть переход первого рода с
  теплотой и скрытой энергией; расклинивание — переход в критической
  точке, у которого свои показатели. От этого зависит поведение вблизи
  горизонта: у плавления был бы скачок, у расклинивания — степенной
  закон. Модель уже выбрала степенной, mu/mu_inf = (1 - r_s/r)^2 (8.1),
  что отвечает расклиниванию, а не плавлению.

  Заодно объясняется, почему у среды вообще есть куда «плавиться»:
  она сидит В КРИТИЧЕСКОЙ ТОЧКЕ, а не глубоко в твёрдой фазе. Вакуум
  маргинально устойчив по построению — и именно это делает возможными
  и stick-slip проскальзывания (5.5), и горизонт.
""")


def report():
    facts()
    postulate_reduction()
    quantitative_conflict()
    a_req = resolution()
    effect_on_route10(a_req)
    hyperuniformity()
    boson_peak()
    isostatic_and_48pi()
    horizon()

    head("СВОДКА СВЕРКИ")
    print(f"""
  ПРИОБРЕТЕНИЯ

  1. Постулатов на один меньше: несжимаемость (1.6) есть следствие
     структуры среды (1.5), а не отдельное допущение. Все четыре мотива
     несжимаемости переносятся на заклинивание.

  2. T-14: гипероднородность перестаёт быть надеждой и становится
     обязательной. Подавление релеевского рассеяния следует из структуры.

  3. Путь 6 к alpha: множитель 6 = 3*2 в 48pi получает прочтение как
     изостатическое число контактов z_c = 2D. Остаётся обосновать 8pi.

  4. 8.1: горизонт есть РАСКЛИНИВАНИЕ, а не плавление. Степенной закон
     (1 - r_s/r)^2 отвечает критической точке, а не переходу первого рода.

  5. 5.5: маргинальная устойчивость объясняет, почему вакуум вообще
     допускает stick-slip проскальзывания.

  ДОЛГИ, ВСКРЫТЫЕ СВЕРКОЙ

  6. КОЛИЧЕСТВЕННОЕ ПРОТИВОРЕЧИЕ (главное). При планковской плотности
     G_сдвиг = rho c^2 = планковское давление, и 6.3 ставит туда же
     K_bulk. Тогда G/K ~ 1 против требуемых 1e-20 — промах на ДВАДЦАТЬ
     порядков. Совместить несжимаемость с планковской ячейкой нельзя.
     Удерживая K = P_Pl и G/K <= 1e-20, получаем ячейку примерно на пять
     порядков крупнее планковской. Это ужесточает T-3 до числа.

  7. 1.7 обязана быть пересчитана: у заклиненной упаковки плотность
     состояний не дебаевская, мягких мод больше, энергия нулевых
     колебаний выше. Затрагивает путь 4 к alpha, оценку космологической
     постоянной и порог Линдемана.

  8. Путь 10: delta_max зависит от положения УФ-обрезания. При сдвиге
     ячейки на пять порядков значение меняется с 0.0798 до {S_EFOLD*math.log(LAMBDABAR_C/((HBAR/((K_BULK_6_3*EPS_REQUIRED/C**2)*C))**0.25)):.4f}.
     Расчёт delta_max обязан идти вместе с фиксацией размера ячейки.
""")


if __name__ == "__main__":
    report()
