"""Несжимаемость как онтология масштабов энергий (T-3, 1.4.3, 6.3).

Развилка «строгая несжимаемость (K = inf) против конечного K_bulk»
переформулируется: среда сжимаема в принципе (K_bulk конечен, планковский
по 6.3), но энергия, нужная для измеримого сжатия любого объёма, лежит
за пределами всего, что есть во Вселенной, — и потому все наблюдаемые
результаты неотличимы от случая абсолютной несжимаемости. Это не постулат,
требующий теоремы, а бухгалтерия масштабов.

Что считается:
  1. энергия сжатия объёма V на относительную величину theta:
     E = (1/2) K theta² V — для V = 1 м³, объёма электрона (lambda_C³),
     объёма протона, одной ячейки d³; сравнение с массой-энергией
     наблюдаемой Вселенной (~1e70 Дж) и с энергией самого узла;
  2. сжатие, реально наводимое узлом: theta = (G/K) eps² (пуассоново
     сцепление сдвиг -> объём второго порядка) и его энергетическая
     цена относительно энергии узла: ~ G/K = eps_LI;
  3. порог по скорости: сжимаемость «включается», когда напряжения
     лоренц-сжатого узла (~gamma² G eps²) достигают K:
     gamma_* ~ sqrt(K/G), E_* = m c² sqrt(K/G) — оценка снизу при
     K/G >= 1e20 (граница 1.4.3/1.5.7); сравнение с космическими лучами;
  4. чёрная дыра: где напряжения достигают K и бухгалтерия перестаёт
     работать — планковская отсечка, а не горизонт (на горизонте G -> 0,
     и K/G только растёт).

Запуск:  python IncompressibilityBudget.py
"""

import math

C = 2.99792458e8
HBAR = 1.054571817e-34
EV = 1.602176634e-19
L_PL = 1.616255e-35
K_BULK = 1e113                    # Па, 6.3 (планковское давление ~4.6e113)
E_UNIVERSE = 1e70                 # Дж, масса-энергия наблюдаемой Вселенной (порядок)
M_E = 9.1093837e-31
M_P = 1.67262192e-27
LAMBDA_C_E = HBAR / (M_E * C)     # 3.86e-13 м
R_P = 0.84e-15


def head(t):
    print(); print("=" * 78); print(t); print("=" * 78)


def main():
    head("НЕСЖИМАЕМОСТЬ КАК БЮДЖЕТ ЭНЕРГИИ")
    print(f"\n  K_bulk = {K_BULK:.0e} Па (6.3), E_Вселенной ~ {E_UNIVERSE:.0e} Дж\n")
    print("  1. Энергия сжатия E = (1/2) K theta² V:")
    print("     объём                    V, м³      theta=1        theta=1e-3     theta=1e-10    E/E_Вселенной(theta=1e-3)")
    vols = [("1 м³", 1.0), ("электрон (lambda_C³)", LAMBDA_C_E ** 3),
            ("протон (r_p³)", R_P ** 3), ("ячейка d³, d = l_Pl", L_PL ** 3)]
    for name, V in vols:
        e = [0.5 * K_BULK * th ** 2 * V for th in (1.0, 1e-3, 1e-10)]
        print(f"     {name:24s} {V:9.1e}   {e[0]:12.2e}   {e[1]:12.2e}   {e[2]:12.2e}   {e[1] / E_UNIVERSE:10.1e}")
    e_node = M_E * C ** 2
    print(f"\n     для сравнения: энергия электрона m_e c² = {e_node:.2e} Дж, планковская {math.sqrt(HBAR * C ** 5 / 6.674e-11):.2e} Дж")
    print("""     Чтение: изменить плотность внутри объёма электрона на 0.1 % стоит
     ~1e70 Дж — массу-энергию всей наблюдаемой Вселенной; на одну ячейку
     при theta = 1 приходится ровно планковская энергия. Ни один процесс
     ниже планковского масштаба этой статьи бюджета не касается.
""")
    print("  2. Что реально наводит узел (сдвиг eps ~ eps_*, пуассоново сцепление):")
    for kg in (1e20, 1e30, 1e40):
        th = 1.0 / kg           # theta ~ (G/K) eps², eps ~ 1
        print(f"     K/G = {kg:.0e}: theta ~ {th:.0e}, цена сжатия / энергия узла ~ (G/K)/2 = {0.5 / kg:.0e}")
    print("""     Наведённое сжатие и его энергетическая цена идут по eps_LI = G/K —
     тому же параметру развязки, что и наведённая лоренц-неинвариантность
     (1.4.3). Все результаты модели при eps_LI <= 1e-20 неотличимы от
     случая K = inf: rho = const в гравитации (7), связь вместо моды в
     электродинамике (3.5), скобки Дирака (1.6.6) — всё с точностью
     1e-20 и лучше.
""")
    print("  3. Порог по скорости: gamma_* ~ sqrt(K/G), E_* = m c² gamma_*:")
    for kg in (1e20, 1e30, 1e40):
        g = math.sqrt(kg)
        print(f"     K/G = {kg:.0e}: gamma_* ~ {g:.0e};  электрон E_* ~ {M_E * C ** 2 * g / EV:.0e} эВ,"
              f"  протон E_* ~ {M_P * C ** 2 * g / EV:.0e} эВ")
    print("""     Космические лучи наблюдаются до ~1e20 эВ (протоны, gamma ~ 1e11) без
     признаков продольного канала: это даёт K/G >~ 1e22 — на два порядка
     сильнее границы 1.4.3 из delta c/c. Оценка грубая (сцепление сдвиг ->
     объём взято по порядку gamma² G eps² ~ K), но она показывает, ЧТО
     именно значит «нарушение ЛИ только у самой скорости света»: не при
     v -> c вообще, а при gamma >~ sqrt(K/G) — там, где напряжения
     сжатого узла добираются до объёмного модуля.
""")
    print("  4. Чёрная дыра.")
    print("""     На горизонте модель кладёт G -> 0 (расклинивание, 1.5.7, 8.1): K/G
     там не падает, а растёт — несжимаемость только крепнет. Бюджет
     ломается не на горизонте, а там, где напряжения достигают K, то есть
     на планковской плотности — внутри, у отсечки 6.3. Именно там (и
     только там) сценарии «строго несжимаемо» и «конечный K» расходятся;
     это и есть место, где к формулировке надо относиться осторожно.
""")


if __name__ == "__main__":
    main()
