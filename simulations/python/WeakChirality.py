def direction_np():
    head("3. НАПРАВЛЕНИЕ n -> p: РАСКЛАД ЧАСТОТ НА СОЛИТОНЕ")
    path = os.path.join(HERE, "torusbvp_results.json")
    if not os.path.exists(path):
        print("  нет torusbvp_results.json — пропуск")
        return
    data = json.load(open(path, encoding="utf-8"))
    best = {}
    for r in data.values():
        key = (int(round(r["Q"])), r["n"])
        if key not in best or r["E"] < best[key]["E"]:
            best[key] = r
    print("""
  Барион в модели (2.5.7, 4.13): три моды на одном солитоне, две
  из них — «пара» (одинаковая поляризация), третья — «одиночная»;
  протон и нейтрон различаются тем, какая подсистема сидит на МЕНЬШЕЙ
  частоте. Оценка энергий раскладов по посчитанным mu_n(Q) секторов
  2.8/2.9 (сумма частот занятых секторов при равном полном заряде):

      расклад A («пара ниже»):     2 mu_1 + mu_2     — кандидат в протон
      расклад B («одиночная ниже»): mu_1 + 2 mu_2    — кандидат в нейтрон
""")
    print(f"  {'Q':>6} {'mu_1':>9} {'mu_2':>9} {'2mu1+mu2':>10} {'mu1+2mu2':>10} {'B - A':>8}")
    for Q in (270, 740):
        r1, r2 = best.get((Q, 1)), best.get((Q, 2))
        if r1 and r2:
            A = 2 * r1["mu"] + r2["mu"]
            B = r1["mu"] + 2 * r2["mu"]
            print(f"  {Q:>6} {r1['mu']:>9.4f} {r2['mu']:>9.4f} {A:>10.4f} "
                  f"{B:>10.4f} {B - A:>+8.4f}")
    print("""
  B - A = mu_2 - mu_1 > 0 всюду (mu_2 менее отрицательна): расклад
  «одиночная ниже» ЛЕЖИТ ВЫШЕ расклада «пара ниже». Значит если нейтрон
  есть B, а протон — A, то n -> p идёт ВНИЗ по энергии — направление
  распада правильное. Разность мала (сотые доли mu при |mu| ~ 0.4),
  что качественно отвечает малости m_n - m_p = 1.29 МэВ против M ~ 940.

  Оговорка честная: это оценка на минимайзерах ОДИНОЧНЫХ секторов, а
  не на трёхмодовом солитоне; знак разности, однако, следует лишь из
  монотонности лестницы mu_n по n (2.8.5), которая устойчива.
""")


