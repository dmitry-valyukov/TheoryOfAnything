"""Слабый сектор из среды: хиральность перехода и подавление (T-38).

Что уже есть в модели (4.13): слабый переход = перестановка занятых и
свободных плоскостей вращения (комплементарность n + n' = 3), у кварков
реализуемая сменой поляризации линейная <-> круговая; подавление =
нерезонансность (G_F ~ 1/m_W^2). Чего нет: ХИРАЛЬНОСТИ. В природе слабый
ток связывает только одну спиральность (V - A), антинейтрино правые,
нейтрино левые. Откуда это в ахиральной среде?

Инструмент — спиральный базис 2.7.4: любое соленоидальное поле есть
сумма компонент h_+ и h_- (rot h_pm = pm k h_pm), спиральность
диагональна. В нём вопрос ставится точно: на какие спиральные
компоненты действует ОПЕРАТОР ПЕРЕХОДА, меняющий поляризацию моды?

Разделы:
  1. переход «линейная -> круговая» в спиральном базисе: оператор
     Delta = W_кр - W_лин; его проекции на h_+ и h_-. Результат: для
     линейной моды |a_+| = |a_-| (ахиральна), для круговой одна из
     компонент обнуляется; ТОК ПЕРЕХОДА (перекрёстный член) живёт
     ЦЕЛИКОМ в одной спиральной компоненте — это и есть V - A на языке
     среды. Знак компоненты (какая именно) = хиральность узла, то есть
     конвенция, физична только корреляция «знак спиральности бариона
     <-> знак спиральности лептонного тока».

  2. незамкнутая мода (нейтрино): без замыкания контура зеркальный
     партнёр не входит в спектр связанных состояний, у бегущей моды
     спиральность фиксирована знаком k.h — нейтрино одной спиральности
     по построению, антинейтрино — противоположной (C = зеркало, 2.7.7).

  3. направление n -> p на солитоне: энергия расклада «пара мод ниже»
     против «одиночная ниже» по посчитанным mu_n(Q) из 2.8/2.9 —
     оценка знака разности через сумму mu по занятым секторам.

  4. подавление: перекрытие эванесцентного хвоста; масштаб m_W как
     самая тяжёлая перестановочная мода — почему это единственное, чего
     среда не даёт без нового входа.

Расчёты к подглаве 4.13 (раздел 4.13.11+), пункт T-38.
Запуск:  python WeakChirality.py
"""

