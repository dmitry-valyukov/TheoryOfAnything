def suppression():
    head("4. ПОДАВЛЕНИЕ И МАСШТАБ m_W")
    print("""
  Перестановка поляризации — переход между двумя устойчивыми краями
  E(lambda) (2.5.7). Барьера нет, но переход требует ПРОМЕЖУТОЧНОГО
  возбуждения третьей плоскости (ранг 1 -> ранг 2 идёт через
  задействование новой плоскости), а её собственная частота лежит на
  масштабе полной перестройки узла — далеко выше Q распада. Амплитуда
  вдали от резонанса ~ (Q/Omega_W)^2 = ферми-подавление 4.13.7.

  Что среда даёт: форму подавления и её универсальность (одна и та же
  Omega_W для всех дублетов — комплементация одна). Чего НЕ даёт: числа
  Omega_W. Это единственный вход слабого сектора, которого не хватает,
  и он того же рода, что масса лептона в 2.10: динамика среды не
  выделяет масштаб, он калибровочный — либо выводим из зарядового
  сектора (4.14.11), где заряды дублетов уже сидят.
""")
    for name, Qd in (("нейтрон", 1.293), ("мюон", 105.66), ("тау", 1776.9)):
        print(f"      {name:>8}: (Q/m_W)^2 = {(Qd / 80379.0) ** 2:.2e}")


def verdict():
    head("ВЕРДИКТ ПО T-38 (продвижение)")
    print("""
  Получено средствами среды, без нового постулата:
    - V - A: ток перехода поляризации живёт в одной спиральной
      компоненте (J_+ = 1/sqrt2, J_- = 0); векторный ток взял бы обе поровну;
    - хиральность нейтрино = хиральность тока = хиральность узла;
      антинейтрино — C-зеркало; e_L и e_R — два вырожденных зеркала
      одного узла (масса связывает L и R, как в СМ);
    - направление n -> p: расклад «одиночная ниже» выше по энергии,
      распад идёт вниз; разность мала — как m_n - m_p;
    - форма подавления (Q/Omega_W)^2 и её универсальность по дублетам.

  Не получено: масштаб Omega_W (m_W) — калибровочный вход того же рода,
  что массы лептонов (2.10). Абсолютный знак хиральности — конвенция,
  физична корреляция знаков барион <-> лептонный ток.

  Обещание из проверки хиральности SpinorSim выполнено наполовину:
  слабый сектор действительно РАЗЛИЧАЕТ зеркала (V - A выведено),
  но не ВЫБИРАЕТ одно из них — этого ахиральная среда дать не может,
  выбор остаётся начальным условием Вселенной, как и в СМ.
""")


if __name__ == "__main__":
    helical_projection()
    unclosed_mode()
    direction_np()
    suppression()
    verdict()
