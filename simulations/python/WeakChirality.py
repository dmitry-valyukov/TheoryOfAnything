def unclosed_mode():
    head("2. НЕЗАМКНУТАЯ МОДА: ОДНА СПИРАЛЬНОСТЬ ПО ПОСТРОЕНИЮ")
    print("""
  Для замкнутого узла (лептон, кварк) оба зеркала (H и -H) — связанные
  состояния одной энергии (2.8: вырождены), и оба входят в спектр.
  Для НЕЗАМКНУТОЙ моды (4.13.8: нейтрино — конфигурация без замыкания
  контура) состояние — бегущее, с выделенным k, и его спиральность
  задана знаком (k . rot u): у бегущей соленоидальной моды h_+ и h_-
  — РАЗНЫЕ моды, а не два состояния одной.

  Следствие: то, что рождается в перестановке поляризации, наследует
  спиральность тока перехода — J живёт в одной компоненте (раздел 1),
  значит рождённая незамкнутая мода имеет ОДНУ спиральность.
  Зеркальная — рождается только зеркальным (C-сопряжённым) переходом.
  Это ровно «нейтрино левые, антинейтрино правые» — БЕЗ отдельного
  постулата: спиральность нейтрино = спиральность тока перехода =
  спиральность узла-родителя, все три — один знак.

  Что это НЕ объясняет: почему у замкнутых узлов оба зеркала
  наблюдаются как один лептон (электрон обеих спиральностей), а не как
  два. Ответ модели: спин 1/2 из репера (2.4) обеим спиральностям даёт
  одинаковый заряд и массу; различие — только в знаке H, а H = ±pq
  вырождены по энергии. То есть e_L и e_R — два зеркала одного узла с
  равной массой. В СМ это же формулируется как «масса связывает L и R».
""")


