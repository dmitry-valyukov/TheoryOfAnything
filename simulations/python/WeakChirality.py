def helical_projection():
    head("1. ПЕРЕХОД ПОЛЯРИЗАЦИИ В СПИРАЛЬНОМ БАЗИСЕ")
    print("""
  Мода с волновым вектором k вдоль z. Спиральный базис:
      h_+ = (x^ + i y^)/sqrt2,   h_- = (x^ - i y^)/sqrt2,   rot h_pm = pm k h_pm.
  Поляризации моды W (комплексная амплитуда, u = Re[W e^{-i w t}]):
      линейная (ранг 1):   W_L = x^                = (h_+ + h_-)/sqrt2
      круговая (ранг 2):   W_C = (x^ + i y^)/sqrt2 = h_+          (правая)
                       или W_C'= (x^ - i y^)/sqrt2 = h_-          (левая)
  Спиральные веса |a_+|^2, |a_-|^2 и оператор перехода Delta = W_C - W_L.
""")
    hp = np.array([1, 1j, 0]) / math.sqrt(2)
    hm = np.array([1, -1j, 0]) / math.sqrt(2)
    WL = np.array([1, 0, 0], dtype=complex)
    WC = hp.copy()
    WCp = hm.copy()

    def proj(W):
        return abs(np.vdot(hp, W)) ** 2, abs(np.vdot(hm, W)) ** 2

    print(f"  {'состояние':>26} {'|a_+|^2':>9} {'|a_-|^2':>9} {'спиральность':>13}")
    for name, W in (("линейная W_L", WL), ("круговая W_C (h_+)", WC),
                    ("круговая W_C' (h_-)", WCp)):
        p, m = proj(W)
        print(f"  {name:>26} {p:>9.3f} {m:>9.3f} {p - m:>+13.3f}")

    print("\n  оператор перехода Delta = W_C - W_L и ТОК перехода J = W_C^* . W_L:")
    for name, W in (("W_L -> W_C  (в h_+)", WC), ("W_L -> W_C' (в h_-)", WCp)):
        D = W - WL
        p, m = proj(D)
        # перекрёстный член: какая спиральная компонента W_L «участвует»
        # в переходе — проекция W_L на итоговое круговое состояние
        J_plus = np.vdot(hp, W) * np.conj(np.vdot(hp, WL))
        J_minus = np.vdot(hm, W) * np.conj(np.vdot(hm, WL))
        print(f"  {name:>26}: |Delta_+|^2={p:.3f} |Delta_-|^2={m:.3f}   "
              f"ток: J_+={abs(J_plus):.3f}  J_-={abs(J_minus):.3f}")
    print("""
  Читается так. Линейная мода АХИРАЛЬНА: |a_+| = |a_-| — она есть
  когерентная сумма двух спиральностей. Круговая — ОДНА спиральность.
  Переход «линейная -> круговая» есть выключение одной из двух
  спиральных компонент, и ТОК ПЕРЕХОДА J живёт целиком в одной
  спиральной компоненте (J_+ = 1/sqrt2, J_- = 0 для перехода в h_+;
  оператор Delta при этом несёт вклад в обеих — но J, амплитуда
  перехода, строго односторонняя).

  Это и есть V - A на языке среды: слабый ток — перестановка
  поляризации — связывает моду только через ОДНУ спиральность.
  Векторный ток (сохраняющий поляризацию) взял бы обе поровну.

  Какая именно (h_+ или h_-) — задаётся тем, В КАКУЮ круговую
  поляризацию уходит мода, то есть хиральностью самого узла (2.7.7:
  спин и топологический заряд развязаны, спиральность H = pq имеет
  знак). Абсолютный знак — конвенция (см. заголовок SpinorSim.py);
  физична КОРРЕЛЯЦИЯ: знак спиральности бариона фиксирует знак
  спиральности лептонного тока, а C-сопряжение (зеркало) обращает оба.
""")


