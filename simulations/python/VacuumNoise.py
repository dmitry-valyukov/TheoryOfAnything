RHO_LAMBDA_J_M3 = 5.36e-10      # [C] плотность тёмной энергии, Дж/м^3


def j_m3_to_mev_fm3(x: float) -> float:
    return x / MEV * FM3


def lambda_bar_e() -> float:
    """Приведённая комптоновская длина электрона, м."""
    return HBAR / (M_E * C)


# ---------------------------------------------------------------------------
# 1. Плотность энергии нулевых колебаний
# ---------------------------------------------------------------------------

def zpe_density(k_cutoff: float, n_pol: int = 2) -> float:
    """Плотность энергии нулевых колебаний до обрезания k_cutoff, Дж/м^3.

    u = n_pol * INT (hbar*omega/2) d^3k/(2pi)^3
      = n_pol * hbar*c*k_c^4 / (16 pi^2)

    Для двух поперечных поляризаций: u = hbar*c*k_c^4 / (8 pi^2).
    Продольной ветви нет — она вырождена в связь (1.1), поэтому n_pol = 2,
    а не 3. Это отличает подсчёт от обычного «вакуума КТП».
    """
    return n_pol * HBAR * C * k_cutoff ** 4 / (16.0 * math.pi ** 2)


def planck_energy_density() -> float:
    """E_Pl / l_Pl^3, Дж/м^3."""
    return E_PLANCK_J / L_PLANCK ** 3


# ---------------------------------------------------------------------------
# 2. Предел Швингера
# ---------------------------------------------------------------------------

def schwinger_field() -> float:
    """Критическое поле Швингера, В/м:  E_S = m^2 c^3 / (e hbar)."""
    return M_E ** 2 * C ** 3 / (E_CHARGE * HBAR)


def schwinger_density() -> float:
    """Плотность энергии при критическом поле, Дж/м^3.

    u_S = eps0 E_S^2 / 2 = m c^2 / (8 pi alpha lambda_bar^3)
    (второе выражение получено подстановкой e^2 = 4 pi eps0 hbar c alpha)
    """
    return 0.5 * EPS0 * schwinger_field() ** 2


def schwinger_density_analytic() -> float:
    lam = lambda_bar_e()
    return M_E * C ** 2 / (8.0 * math.pi * ALPHA * lam ** 3)


# ---------------------------------------------------------------------------
# 3. Отношение «шум / предел Швингера»
# ---------------------------------------------------------------------------

def saturation_fraction() -> dict:
    """Доля предела Швингера, занятая нулевыми колебаниями.

    Два способа сравнения — и оба дают величину, ТОЧНО пропорциональную alpha.

    (I) Интегральный: вся энергия нулевых мод с k < 1/lambda_bar.
        u = m c^2 / (8 pi^2 lambda_bar^3)
        f = u / u_S = alpha / pi

    (II) Поквантовый: один нулевой квант hbar*omega_e/2 на комптоновский объём.
        u = (m c^2 / 2) / lambda_bar^3
        f = 4 pi alpha
    """
    lam = lambda_bar_e()
    u_S = schwinger_density()

    u_int = zpe_density(1.0 / lam)                 # интегральный
    u_quantum = 0.5 * M_E * C ** 2 / lam ** 3      # поквантовый

    return {
        "u_S": u_S,
        "u_int": u_int,
        "u_quantum": u_quantum,
        "f_int": u_int / u_S,
        "f_quantum": u_quantum / u_S,
        "f_int_analytic": ALPHA / math.pi,
        "f_quantum_analytic": 4.0 * math.pi * ALPHA,
    }


def alpha_from_saturation() -> dict:
    """Что даёт гипотеза насыщения f = 1."""
    return {
        "int": math.pi,               # f = alpha/pi = 1  =>  alpha = pi
        "quantum": 1.0 / (4.0 * math.pi),
    }


