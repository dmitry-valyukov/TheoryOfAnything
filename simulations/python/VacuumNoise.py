K_EV_PER_K = 8.617333262e-5           # эВ/К
GAP_EV = 2.0 * 510998.95              # 2 m_e c^2 в эВ


def pair_population(T_kelvin: float) -> float:
    """Равновесная относительная населённость реальных пар при щели 2 m c^2."""
    x = GAP_EV / (K_EV_PER_K * T_kelvin)
    return math.exp(-x) if x < 700 else 0.0


