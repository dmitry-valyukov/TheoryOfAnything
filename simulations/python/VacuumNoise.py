# 4b. Докритическое рождение пар: интеграл по хвосту распределения
# ---------------------------------------------------------------------------

def subcritical_exponent(alpha: float = ALPHA) -> float:
    """Показатель подавления рождения пар шумом с гауссовым распределением поля.

    Швингеровская скорость рождения пар в поле E:
        Gamma(E) ~ exp(-pi E_S / E)
    Она не обращается в нуль ниже критического поля, а лишь экспоненциально
    подавлена. Если поле есть шум с гауссовым распределением и дисперсией
    sigma, полная скорость получается интегрированием:

        R ~ INT exp(-E^2 / 2 sigma^2) exp(-pi E_S / E) dE

    Метод перевала: максимум подынтегральной функции при E* = (pi E_S sigma^2)^(1/3),
    и показатель в точке перевала равен

        W = (3/2) (pi E_S / sigma)^(2/3)

    Дисперсия шума связана с его плотностью энергии: eps0 <E^2> = u, откуда
        (sigma / E_S)^2 = u / (eps0 E_S^2) = u / (2 u_S) = f / 2 = alpha / (2 pi)

    Подстановка даёт W как функцию ОДНОЙ ЛИШЬ alpha:
        W = (3/2) pi^(2/3) (2 pi / alpha)^(1/3)
    """
    return 1.5 * math.pi ** (2.0 / 3.0) * (2.0 * math.pi / alpha) ** (1.0 / 3.0)


def alpha_from_exponent(W: float) -> float:
    """Обращение: какая alpha отвечает заданному показателю подавления."""
    return 2.0 * math.pi / (W / (1.5 * math.pi ** (2.0 / 3.0))) ** 3


def cosmological_cutoff() -> dict:
    """Что даёт обрезание спектра шума на пороге рождения пар вместо планковского."""
    hbarc_mev_fm = 197.3269804
    me_mev = 0.51099895
    lam_fm = hbarc_mev_fm / me_mev
    # u = hbar c k^4 / (8 pi^2), в МэВ/фм^3, для k = n / lam
    u_e = me_mev / (8.0 * math.pi ** 2 * lam_fm ** 3)          # k = 1/lam
    u_2e = 16.0 * u_e                                          # k = 2/lam (порог 2 m c^2)
    rho_lambda = j_m3_to_mev_fm3(RHO_LAMBDA_J_M3)
    u_planck_zpe = j_m3_to_mev_fm3(zpe_density(1.0 / L_PLANCK))
    return {
        "lam_fm": lam_fm,
        "u_e": u_e, "u_2e": u_2e,
        "rho_lambda": rho_lambda,
        "orders_planck": math.log10(u_planck_zpe / rho_lambda),
        "orders_e": math.log10(u_e / rho_lambda),
        "orders_2e": math.log10(u_2e / rho_lambda),
    }


