"""BellQuadrupole.py — может ли мгновенный квадрупольный канал дать нарушение Белла.

Расчёты к подглаве theory/09-2-kvadrupolnyy-kanal-i-bell.md.

Подглава 1.6 показала: в несжимаемой среде поле давления определяется
эллиптическим уравнением, решение берётся по всему пространству без
запаздывания, а дальнее поле локализованного солитона КВАДРУПОЛЬНО,
p ~ Q_kl / r^3 (структура аналогии Лайтхилла).

Глава 9 объявляет этот канал носителем квантовой нелокальности. Здесь
проверяется, что из этого следует численно. Четыре теста:

  1. Угловая структура: квадрупольная связь a.Q.a имеет период pi, а не 2pi.
  2. Локальный предел: общий (разделяемый) квадруполь даёт ровно S = 2.
  3. Мгновенная добавка: сколько S покупается и какой ценой в сигнализации.
  4. Верхняя граница: неограниченный мгновенный канал даёт S = 4, а не 2.83.

Запуск:
    python BellQuadrupole.py
"""

from __future__ import annotations

import numpy as np

TSQRT2 = 2.0 * np.sqrt(2.0)          # квантовый предел Цирельсона
N_PHI = 2_000_001          # узлов сетки по скрытому параметру
SEED = 20260813

# Канонические углы CHSH для поляризации (период pi -> шаг pi/8)
CANONICAL_POL = (0.0, np.pi / 4.0, np.pi / 8.0, 3.0 * np.pi / 8.0)


# ---------------------------------------------------------------------------
# 1. Квадрупольная связь и её угловая структура
# ---------------------------------------------------------------------------

def quadrupole_response(theta: np.ndarray, phi: np.ndarray) -> np.ndarray:
    """Отклик анализатора с ориентацией theta на квадруполь с осью phi.

    Симметричный бесследовый тензор в плоскости имеет две компоненты,
    (Q11 - Q22)/2 и Q12, и параметризуется одним углом phi:
        a.Q.a - tr/2 = r * cos(2 theta - 2 phi)

    Отсюда главное структурное свойство: зависимость идёт ТОЛЬКО через
    удвоенный угол. Период pi, а не 2pi. Это в точности угловая структура
    поляризационных измерений (закон Малюса), а НЕ спина 1/2.
    """
    return np.cos(2.0 * theta - 2.0 * phi)


def angular_period_test() -> dict:
    """Проверяет, что отклик имеет период pi, а корреляция спина 1/2 — 2pi."""
    phi = 0.3
    th = np.linspace(0.0, 2.0 * np.pi, 2001)
    q = quadrupole_response(th, phi)
    half = len(th) // 2
    # сдвиг на pi
    shifted = quadrupole_response(th + np.pi, phi)
    return {
        "max_diff_pi_shift": float(np.max(np.abs(q - shifted))),
        "max_diff_pi_shift_dipole": float(
            np.max(np.abs(np.cos(th - phi) - np.cos(th + np.pi - phi)))),
        "unused": half,
    }


# ---------------------------------------------------------------------------
# 2. Локальная модель: общий квадруполь без мгновенной связи
# ---------------------------------------------------------------------------

def outcomes_local(theta_a, theta_b, phi):
    """Исходы при чисто локальной связи с общей осью quadrupole phi."""
    A = np.sign(quadrupole_response(theta_a, phi))
    B = -np.sign(quadrupole_response(theta_b, phi))
    return A, B


# ---------------------------------------------------------------------------
# 3. Мгновенная добавка: удалённая настройка тянет общую ось
# ---------------------------------------------------------------------------

def outcomes_instant(theta_a, theta_b, phi, chi):
    """Мгновенный канал: ось, видимая каждой стороной, смещена удалённой настройкой.

    Физическая мотивировка: анализатор возмущает среду, поле давления
    пересчитывается по всему пространству без запаздывания (1.6), значит
    ориентация квадруполя, «видимая» партнёром, сдвигается мгновенно.

    Простейшая симметричная форма: удалённая настройка притягивает ось,
        phi_A = phi + chi * sin(2(theta_b - phi)) / 2
        phi_B = phi + chi * sin(2(theta_a - phi)) / 2
    При chi = 0 модель локальна и совпадает с предыдущей.
    """
    phi_A = phi + 0.5 * chi * np.sin(2.0 * (theta_b - phi))
    phi_B = phi + 0.5 * chi * np.sin(2.0 * (theta_a - phi))
    A = np.sign(quadrupole_response(theta_a, phi_A))
    B = -np.sign(quadrupole_response(theta_b, phi_B))
    return A, B


# ---------------------------------------------------------------------------
# 4. CHSH и проверка на сигнализацию
# ---------------------------------------------------------------------------

# Детерминированная сетка по скрытому параметру phi: точнее Монте-Карло и
# не создаёт шума, который можно спутать с сигнализацией.
PHI_GRID = (np.arange(N_PHI) + 0.5) * np.pi / N_PHI


def correlation(theta_a, theta_b, chi, rng=None):
    phi = PHI_GRID
    if chi == 0.0:
        A, B = outcomes_local(theta_a, theta_b, phi)
    else:
        A, B = outcomes_instant(theta_a, theta_b, phi, chi)
    return float(np.mean(A * B)), float(np.mean(A)), float(np.mean(B))


def chsh(chi, rng, angles=CANONICAL_POL):
    a, ap, b, bp = angles
    e = {}
    for x, y in ((a, b), (a, bp), (ap, b), (ap, bp)):
        e[(x, y)] = correlation(x, y, chi, rng)[0]
    return abs(e[(a, b)] - e[(a, bp)] + e[(ap, b)] + e[(ap, bp)])


def signalling(chi, rng, angles=CANONICAL_POL):
    """Максимальный сдвиг МАРГИНАЛА одной стороны при смене настройки другой.

    Условие несигнализации: P(A=+1 | a, b) не зависит от b.
    Возвращает max по парам настроек модуля разности маргиналов.
    """
    a, ap, b, bp = angles
    worst = 0.0
    for x in (a, ap):
        m = [correlation(x, y, chi, rng)[1] for y in (b, bp)]
        worst = max(worst, abs(m[0] - m[1]))
    for y in (b, bp):
        m = [correlation(x, y, chi, rng)[2] for x in (a, ap)]
        worst = max(worst, abs(m[0] - m[1]))
    return worst


# ---------------------------------------------------------------------------
# 5. Алгебраический максимум: PR-бокс
# ---------------------------------------------------------------------------

def pr_box_chsh(rng, n=200_000):
    """Неограниченный мгновенный канал: каждая сторона знает обе настройки.

    Ящик Попеску — Рорлиха: A xor B = x AND y. Даёт S = 4 — алгебраический
    максимум, ВЫШЕ квантового 2.83. Показывает, что мгновенная связь сама
    по себе даёт СЛИШКОМ много, а не слишком мало.
    """
    lam = np.array([0, 1])          # точное перечисление, а не выборка
    s = 0.0
    marg_a, marg_b = {}, {}
    for x in (0, 1):
        for y in (0, 1):
            A = lam
            B = (lam ^ (x & y))
            ea = 1 - 2 * A
            eb = 1 - 2 * B
            corr = float(np.mean(ea * eb))
            s += -corr if (x == 1 and y == 1) else corr
            marg_a[(x, y)] = float(np.mean(ea))
            marg_b[(x, y)] = float(np.mean(eb))
    sig = max(
        max(abs(marg_a[(x, 0)] - marg_a[(x, 1)]) for x in (0, 1)),
        max(abs(marg_b[(0, y)] - marg_b[(1, y)]) for y in (0, 1)),
    )
    return abs(s), sig


