def noisy_pr_chsh(p: float) -> float:
    """CHSH изотропно зашумлённого ящика Попеску - Рорлиха: S(p) = 4 p.

    Ящик с вероятностью p ведёт себя как ПР, иначе выдаёт некоррелированный
    шум. Смесь остаётся НЕсигнализирующей при любом p (маргиналы обоих
    слагаемых равны 1/2), а корреляции просто масштабируются. Отсюда
    S = 2 при p = 1/2 и S = 2 sqrt(2) при p = 1/sqrt(2).
    """
    return 4.0 * p


