try:
    from scipy.special import erf as _erf
except ImportError:                                    # запасной путь без scipy
    import math as _math
    _ufunc = np.frompyfunc(_math.erf, 1, 1)
    def _erf(x):
        return _ufunc(np.asarray(x, dtype=float)).astype(float)

PHI_N = (np.arange(200_001) + 0.5) * np.pi / 200_001


def correlation_noisy(theta_a, theta_b, sigma):
    """Корреляция при пороговом детекторе, погружённом в локальный шум.

    A = sign(cos(2 th_a - 2 phi) + n_A),  B = -sign(cos(2 th_b - 2 phi) + n_B),
    n — независимый гауссов шум с дисперсией sigma. Усреднение по шуму берётся
    аналитически: <sign(x + n)> = erf(x / (sigma sqrt2)).
    """
    ca = np.cos(2.0 * theta_a - 2.0 * PHI_N)
    cb = np.cos(2.0 * theta_b - 2.0 * PHI_N)
    if sigma == 0.0:
        return -float(np.mean(np.sign(ca) * np.sign(cb)))
    k = 1.0 / (sigma * np.sqrt(2.0))
    return -float(np.mean(_erf(ca * k) * _erf(cb * k)))


def visibility_and_shape(sigma, n_pts=181):
    """Амплитуда косинусной гармоники V и относительная ошибка формы."""
    d = np.linspace(0.0, np.pi, n_pts)
    curve = np.array([correlation_noisy(0.0, x, sigma) for x in d])
    V = -(2.0 / np.pi) * np.trapezoid(curve * np.cos(2.0 * d), d)
    resid = curve - (-V * np.cos(2.0 * d))
    err = float(np.sqrt(np.mean(resid ** 2)) / max(abs(V), 1e-30))
    return float(V), err


def chsh_noisy(sigma, angles=CANONICAL_POL):
    a, ap, b, bp = angles
    e = {(x, y): correlation_noisy(x, y, sigma)
         for x, y in ((a, b), (a, bp), (ap, b), (ap, bp))}
    return abs(e[(a, b)] - e[(a, bp)] + e[(ap, b)] + e[(ap, bp)])


