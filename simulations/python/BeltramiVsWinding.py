"""
T-43: на какой ветви живёт солитон — Арнольда (регулярные торы) или
Бельтрами (минимум энергии при фиксированной спиральности)?

Развилка поставлена в 2.7.5. Здесь она ЗАКРЫВАЕТСЯ, тремя независимыми
доводами, каждый со своим расчётом:

  1. ветвь Бельтрами ПУСТА для локализованного объекта: теорема
     Лиувилля (Надирашвили 2014; Чае - Константин 2015) запрещает
     локализованные поля Бельтрами с конечной энергией. Проверка на
     руках для l = 1: условия обнуления нормальной и касательных
     компонент на границе шара несовместны (нет общих корней).

  2. даже был бы минимум Бельтрами достижим геометрически, он недостижим
     ДИНАМИЧЕСКИ: релаксация к Бельтрами (сценарий Тейлора) требует
     реконнекции линий поля, реконнекция требует диссипации, а среда
     ниже порога расклинивания бездиссипативна (7.2). Топология орбит
     вморожена. При этом сохраняется и объём носителя (несжимаемость!),
     а вместе с ним - нижняя граница Арнольда  E >= x1 |H| / (2a).
     Минимайзер на листе вмороженной топологии стационарен и
     НЕ-бельтрамиев => структурная теорема Арнольда => торы.

  3. цена намотки: kappa(A) = a int|rot u|^2 / (x1 |H|) >= 1 для
     тороидальной трубки с намоткой, минимум по соотношению сторон
     A = R/r. Положение минимума - первый расчётный ответ на вопрос,
     откуда берётся A (до сих пор R = r постулировалось).

     Существенно, что энергия здесь УПРУГАЯ, int mu |grad u|^2 - для
     соленоидального поля это int mu |rot u|^2. Соответствие с магнитной
     релаксацией: B <-> rot u, A <-> u, магнитная энергия <-> упругая,
     магнитная спиральность int A.B <-> H = int u . rot u. Теорема
     Волтьера тогда даёт E_upr >= (mu/2) (x1/a) |H| с равенством только
     на поле Бельтрами.

Итог: ветвь Бельтрами закрыта дважды (кинематически теоремой Лиувилля,
динамически бездиссипативностью), солитон живёт на ветви Арнольда,
тороидальное расслоение орбит ВЫНУЖДЕНО.

Расчёты к подглаве theory/02-8-vetv-arnolda.md.
Запуск:  python BeltramiVsWinding.py
"""

import math

import numpy as np
from scipy.optimize import brentq

X1 = 4.493409457909064  # первый корень tan x = x = первый нуль j1


def head(t):
    print()
    print("=" * 78)
    print(t)
    print("=" * 78)


# ---------------------------------------------------------------- 1
def j0(x):
    return np.sin(x) / x


def j1(x):
    return np.sin(x) / x ** 2 - np.cos(x) / x


def liouville_l1():
    head("1. ВЕТВЬ БЕЛЬТРАМИ ПУСТА: ЛОКАЛИЗОВАННЫХ ПОЛЕЙ БЕЛЬТРАМИ НЕТ")
    print("""
  Общая теорема (Надирашвили 2014; Чае - Константин 2015): поле Бельтрами
  rot u = lambda u с постоянной lambda != 0 в R^3, имеющее конечную
  энергию (или убывающее быстрее 1/|x|), тождественно равно нулю.
  Сферомак существует только благодаря СТЕНКЕ (проводящей границе);
  у вакуумной среды стенки нет.

  Проверка на руках для младшей моды l = 1 (поле Чандрасекара - Кендалла
  в шаре радиуса a, x = lambda a):

      нормальная компонента на границе:    u_r ~ j1(x)/x        = 0
      касательные компоненты на границе:   psi(x) = j0(x) - j1(x)/x = 0

  Продолжение нулём наружу требует обнуления ВСЕХ компонент сразу,
  то есть общего корня j1 и psi. Но в нуле j1 имеем psi = j1'(x)
  (из j1' = j0 - 2 j1/x), а j1 и j1' не могут обнулиться одновременно
  (единственность решения уравнения Бесселя). Числа:
""")
    # корни j1 (они же корни tan x = x) и значения psi в них
    roots_j1 = []
    for k in range(1, 21):
        lo, hi = k * math.pi + 1e-9, (k + 1) * math.pi - 1e-9
        roots_j1.append(brentq(lambda x: math.tan(x) - x if abs(math.cos(x)) > 1e-12 else 1.0,
                               k * math.pi + math.pi / 2 + 1e-9,
                               k * math.pi + 1.5 * math.pi - 1e-9, xtol=1e-13))
    roots_j1 = [X1] + roots_j1
    roots_j1 = sorted(set(round(r, 10) for r in roots_j1))[:12]

    def psi(x):
        return float(j0(np.array([x]))[0] - j1(np.array([x]))[0] / x)

    print(f"  {'нуль j1 (x_n)':>16} {'psi(x_n)':>12} {'|psi|':>9}")
    minabs = np.inf
    for r in roots_j1:
        v = psi(r)
        minabs = min(minabs, abs(v))
        print(f"  {r:>16.6f} {v:>12.6f} {abs(v):>9.4f}")
    print(f"""
  min |psi| по первым {len(roots_j1)} нулям = {minabs:.4f} — отделён от нуля.
  Асимптотика |psi(x_n)| -> 1/x_n * ... убывает, но нулей нет ни при каком n:
  общий корень потребовал бы j1 = j1' = 0.

  ВЫВОД: локализованное состояние Бельтрами не существует. Лестница
  сферомака из 2.7.6 - объект со стенкой, у солитона её нет.
""")


