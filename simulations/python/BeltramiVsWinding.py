def frozen_topology():
    head("2. ДИНАМИЧЕСКИЙ ЗАПРЕТ: БЕЗ ДИССИПАЦИИ НЕТ РЕЛАКСАЦИИ ТЕЙЛОРА")
    print("""
  Сценарий, которым плазма приходит к состоянию Бельтрами (релаксация
  Тейлора), устроен так: реконнекция уничтожает все топологические
  инварианты, КРОМЕ полной спиральности H, и система скатывается к
  минимуму E при фиксированном H - полю Бельтрами. Реконнекция есть
  диссипативный процесс (конечная проводимость, вязкость).

  В вакуумной среде ниже порога расклинивания диссипации нет (7.2).
  Следовательно:

    - реконнекция запрещена, топология КАЖДОЙ линии поля вморожена;
    - доступные движения - сохраняющие объём диффеоморфизмы
      (несжимаемость!), поэтому ОБЪЁМ НОСИТЕЛЯ V сохраняется;
    - расползание, обесценивающее энергию при фиксированном H
      (E -> 0 при раздувании), требует роста V и потому запрещено;
    - остаётся минимизация на листе вмороженной топологии. Её нижняя
      граница - неравенство Арнольда для УПРУГОЙ энергии:

          E_upr = (mu/2) int |rot u|^2 >= (mu/2) (x1/a) |H|,
          a = (3V/4pi)^(1/3),  x1 = 4.49341

      (спектральная щель ротора на области объёма V; соответствие с
      магнитной релаксацией B <-> rot u, int A.B <-> int u.rot u);
      минимайзер листа стационарен, не-бельтрамиев => по структурной
      теореме Арнольда (2.7.5) носитель расслоён на инвариантные ТОРЫ.
      Расползание тоже проигрывает: при раздувании x -> lam x с
      сохранением H упругая энергия падает как 1/lam, но требует роста
      объёма носителя lam^3 - а объём вморожен несжимаемостью.

  Замечательно, что оба запрета обеспечивает сама несжимаемость:
  она сохраняет объём (пункт про расползание) и она же дает поперечность,
  из которой в 2.7 получено всё остальное. Это второе место после 1.5.7,
  где маргинальный джемминг не мешает модели, а строит её.
""")


