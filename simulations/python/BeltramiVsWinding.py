def make_grid(N, L):
    dx = L / N
    x = (np.arange(N) - N // 2) * dx
    X, Y, Z = np.meshgrid(x, x, x, indexing="ij")
    k1 = 2.0 * math.pi * np.fft.fftfreq(N, d=dx)
    KX, KY, KZ = np.meshgrid(k1, k1, k1, indexing="ij")
    return X, Y, Z, KX, KY, KZ, dx


def winding_cost(N=96, L=20.0):
    head("3. ЦЕНА НАМОТКИ kappa(A) И ОПТИМАЛЬНОЕ СООТНОШЕНИЕ СТОРОН")
    print("""
  Для тороидальной трубки (полоидаль + тороидаль, реальное поле) считаем
      E2 = int |rot u|^2,  H = int u . rot u,  a = радиус носителя,
      kappa(A) = a E2 / (x1 |H|) >= 1  (равенство - только Бельтрами).
  kappa показывает, во сколько раз упругая энергия намотки дороже
  недостижимого минимума Волтьера, а её минимум по A = R/r отвечает,
  какое соотношение сторон энергетически выгодно при данной спиральности.
""")
    X, Y, Z, KX, KY, KZ, dx = make_grid(N, L)
    RHO = np.sqrt(X ** 2 + Y ** 2)
    PHI = np.arctan2(Y, X)
    K2 = KX ** 2 + KY ** 2 + KZ ** 2
    dV = dx ** 3
    npt = N ** 3

    def fftv(W):
        return np.fft.fftn(W, axes=(1, 2, 3))

    def ifftv(Wh):
        return np.fft.ifftn(Wh, axes=(1, 2, 3))

    results = []
    r_t = 1.0
    for A in (1.0, 1.25, 1.5, 2.0, 2.5, 3.0, 4.0, 5.0, 6.5):
        R0 = A * r_t
        S2 = (RHO - R0) ** 2 + Z ** 2
        F = np.exp(-S2 / (2.0 * (r_t / 2.0) ** 2))
        ephi = np.stack([-np.sin(PHI), np.cos(PHI), np.zeros_like(PHI)])
        # полоидаль из векторного потенциала + тороидаль
        Ah = fftv((ephi * F).astype(np.complex128))
        upol = ifftv(np.stack([1j * (KY * Ah[2] - KZ * Ah[1]),
                               1j * (KZ * Ah[0] - KX * Ah[2]),
                               1j * (KX * Ah[1] - KY * Ah[0])])).real
        u = upol + F * ephi
        # соленоидальная проекция (точная)
        uh = fftv(u.astype(np.complex128))
        kd = KX * uh[0] + KY * uh[1] + KZ * uh[2]
        with np.errstate(invalid="ignore", divide="ignore"):
            f = np.where(K2 > 0, kd / np.where(K2 > 0, K2, 1.0), 0.0)
        uh[0] -= KX * f
        uh[1] -= KY * f
        uh[2] -= KZ * f
        u = ifftv(uh).real
        uh = fftv(u.astype(np.complex128))
        wh = np.stack([1j * (KY * uh[2] - KZ * uh[1]),
                       1j * (KZ * uh[0] - KX * uh[2]),
                       1j * (KX * uh[1] - KY * uh[0])])
        w = ifftv(wh).real
        E2 = float((w ** 2).sum() * dV)      # int |rot u|^2
        H = float((u * w).sum() * dV)
        # радиус носителя: 99.5% энергии
        r2 = (X ** 2 + Y ** 2 + Z ** 2).ravel()
        e_loc = (w ** 2).sum(axis=0).ravel()
        order = np.argsort(r2)
        cum = np.cumsum(e_loc[order])
        a_enc = math.sqrt(r2[order][np.searchsorted(cum, 0.995 * cum[-1])])
        kappa = a_enc * E2 / (X1 * abs(H))
        results.append((A, E2, H, a_enc, kappa))

    print(f"  {'A = R/r':>8} {'int|rot u|^2':>13} {'H':>10} {'a_enc':>7} {'kappa':>8}")
    for A, E2, H, a_enc, kappa in results:
        print(f"  {A:>8.2f} {E2:>13.4f} {H:>10.4f} {a_enc:>7.3f} {kappa:>8.4f}")
    best = min(results, key=lambda t: t[4])
    print(f"""
  минимум цены: kappa = {best[4]:.4f} при A = R/r = {best[0]:.2f}

  Читается это так. kappa > 1 всюду - намотка всегда дороже
  (недостижимого) минимума Волтьера, как и должно быть. kappa растёт
  с A МОНОТОННО, почти линейно, и минимальна на границе A = 1 - на
  рог-торе (при A < 1 трубка самопересекается, тора уже нет). Компактный
  тор с R = r платит за спиральность втрое меньше тонкого кольца
  с A = 4...6. Это первый расчётный довод в пользу рог-тора, который
  до сих пор был чистым постулатом.
""")
    return results


def verdict():
    head("ВЕРДИКТ ПО T-43")
