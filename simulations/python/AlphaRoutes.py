import math

# --- измеренные величины (CODATA) ---------------------------------------
ALPHA = 7.2973525693e-3
INV_ALPHA = 1.0 / ALPHA
M_E_GEV = 0.51099895000e-3
M_PL_GEV = 1.220890e19            # планковская масса
R_E_M = 2.8179403262e-15          # классический радиус электрона
LAMBDABAR_C_M = 3.8615926796e-13  # приведённая комптоновская длина
