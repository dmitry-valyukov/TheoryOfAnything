def route_inversion():
    head("9. ПУТЬ 13: ОБРАТИТЬ ЗАДАЧУ — СПЕКТР ИЗ БЕГА alpha")
    print("""
  Идея: не выводить alpha из поляризации по заряженным парам, а наоборот —
  взять измеренный бег alpha и прочесть по нему спектр заряженных частиц.

  Бег задаётся суммой по частицам ниже масштаба:

      1/alpha(mu) = 1/alpha(m_e) - (2b/3pi) ln(mu/m_e),   b = sum N_c Q^2

  Каждая заряженная частица даёт излом кривой на своей массе. Значит
  измеренный бег ЕСТЬ спектроскопия вакуума.
""")
    from fractions import Fraction as F
    lep = F(1) * F(-1) ** 2
    up = F(3) * F(2, 3) ** 2
    dn = F(3) * F(-1, 3) ** 2
    per = lep + up + dn
    print("  ЧТО МОДЕЛЬ ДАЁТ НЕЗАВИСИМО ОТ alpha:")
    print("    заряды 2/3 и -1/3 — из доли цветового обхода (5.11)")
    print("    число цветов N_c = 3 — из размерности D = 3 (5.1)")
    print()
    print(f"    вклад одного поколения:  {lep} (лептон) + {up} (up) + {dn} (down) = {per}")
    print()
    print(f"  ЧТО ИЗМЕРЕНО ПО БЕГУ:  b = sum N_c Q^2 = 8   (4.10)")
    print()
    print(f"  ОТСЮДА:  N_поколений = 8 / ({per}) = {F(8)/per}   — РОВНО ТРИ")
    print()
    print("  КОНТРОЛЬНЫЙ ТЕСТ (проверка на неслучайность):")
    print(f"  {'если бы...':>28} {'вклад поколения':>18} {'N_поколений':>16}")
    for name, p in (("заряды кварков +-1/2", F(1) + F(3)*F(1,2)**2 + F(3)*F(1,2)**2),
                    ("цветов 2", F(1) + F(2)*F(2,3)**2 + F(2)*F(1,3)**2),
                    ("цветов 4", F(1) + F(4)*F(2,3)**2 + F(4)*F(1,3)**2)):
        print(f"  {name:>28} {str(p):>18} {float(F(8)/p):>16.3f}")
    print("""
  Все три контрольных варианта дают НЕЦЕЛОЕ число поколений. Значит
  совпадение не автоматическое: подстановка неверных зарядов или неверного
  числа цветов результат разрушает. Это настоящая проверка, а не тавтология.

  ЧТО ПУТЬ 13 ДАЁТ:
    - число поколений РОВНО ТРИ, из измеренного бега плюс собственные
      заряды модели. Это прямой вклад в T-20;
    - перекрёстную проверку зарядов 2/3 и -1/3 по независимому каналу.

  ЧТО ПУТЬ 13 НЕ ДАЁТ, и это надо сказать прямо:
    изломы кривой стоят РОВНО НА МАССАХ частиц. Прочесть их — значит
    измерить массы, а не вывести. Инверсия даёт СЧЁТ и подтверждает
    ЗАРЯДЫ, но не даёт ЗНАЧЕНИЙ масс. T-7 она не спасает.
""")


