# ------------------------------------- 3. путь «сечение рассеяния»

def route_scattering():
    head("3. ПУТЬ «СЕЧЕНИЕ РАССЕЯНИЯ»")
    r_from_sigma = math.sqrt(SIGMA_T_M2 * 3.0 / (8.0 * math.pi))
    print(f"  томсоновское сечение   sigma_T = {SIGMA_T_M2:.6e} м^2")
    print(f"  отсюда r_e = sqrt(3 sigma_T / 8 pi) = {r_from_sigma:.6e} м")
    print(f"  сверка с табличным r_e             = {R_E_M:.6e} м"
          f"   (расхожд. {abs(r_from_sigma-R_E_M)/R_E_M:.1e})")
    print("""
  Идея пути: рассеяние поперечной волны на упругом включении — классическая
  задача механики сплошных сред, полностью вычислимая. Солитон есть область
  с иным модулем сдвига; сечение рассеяния сдвиговой волны на нём даёт r_e,
  а через него alpha (путь 2).

  НЕМЕДЛЕННАЯ ПРОВЕРКА, и она жёсткая. Рэлеевское рассеяние на включении
  размера a даёт сечение

      sigma ~ a^2 (k a)^4     то есть  sigma ~ omega^4

  а томсоновское сечение от частоты НЕ ЗАВИСИТ вовсе. Значит модель обязана
  объяснить, откуда берётся omega^0: это не рэлеевский предел, а резонансный
  (дипольный) отклик свободно движущегося включения. Пока этот переход не
  показан, путь не начат. Зато проверка дешёвая и делается первой.""")


# --------------------------- 4. путь «полюс Ландау на масштабе ячейки»

def route_landau():
    head("4. ПУТЬ «ПОЛЮС ЛАНДАУ НА МАСШТАБЕ ЯЧЕЙКИ» — ПРОВЕРЕН")
    print("""
  Идея: у среды есть физическое обрезание — размер ячейки a = l_Pl. Если
  потребовать, чтобы полюс Ландау КЭД пришёлся ровно на это обрезание,
  величина alpha определяется однозначно, без единого подгоночного числа.

  Однопетлевой бег:  1/alpha(mu) = 1/alpha(m_e) - (2b/3pi) ln(mu/m_e),
  где b = sum N_c Q^2 по частицам ниже mu. Полюс: 1/alpha(Lambda) = 0.
""")
    L = math.log(M_PL_GEV / M_E_GEV)
    print(f"  ln(M_Pl / m_e) = {L:.4f}")
    print()
    print(f"  {'b = sum N_c Q^2':>18} {'1/alpha':>12} {'промах':>12}")
    for b, note in ((1.0, "только электрон"), (8.0, "полный набор, 4.10")):
        inv = (2.0 * b / (3.0 * math.pi)) * L
        print(f"  {b:>10.0f} ({note:>15}) {inv:>12.3f} {abs(inv-INV_ALPHA)/INV_ALPHA:>11.1%}")
    print()
    b_need = INV_ALPHA / ((2.0 / (3.0 * math.pi)) * L)
    print(f"  какое b дало бы ровно 137.036:  b = {b_need:.4f}   — не целое")
    lam_need = M_E_GEV * math.exp(INV_ALPHA * 3.0 * math.pi / (2.0 * 8.0))
    print(f"  какое обрезание дало бы 137.036 при b = 8:  {lam_need:.3e} ГэВ")
    print(f"     это в {lam_need/M_PL_GEV:.2e} раз выше планковской массы")
    print("""
  ВЫВОД: путь закрыт. При правильном наборе частиц (b = 8) он даёт 1/87.5
  против 137.036 — промах 36 процентов, и заткнуть его нечем: требуемое
  b нецелое, а требуемое обрезание на двенадцать порядков выше планковского.
  Достоинство отрицательного результата в том, что путь был безпараметрическим:
  проверка однозначна и переигровке не подлежит.""")


