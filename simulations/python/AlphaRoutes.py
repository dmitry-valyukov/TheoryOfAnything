# ------------------------- 7. путь 12: alpha как объявленный вход

def route_calibration():
    head("7. ПУТЬ 12: alpha КАК ОБЪЯВЛЕННЫЙ ВХОД")
    G_SI = 6.67430e-11
    HBAR = 1.054571817e-34
    C = 2.99792458e8
    M_E_KG = 9.1093837015e-31
    m_pl = math.sqrt(HBAR * C / G_SI)
    L = math.log(m_pl / M_E_KG)
    grav = G_SI * M_E_KG**2 / (HBAR * C)
    s = 2.0 * ALPHA / (3.0 * math.pi)
    delta_max = s * L

    print("""
  Гипотеза: alpha не выводить, а объявить ВХОДОМ модели — как плотность
  или модуль сдвига. Гипотеза законная: у Стандартной модели свободных
  параметров девятнадцать, и это не делает её бессодержательной.

  НО у alpha есть особенность, из-за которой слово «калибровка» тут
  требует оговорки. Размерные постоянные c, hbar, G калибровочны в точном
  смысле: их можно обратить в единицу выбором единиц. Безразмерную alpha
  в единицу не обратить никаким выбором. Значит она несёт физическое
  содержание, а не соглашение о единицах, и «объявить входом» её можно
  только явно и с оплатой — сокращением числа предсказаний.
""")
    print("  РЕПЕРЫ ДЛЯ БЮДЖЕТА ПАРАМЕТРОВ")
    print(f"    m_Pl/m_e                = {m_pl/M_E_KG:.6e}")
    print(f"    ln(m_Pl/m_e)            = {L:.4f}")
    print(f"    G m_e^2/(hbar c)        = {grav:.6e}")
    print(f"    (m_e/m_Pl)^2            = {(M_E_KG/m_pl)**2:.6e}"
          f"   расхожд. {abs(grav-(M_E_KG/m_pl)**2)/grav:.1e}")
    print(f"    отношение грав/эм       = {grav/ALPHA:.6e}")
    print("""
  Первое наблюдение бесплатное, но его надо зафиксировать: гравитационная
  константа связи есть ТОЖДЕСТВЕННО (m_e/m_Pl)^2. В планковских единицах,
  где размер ячейки задаёт G, сила гравитации ВХОДОМ НЕ ЯВЛЯЕТСЯ — она
  следует из одного отношения масс. Один вход, два наблюдаемых.
""")
    print("  ЧТО ДОБАВЛЯЕТ ПУТЬ 10")
    print(f"    s = 2 alpha/3pi         = {s:.6e}")
    print(f"    delta_max = s ln(m_Pl/m_e) = {delta_max:.6f}")
    print()
    print("    то есть  alpha = 3 pi delta_max / (2 ln(m_Pl/m_e))")
    print()
    print(f"  {'delta_max':>14} {'1/alpha':>12}")
    for d in (0.070, 0.0798, 0.090, 0.100):
        print(f"  {d:>14.4f} {2*L/(3*math.pi*d):>12.2f}")
    print("""
    Здесь delta_max — суммарная доля пути к плавлению, пройденная средой
    от комптоновской длины солитона до собственной ячейки. Это ОДНО число,
    и оно свойство упаковки, а не электродинамики.

    Следствие: alpha и m_e/m_Pl НЕ НЕЗАВИСИМЫ. Калибруй одно — второе
    предсказывается. Чувствительность мягкая: ошибка в delta_max
    переносится на 1/alpha один к одному.
""")
    print("""  БЮДЖЕТ: ЧЕСТНЫЙ СЧЁТ

    без пути 10:   входы {m_e/m_Pl, alpha}          -> 3 наблюдаемых
                   (alpha, m_e/m_Pl, сила гравитации)      выигрыш +1

    с путём 10 и вычисленным delta_max:
                   входы {m_e/m_Pl}                 -> 3 наблюдаемых
                                                            выигрыш +2

    с путём 10, но delta_max тоже входом:
                   входы {m_e/m_Pl, delta_max}      -> 3 наблюдаемых
                                                            выигрыш +1 (без изменений)

    Весь выигрыш держится на том, вычислимо ли delta_max из физики
    заклиненной упаковки. Если да — путь 12 не поражение, а сокращение
    числа входов. Если нет — переименование задачи.
""")
    print("""  ПРАВИЛО, БЕЗ КОТОРОГО ПУТЬ 12 ПРЕВРАЩАЕТ МОДЕЛЬ В НЕОПРОВЕРЖИМУЮ

    1. Входы объявляются СПИСКОМ И ЗАРАНЕЕ, до сравнения с опытом.
    2. Число наблюдаемых строго больше числа входов.
    3. ОДНО И ТО ЖЕ значение входа работает в независимых явлениях —
       именно это отличает калибровку от подгонки.
    4. Список входов модели обязан быть КОРОЧЕ списка Стандартной модели
       (19 параметров без нейтрино, около 26 с ними). Модель претендует
       объяснить происхождение СМ; если её собственный список не короче,
       предприятие не даёт ничего.

    Пункт 4 — главный, и сегодня модель его НЕ выполняет: поскольку спектр
    масс лептонов не выводится (T-7), отношения масс входят как входы, и
    ароматный сектор обходится не дешевле, чем в СМ. Выигрыши модели
    сегодня структурные (заряды 2/3 и -1/3, три цвета из D = 3, уравнения
    Максвелла, спин 1/2), а не числовые.
""")
    print("""  ИСТОРИЧЕСКОЕ ПРЕДУПРЕЖДЕНИЕ

    Обе крайности уже проверены историей и обе провалились. Эддингтон
    выводил 137 из числа степеней свободы и получил сначала 136, потом
    137 — подгонкой под уточнявшийся опыт. Дирак объявил большие числа
    первичными и получил переменную во времени G, опровергнутую
    измерениями. Работает средний путь: вход ОБЪЯВЛЯЕТСЯ, и из него
    выводятся СВЯЗИ между наблюдаемыми.
""")


# ------------------- 8. параметры среды: какие из них вообще считаются

def medium_parameters():
    head("8. ПАРАМЕТРЫ СРЕДЫ: КАКИЕ ИЗ НИХ ВООБЩЕ СЧИТАЮТСЯ")
    print("""
  Возражение: чтобы вычислить delta_max, нужны параметры среды — значит
  совсем без параметров модель не обходится. Верно. Но считать надо не все
  параметры, а только БЕЗРАЗМЕРНЫЕ.

  РАЗМЕРНЫЕ ПАРАМЕТРЫ БЕСПЛАТНЫ. Среда задаётся тройкой rho, G_сдвиг, a.
  Три величины при трёх базовых размерностях (M, L, T) — это ровно выбор
  системы единиц, и ничего сверх него:

      c = sqrt(G/rho)         скорость
      a                       длина
      rho a^3                 масса
      hbar = rho a^4 c        действие (определяет, что называть ячейкой)

  То есть (rho, G, a) есть та же тройка, что (c, hbar, G_Ньютона), то есть
  планковские единицы. Безразмерного содержания в ней НОЛЬ: любую из трёх
  можно обратить в единицу выбором единиц.

  СЧИТАЮТСЯ ТОЛЬКО БЕЗРАЗМЕРНЫЕ. И вот здесь у маргинально заклиненной
  упаковки их почти нет — в этом весь смысл критической точки.
""")
    print("  Что у заклиненной упаковки НЕ является свободным параметром:")
    print()
    print(f"  {'величина':>34} {'значение':>16} {'откуда':>22}")
    rows = [
        ("изостатическое число контактов z_c", "2D = 6", "из D = 3 (Максвелл)"),
        ("предел G/B при заклинивании", "0", "критическая точка"),
        ("коэффициент Пуассона nu", "1/2", "следствие G/B -> 0"),
        ("плотность упаковки phi_J", "~0.639", "универсальна (RCP)"),
        ("масштаб бозонного пика", "~ (dz)^1/2", "универсальный показатель"),
    ]
    for a, b, c in rows:
        print(f"  {a:>34} {b:>16} {c:>22}")
    print("""
  ГЛАВНОЕ СОВПАДЕНИЕ. Условие G/B -> 0 тождественно nu -> 1/2:

      nu = (3B - 2G) / (2(3B + G))  ->  3B/6B = 1/2   при G/B -> 0

  А nu -> 1/2 (то есть K/G -> бесконечность) — это в точности постулат
  несжимаемости модели, введённый ради конфайнмента, гравитации и
  электродинамики (1.6.1). Значит несжимаемость НЕ ЯВЛЯЕТСЯ отдельным
  допущением поверх заклинивания: это ОДНО И ТО ЖЕ условие.

  Модель постулировала маргинальное заклинивание (1.5) и несжимаемость
  (1.6) как два разных постулата. Они оказываются одним.

  ОТСЮДА СТАВКА ПУТИ 10. Если среда сидит ровно в маргинально заклиненной
  точке в D = 3, её безразмерные свойства УНИВЕРСАЛЬНЫ — определяются
  классом универсальности, а не подгонкой. Тогда delta_max есть
  универсальное число этой критической точки, и alpha предсказывается
  из D = 3 плюс условие заклинивания.

  Если же delta_max зависит от неуниверсальной детали упаковки — она
  становится одним объявленным входом (путь 12). Это и есть развилка,
  и решается она расчётом, а не рассуждением.
""")


