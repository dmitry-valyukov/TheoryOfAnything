def which_defect():
    head("3. КАКОЙ ДЕФЕКТ И ЧТО ОН ДАЁТ БЕСПЛАТНО")
    print("""
  Единственное сферически-симметричное соленоидальное поле —
      u = (A / r^2) e_r          (2.7.2: там отброшено как нелокализуемое)
  — и это ровно кулоновский хвост. Оно соленоидально ВНЕ нуля, а в
  нуле имеет дельта-источник с потоком 4 pi A. Это центр дилатации,
  точечный дефект упругой среды с топологическим индексом.

  Даром получаем:
    - закон Гаусса: поток через ЛЮБУЮ охватывающую поверхность = 4 pi A,
      от формы не зависит — теорема Гаусса для соленоидального поля;
    - кулоновскую форму E ~ 1/r^2 — не подгонка, а единственная
      сферически-симметричная соленоидальная конфигурация;
    - квантование: если A есть топологический индекс (число «лишних
      ячеек» в керне — аналог вектора Бюргерса), A = n A_0.

  Цена — и здесь честное расхождение, которое надо назвать. УПРУГАЯ
  энергия хвоста смещения
      mu int |grad u|^2 dV = mu int 6A^2/r^6 * 4 pi r^2 dr = 8 pi mu A^2 / r_c^3
  расходится как 1/r_c^3, тогда как ЭЛЕКТРОСТАТИЧЕСКАЯ энергия кулоновского
  поля — как e^2/(8 pi eps_0 r_c), то есть 1/r_c. Показатели разные.
  Значит E-поле дефекта НЕ есть mu grad u напрямую — оно связано с
  хвостом через нормировку kappa так, что энергия E^2 eps_0/2 ~ 1/r^4,
  то есть E ~ 1/r^2 ~ u, а НЕ ~ grad u ~ 1/r^3. Это и есть содержание
  T-28: E = kappa_E u (поле пропорционально смещению хвоста, а не его
  градиенту) — единственная нормировка, при которой энергии совпадают
  по показателю. Ядро обязательно в обоих прочтениях; классическая
  проблема собственной энергии наследуется, а не решается; естественный
  радиус ядра — шаг упаковки d (1.8), где линейная теория ломается (3.4).
""")
    A = 1.0
    print(f"  {'r_c':>7} {'8 pi A^2 / r_c^3 (упругая)':>27} {'~1/r_c (кулоновская)':>22}")
    for rc in (0.1, 0.01, 0.001):
        print(f"  {rc:>7.3f} {8*math.pi*A**2/rc**3:>27.3e} {1.0/rc:>22.3e}")


