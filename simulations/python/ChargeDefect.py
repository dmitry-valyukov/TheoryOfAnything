def electron_two_carriers():
    head("5. ЭЛЕКТРОН = УЗЕЛ + ДЕФЕКТ: ЧТО СИДИТ В ЦЕНТРЕ")
    m = load_minimizer()
    print("""
  Узел (сектор n = 1) несёт спин, спиральность, массу — и нулевой поток.
  Заряд несёт дефект — центр дилатации с кулоновским хвостом. Чтобы
  электрон был ОДНИМ объектом, оба должны уживаться в центре. Профиль
  минимайзера на оси rho -> 0:
""")
    if m is None:
        print("  (минимайзер не найден)")
        return
    V, R, Z, w = m
    rho_d = (np.abs(V) ** 2).sum(0)
    for i in (0, 1, 2, 4, 8, 12, 16):
        r_val = R[i, 0]
        prof = rho_d[i, :]
        print(f"     rho = {r_val:5.2f}:  max_z |W|^2 = {prof.max():.4f}   "
              f"(плато 1.5, максимум узла {rho_d.max():.3f} на R = 1.88)")
    i, k = 0, int(np.argmax(rho_d[0, :]))
    ratio = V[1, i, k] / V[0, i, k]
    print(f"\n  на оси: V_phi / V_rho = {ratio:.4f}  (= +i: поляризация (x + i y), "
          f"чистый спин, L_z = 0);  |V_z| = {abs(V[2, i, k]):.1e}")
    print("""
  Центр узла НЕ пуст: там регулярная спиновая гирация — круговое
  вращение смещения в плоскости, ортогональной оси, с плотностью ~0.95
  против 1.7 в кольце. Именно эта гирация — стационарное самоколебание
  du/dt в центре (Деррик, C3), которого требует прочтение E = -du/dt.

  Совместимость с дефектом: центр дилатации — сферически симметричный
  РАДИАЛЬНЫЙ источник u ~ e_r / r^2; гирация — чисто ПОПЕРЕЧНОЕ поле
  (e_rho, e_phi), радиальной сферической компоненты не имеет
  (V_z = 0 на оси, а e_rho, e_phi ортогональны e_r в центре).
  Два поля ортогональны по компонентам, суперпозиция не создаёт
  перекрёстного потока — уживаются в одной точке.

  Так У-2 («тор изображает структуру фазы, а не распределение заряда»)
  из оговорки становится утверждением о структуре: заряд — точечный
  дефект в центре, кольцо узла — распределение ФАЗЫ и спиральности
  вокруг; на оси — спиновая гирация. Точечность электрона в рассеянии
  (4.12) естественна: рассеивают дефект и керн гирации, оба на оси.
""")


def verdict():
    head("ВЕРДИКТ ПО T-27 / T-28")
    print("""
  T-27, что выведено:
    - теорема: намотанная мода любого сектора несёт нулевой поток;
      заряд не есть намотка и не есть колебание — только дефект;
    - дефект = центр дилатации, u = A/r^2 e_r: закон Гаусса,
      кулоновский хвост и независимость от поверхности — автоматически;
      квантование — по целочисленности индекса (число лишних ячеек);
    - электрон = узел (спин, масса) + дефект (заряд, в центре): в центре
      узла — регулярная спиновая гирация (поперечная), дефект —
      радиальный источник; ортогональны по компонентам, совместимы.
  T-27, что не выведено: rho_q как ГЛАДКАЯ плотность — и не будет:
    в несжимаемой среде заряд обязан быть особенностью. Собственная
    энергия ядра ~ 1/r_c^3 наследуется; радиус ядра ~ d.
    Плотность тока j — движение дефекта; сила Лоренца — отдельно (не здесь).

  T-28: kappa фиксируется квантованием потока дефекта, kappa_E = e/(eps_0 d^3);
    строки kappa = 1 и kappa = rho c таблицы 3.5.6 — догадки без условия.
    Новый свободный параметр не появился: d — тот же вход, что в 1.8.
""")


