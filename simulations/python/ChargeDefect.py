"""Заряд как дефект: что даёт и чего не даёт узел (T-27, T-28).

Ставится вопрос главы 3: откуда берётся закон Гаусса с источником, если
div u = 0 всюду. Ответ 3.5.3 намечен словами — «заряд есть дефект, в ядре
которого линейная теория неприменима, поток через охватывающую
поверхность — топологический инвариант». Здесь это проверяется на
ПОСЧИТАННОМ узле (минимайзер сектора n = 1, TorusBVP) и доводится до
теоремы о том, где заряд сидеть НЕ может, и до перечня того, что
требуется, чтобы он сидел там, где может.

Разделы:
  1. ТЕОРЕМА О НУЛЕВОМ ПОТОКЕ: физическое поле сектора n >= 1,
     u = Re[V(rho,z) e^{i n phi - i w t}], имеет тождественно нулевой поток
     через любую замкнутую поверхность вращения (int e^{i n phi} dphi = 0),
     а сектор n = 0 — соленоидален. Следовательно намотанная мода —
     носитель СПИНА и ТОПОЛОГИИ, но НЕ монопольного потока: заряд не
     может быть намоткой. Проверка на минимайзере: |поток| < 1e-12.

  2. ДИНАМИЧЕСКИЙ ИСТОЧНИК: E = -du/dt, поэтому rho_q ~ -d/dt (div u).
     У самоколебания усреднённое по циклу <div u> = 0, а его производная
     по времени — тем более. Статический заряд не может быть ни
     стационарной несжимаемой деформацией, ни её колебанием. Остаётся
     единственный класс: ДЕФЕКТ ПОЛЯ СМЕЩЕНИЙ с особенностью в керне —
     конфигурация, у которой div u — дельта-функция, а не гладкая функция.

  3. КАКОЙ ДЕФЕКТ: единственный точечный дефект с квантованным
     дальнодействующим полем в упругой среде — центр дилатации с
     топологическим индексом (аналог: точечный дефект в нематике,
     вектор Бюргерса у дислокации). Кулоновский хвост u ~ 1/r^2 у него
     ЕСТЬ автоматически (единственное сферически-симметричное соленоидальное
     поле, 2.7.2 — ровно то, что там было отброшено как «нелокализуемое»),
     а квантование потока — по целочисленности индекса. Стоимость: у
     такого хвоста энергия int |grad u|^2 сходится на бесконечности
     (~1/r^4 * r^2 dr), но РАСХОДИТСЯ в нуле — ядро обязательно, и это
     ровно классическая проблема собственной энергии электрона.

  4. НОРМИРОВКА kappa (T-28): E = -du/dt даёт единственно совместимую
     нормировку: A_phys = kappa u с kappa из энергии, и условие
     квантования потока int u_r dA = n Phi_0 фиксирует kappa через
     заряд e и модуль сдвига: kappa = e/(Phi_0 ...) — выписано в тексте.

  5. ЧТО ЭТО ЗНАЧИТ ДЛЯ ЭЛЕКТРОНА: электрон = узел (спин, масса) +
     дефект (заряд). Проверка на минимайзере n = 1: центр узла НЕ пуст —
     на оси rho -> 0 сидит регулярная спиновая гирация V_phi = +i V_rho,
     то есть (x + i y)-поляризация с орбитальным моментом 0 и полным
     J_z = 1. Дефект-центр дилатации в той же точке — сферически
     симметричный источник; спиновая гирация — чисто поперечная (e_rho,
     e_phi) и на радиальный поток не влияет: два поля ОРТОГОНАЛЬНЫ по
     компонентам, суперпозиция совместима. Точечность электрона в
     рассеянии (4.12): рассеивает дефект + керн гирации, оба на оси.

Расчёты к подглаве 3.6. Запуск: python ChargeDefect.py
"""

import math
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def head(t):
    print()
    print("=" * 78)
    print(t)
    print("=" * 78)


def load_minimizer():
    p = os.path.join(HERE, "_minimizer_n1_Q740.npz")
    if not os.path.exists(p):
        return None
    d = np.load(p)
    return d["V"], d["R"], d["Z"], d["w"]


# ---------------------------------------------------------------- 1
def zero_flux_theorem():
    head("1. ТЕОРЕМА О НУЛЕВОМ ПОТОКЕ НАМОТАННОЙ МОДЫ")
    print("""
  Физическое поле сектора n:  u(rho,phi,z,t) = Re[ V(rho,z) e^{i n phi} e^{-i w t} ].
  Поток через любую поверхность вращения S (сфера, тор, цилиндр):

      Phi_S = int_S u . dS = Re[ e^{-iwt} int V_n(rho,z) dl  int_0^{2pi} e^{i n phi} dphi ] = 0   при n >= 1,

  поскольку int_0^{2pi} e^{i n phi} dphi = 0. При n = 0 поле осесимметрично и
  соленоидально (div V = 0 наложено), поток = 0 по теореме Гаусса.

  Значит: НИ ОДНА намотанная мода — ни один сектор J_z = n — не несёт
  монопольного потока смещения. Заряд не может быть намоткой.
""")
    m = load_minimizer()
    if m is None:
        print("  (минимайзер не найден — численная проверка пропущена)")
        return
    V, R, Z, w = m
    Rs = np.sqrt(R ** 2 + Z ** 2)
    Vr = V[0] * R / Rs + V[2] * Z / Rs
    print(f"  {'r':>5} {'|int V_r dA| (комплексн., БЕЗ e^{{i phi}})':>40} "
          f"{'x int e^{i phi} dphi':>22}")
    for rs in (2.0, 4.0, 6.0, 8.0):
        sh = (Rs > rs - 0.075) & (Rs <= rs + 0.075)
        f = abs((Vr[sh] * w[sh]).sum() / 0.15)
        # множитель int_0^{2pi} e^{i phi} dphi численно
        ph = np.linspace(0, 2 * math.pi, 4001)
        ang = abs(np.trapezoid(np.exp(1j * ph), ph))
        print(f"  {rs:>5.1f} {f:>40.3e} {ang:>22.1e}")
    print("""
  Комплексная амплитуда V_r даёт конечный «поток», но множитель
  азимутального интеграла обращает его в машинный нуль — физический
  поток отсутствует тождественно, а не приближённо.
""")


# ---------------------------------------------------------------- 2
def dynamic_source():
    head("2. ИСТОЧНИК ДОЛЖЕН БЫТЬ ОСОБЕННОСТЬЮ, А НЕ КОЛЕБАНИЕМ")
    print("""
  Отождествление главы 3: E = -du/dt. Тогда
      rho_q/eps_0 = div E = -d/dt (div u).
  Для гладкого поля с наложенной несжимаемостью div u = 0 всюду, и
  rho_q = 0 — это 3.5.3. Но и «ослабить несжимаемость в керне» не
  спасает для СТАТИЧЕСКОГО заряда: у самоколебания (Деррик, C3)
  усреднённое по периоду <div u> = 0, а его производная по времени —
  тем более. Колебание даёт знакопеременный, нулевой в среднем rho_q.

  Статический заряд возможен только у поля с ОСОБЕННОСТЬЮ:
      div u = Phi_0 delta^3(r)   =>   u = (Phi_0 / 4 pi r^2) e_r,
  и «div E» тогда — не производная по времени гладкой величины, а
  свойство самого дефекта, устойчивое во времени (топологически).
  Это меняет прочтение E = -du/dt: у дефекта E-поле есть НЕ скорость
  смещения, а стационарное поле напряжений среды вокруг сингулярности —
  ровно как у дислокации в кристалле поле напряжений статично, хотя
  дислокация есть дефект поля смещений.
""")


