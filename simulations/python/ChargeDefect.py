def normalization():
    head("4. НОРМИРОВКА kappa (T-28) ИЗ КВАНТОВАНИЯ ПОТОКА")
    print("""
  Для стационарного дефекта E-поле = kappa_E * u_хвоста (раздел 3:
  только так совпадают показатели энергий). Закон Гаусса:
      oint E . dS = kappa_E * 4 pi A = q / eps_0.
  Квант потока смещения A_0 — объём одной «лишней ячейки» в керне,
  A_0 = d^3/(4 pi) (T-40; аналог вектора Бюргерса), A = n A_0. Тогда
      e = eps_0 kappa_E d^3   =>   kappa_E = e / (eps_0 d^3).
  Размерности: [e/eps_0] = В*м, [d^3] = м^3, [kappa_E] = В/м^2; [u] = м,
  так что E = kappa_E u имеет размерность В/м. Сходится.

  Итог для T-28: kappa НЕ свободен и НЕ равен ни 1, ни rho c — он
  фиксируется зарядом и шагом упаковки, kappa_E = e/(eps_0 d^3). Обе
  строки таблицы 3.5.6 (kappa = 1 и kappa = rho c) были догадками без
  условия; условие — квантование потока дефекта. Число же d — тот же
  калибровочный вход, что везде (1.8, 2.10): d фиксируется по e так же,
  как ранее Theta по alpha.
""")


