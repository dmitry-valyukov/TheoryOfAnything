def constraint_chain():
    head("1. ЦЕПОЧКА СВЯЗЕЙ ПО ДИРАКУ")
    print("""
  Лагранжиан среды с наложенной несжимаемостью:

      L = int [ (rho/2) u_dot_i u_dot_i - V(u, du) - p div u ] d^3x

  Импульсы:  pi_i = rho u_dot_i,   pi_p = 0   (p входит в L без производной).
  Гамильтониан:  H = int [ pi^2/(2 rho) + V + p div u ].

      phi_1 = pi_p                      первичная связь
      phi_2 = div u                     вторичная:  d(phi_1)/dt = -dH/dp = -div u
      phi_3 = div pi                    третичная:  d(phi_2)/dt = div pi / rho
      phi_4 = lap p - div(dV/du)        четвертичная: d(phi_3)/dt

  Следующий шаг даёт  lap v = 0, где v — множитель при phi_1 в H_T = H + int v pi_p.
  Это уравнение ОПРЕДЕЛЯЕТ множитель, а не порождает пятую связь: цепочка
  замкнулась на четырёх связях. Определённость множителя — сама по себе
  признак связи второго рода: у связи первого рода множитель остаётся
  произвольным, и эта произвольность и есть калибровочный произвол.

  При линейном V = (mu/2)(d_i u_j)^2 связь phi_4 даёт lap p = 0, откуда p = 0.
  При нелинейном V восстанавливается уравнение 1.6.2:  lap p = -rho d_i d_j(u_i u_j).
""")


# --------------------------------------------- 2. матрица связей и её ранг

def constraint_matrix():
    head("2. МАТРИЦА СВЯЗЕЙ C_ab = {phi_a, phi_b}")
    print("""
  Канонические скобки:  {u_i(x), pi_j(y)} = delta_ij delta(x-y),  {p, pi_p} = delta.
  В k-представлении:    div u -> i k_i u_i,  div pi -> i k_j pi_j,  lap p -> -k^2 p.

      {phi_2, phi_3} = (i k_i)(i k_j) delta_ij = -k^2
      {phi_1, phi_4} = {pi_p, -k^2 p}          = +k^2
      все прочие пары обращаются в нуль

  Порядок: (phi_1, phi_2, phi_3, phi_4) = (pi_p, div u, div pi, lap p).
""")
    print(f"  {'k':>22} {'k^2':>12} {'det C':>16} {'rank':>6} {'dim ker':>9}")
    ok = True
    for kv in K_SAMPLES:
        k2 = sum(c * c for c in kv)
        C = [[F(0)] * 4 for _ in range(4)]
        C[1][2] = -k2
        C[2][1] = k2
        C[0][3] = k2
        C[3][0] = -k2
        det = det_exact(C)
        rk = rank_exact(C)
        ker = 4 - rk
        ok &= (det == k2**4) and rk == 4 and ker == 0
        ks = "(" + ",".join(str(c) for c in kv) + ")"
        print(f"  {ks:>22} {str(k2):>12} {str(det):>16} {rk:>6} {ker:>9}")
    print()
    print(f"  тождество det C = (k^2)^4 = k^8 на всех образцах: {'ДА' if ok else 'НЕТ'}")
    print("""
  det C = k^8 отличен от нуля при любом k != 0, ядро пусто. Значит НЕТ ни одной
  комбинации связей, коммутирующей со всеми остальными, то есть НЕТ связи
  первого рода.

  ВЫВОД: все четыре связи — ВТОРОГО РОДА.

  Особая точка k = 0: там связи вырождаются тождественно (i k_i u_i = 0 при
  k = 0), то есть однородная мода вообще не ограничена. Это глобальный сдвиг
  среды как целого; связи первого рода он не порождает.""")


# ------------------------------------- 3. род связи не зависит от потенциала

def independence_of_potential():
    head("3. РОД СВЯЗИ НЕ ЗАВИСИТ ОТ ПОТЕНЦИАЛА")
    print("""
  Решающая скобка

      {div u (x), div pi (y)} = -lap delta(x - y)   ->   -k^2  != 0

  вычисляется ИСКЛЮЧИТЕЛЬНО из канонической скобки {u_i, pi_j} = delta_ij delta.
  Упругая энергия V в неё не входит вовсе.

  Отсюда теорема: какова бы ни была упругая энергия — линейная, нелинейная,
  с любым числом производных, с любыми параметрами среды — пара
  (div u, div pi) остаётся второго рода. Результат не подгоняется и не
  обходится выбором модели среды.

  Единственное место, где можно было бы вмешаться, — кинетический член:
  нужно, чтобы импульс, сопряжённый u, не был равен rho u_dot. Но rho u_dot
  и есть плотность импульса среды; отказ от этого равенства означает отказ
  от прочтения u как механического смещения, то есть от онтологии модели.
""")


# ------------------------------- 4. калибровочной свободы нет: два довода

def _shear_energy_integral(ux, uy, lam_L, mu, n=20000):
    """
    Интеграл по периоду от V = mu e_ij e_ij + (lam_L/2)(e_kk)^2
    для одномерно-зависимого поля u = (ux(x), uy(x), 0).
    """
    x = np.linspace(0.0, 2 * np.pi, n, endpoint=False)
    dx = 2 * np.pi / n
    dux = np.gradient(ux(x), dx, edge_order=2)
    duy = np.gradient(uy(x), dx, edge_order=2)
    e11 = dux
    e12 = 0.5 * duy
    tr = e11
    dens = mu * (e11**2 + 2 * e12**2) + 0.5 * lam_L * tr**2
    return dens.sum() * dx


def no_gauge_freedom():
    head("4. ПОЧЕМУ КАЛИБРОВОЧНОЙ СВОБОДЫ НЕТ")
    print("""
  Надежда постановки T-12 была на аналогию с кулоновской калибровкой: там
  мгновенность калибровочно-зависима и потому ненаблюдаема. Для этого нужен
  был бы сдвиг

      u -> u + grad(lambda)

  оставляющий теорию инвариантной. Два независимых довода его закрывают.

  ДОВОД A: сдвиг не сохраняет саму связь.

      div(u + grad lambda) = div u + lap lambda

  Связь сохраняется лишь при lap lambda = 0; с убыванием на бесконечности
  отсюда lambda = 0 тождественно. Кандидат в калибровочные преобразования
  не действует на поверхности связей вовсе — калибровать нечего.

  ДОВОД B: сдвиг не сохраняет упругую энергию при mu != 0.
""")
    # u = (0, sin x, 0)  ->  div u = 0 ; lambda = cos x  ->  grad lambda = (-sin x, 0, 0)
    mu, lam_L = 1.0, 0.0
    V0 = _shear_energy_integral(lambda x: np.zeros_like(x), np.sin, lam_L, mu)
    V1 = _shear_energy_integral(lambda x: -np.sin(x), np.sin, lam_L, mu)
    print(f"      u = (0, sin x, 0),  div u = 0  (связь выполнена)")
    print(f"      lambda = cos x,  grad lambda = (-sin x, 0, 0)")
    print(f"      чистый сдвиг: lam_L = 0, mu = 1")
    print(f"      V[u]              = {V0:.6f}   (аналитически  mu*pi/2 = {np.pi/2:.6f})")
    print(f"      V[u + grad lambda] = {V1:.6f}   (аналитически 3mu*pi/2 = {3*np.pi/2:.6f})")
    print(f"      dV = {V1 - V0:.6f}   (аналитически  mu*pi = {np.pi:.6f})")
    print(f"      при mu = 0:  dV = {0.0:.6f}")
    print("""
      Приращение энергии равно mu*pi и обращается в нуль ТОЛЬКО при mu = 0.
      Но mu = 0 означает c_T = sqrt(mu/rho) = 0, то есть отсутствие поперечных
      волн — отсутствие света.

  ЗАПРЕТ. Сдвиговая жёсткость и калибровочная тривиальность несжимаемости
  несовместимы. Среда не может одновременно иметь распространяющиеся
  поперечные моды и ненаблюдаемый мгновенный сектор. Ветвь «первого рода»
  закрыта не численно, а структурно.""")


# ----------------------------------------------- 5. скобка Дирака

def dirac_bracket():
    head("5. СКОБКА ДИРАКА: ПОПЕРЕЧНЫЙ ПРОЕКТОР")
    print("""
      {A, B}_D = {A, B} - {A, phi_a} (C^-1)_ab {phi_b, B}

  В секторе (u, pi) участвуют phi_2 = i k.u и phi_3 = i k.pi, для которых
  C = [[0, -k^2], [k^2, 0]],  C^-1 = [[0, 1/k^2], [-1/k^2, 0]].

  Ненулевые скобки: {u_i, phi_3} = i k_i,  {phi_2, pi_j} = i k_j.
  Единственный выживающий член даёт  (i k_i)(1/k^2)(i k_j) = -k_i k_j / k^2,
  и с учётом знака в определении:

      {u_i(k), pi_j(-k)}_D = delta_ij - k_i k_j / k^2 = P^T_ij
""")
    ok = True
    for kv in K_SAMPLES:
        k2 = sum(c * c for c in kv)
        D = [[(F(1) if i == j else F(0)) - kv[i] * kv[j] / k2 for j in range(3)] for i in range(3)]
        P = [[(F(1) if i == j else F(0)) - kv[i] * kv[j] / k2 for j in range(3)] for i in range(3)]
        # проверки проектора: P^2 = P, P k = 0, tr P = 2
        P2 = [[sum(P[i][m] * P[m][j] for m in range(3)) for j in range(3)] for i in range(3)]
        idem = all(P2[i][j] == P[i][j] for i in range(3) for j in range(3))
        annih = all(sum(P[i][m] * kv[m] for m in range(3)) == 0 for i in range(3))
        tr = sum(P[i][i] for i in range(3))
        ok &= idem and annih and tr == 2
        ks = "(" + ",".join(str(c) for c in kv) + ")"
        print(f"  k = {ks:>22}   P^2 = P: {str(idem):>5}   P k = 0: {str(annih):>5}   tr P = {tr}")
    print()
    print(f"  все проверки проектора точны на всех образцах: {'ДА' if ok else 'НЕТ'}")
    print("""
  Скобки одноимённых переменных зануляются: {u_i, phi_2} = 0 и {phi_2, u_j} = 0,
  поэтому {u_i, u_j}_D = 0, и симметрично {pi_i, pi_j}_D = 0.

  В координатном представлении

      {u_i(x), pi_j(y)}_D = [delta_ij - d_i d_j lap^-1] delta(x - y)

  Оператор lap^-1 нелокален: скобка Дирака двух пространственно разнесённых
  точек ОТЛИЧНА ОТ НУЛЯ. Это и есть формальная запись мгновенности, и она
  физична, поскольку связь второго рода и калибровочной свободы нет.""")
    return True


# ------------------------- 6. алгебра наблюдаемых: ротор убивает нелокальность

def observable_algebra():
    head("6. АЛГЕБРА НАБЛЮДАЕМЫХ E И B")
    print("""
  Отождествления модели (глава 3):   E = -u_dot = -pi/rho,   B = rot u.
  В k-представлении rot -> i k x. Считаем {B_i, E_j}_D, отбросив общий
  множитель -i/rho и сравнив матрицу

      M_ij = sum_{k,l} eps_ikl k_k D_lj      (D — скобка Дирака, нелокальна)

  с локальным эталоном

      M^loc_ij = sum_k eps_ikj k_k           (то же с D -> delta, локально)
""")
    ok = True
    for kv in K_SAMPLES:
        k2 = sum(c * c for c in kv)
        D = [[(F(1) if i == j else F(0)) - kv[i] * kv[j] / k2 for j in range(3)] for i in range(3)]
        M = [[sum(F(int(EPS[i][a][l])) * kv[a] * D[l][j] for a in range(3) for l in range(3))
              for j in range(3)] for i in range(3)]
        Ml = [[sum(F(int(EPS[i][a][j])) * kv[a] for a in range(3))
               for j in range(3)] for i in range(3)]
        same = all(M[i][j] == Ml[i][j] for i in range(3) for j in range(3))
        ok &= same
        ks = "(" + ",".join(str(c) for c in kv) + ")"
        print(f"  k = {ks:>22}   M == M^loc (точно): {same}")
    print()
    print(f"  совпадение точное на всех образцах: {'ДА' if ok else 'НЕТ'}")
    print("""
  Причина видна в две строки. Нелокальная часть проектора есть
  d_l d_j lap^-1 и СИММЕТРИЧНА по (l, j). Ротор сворачивает индекс l с
  антисимметричным eps_ikl, поэтому вклад зануляется тождественно:

      eps_ikl k_k (k_l k_j / k^2) = 0     (свёртка симметричного с антисимметричным)

  Итог:

      {B_i(x), E_j(y)}_D = -(1/rho) eps_ikj d_k delta(x - y)     СТРОГО ЛОКАЛЬНО
      {B_i, B_j}_D = 0,   {E_i, E_j}_D = 0                        локально

  Это ответ, которого в бинарной постановке T-12 не было. Связь второго рода,
  мгновенность физична — но ВСЕ наблюдаемые линейного сектора модели строятся
  ротором и производной по времени, а на них нелокальность не переносится.
  Микропричинность в линейном секторе выполняется ТОЧНО.""")
    return ok


# ------------------------------------------ 7. контраст с электродинамикой

def contrast_with_maxwell():
    head("7. ПОЧЕМУ В ЭЛЕКТРОДИНАМИКЕ ИНАЧЕ")
    print("""
  Различие структурное, и состоит оно в том, НА ЧТО наложена связь.

  Электродинамика.  Связь Гаусса  div E = 0  наложена на ИМПУЛЬС (E = -pi_A).
    {div E(x), div E(y)} = 0, потому что импульсы коммутируют между собой.
    Связь ПЕРВОГО рода, она порождает калибровочные преобразования
    A -> A + grad(lambda), и продольная часть A нефизична с самого начала.
    Условие div A = 0 — это КАЛИБРОВКА, наш свободный выбор. Пара
    (Гаусс, кулоновская калибровка) второго рода, но мгновенность внесена
    нашим выбором и снимается другим выбором.

  Упругая среда.    Связь div u = 0 наложена на КОНФИГУРАЦИЮ.
    Её сохранение во времени ПОРОЖДАЕТ сопряжённую связь div pi = 0,
    а сопряжённая пара второго рода по построению: {div u, div pi} = -lap delta.
    Выбора здесь нет. Продольная часть u — настоящее смещение среды,
    и она удаляется силой (постулатом K -> бесконечность), а не объявляется
    бессмысленной.

  Формально алгебры совпадают: и там и здесь скобка Дирака есть P^T delta.
  Различие целиком в статусе — в электродинамике это цена калибровки,
  в упругой среде свойство самой среды. Именно это и требовалось различить.
""")


# --------------------------- 8. правило отбора мультиполей (численно)

def multipole_selection(n=64, seed=11):
    head("8. ПРАВИЛО ОТБОРА МУЛЬТИПОЛЕЙ (проверка 1.6.4 на сетке)")

    rng = np.random.default_rng(seed)
    L = 2 * np.pi
    ax = np.arange(n) * L / n
    X, Y, Z = np.meshgrid(ax, ax, ax, indexing="ij")
    kax = np.fft.fftfreq(n, d=1.0 / n)
    KX, KY, KZ = np.meshgrid(kax, kax, kax, indexing="ij")
    KK = KX**2 + KY**2 + KZ**2
    KK[0, 0, 0] = 1.0

    def d(f, axis):
        K = [KX, KY, KZ][axis]
        return np.real(np.fft.ifftn(1j * K * np.fft.fftn(f)))

    # Поле строится как ротор локализованного вектор-потенциала: тогда оно
    # соленоидально ТОЧНО (div rot = 0) и при этом локализовано. Простое
    # оконное срезание соленоидального поля связь бы нарушило.
    A = rng.normal(size=(3, n, n, n))
    Ah = np.fft.fftn(A, axes=(1, 2, 3)) * np.exp(-KK / 8.0)
    A = np.real(np.fft.ifftn(Ah, axes=(1, 2, 3)))

    c = L / 2
    win = np.exp(-((X - c) ** 2 + (Y - c) ** 2 + (Z - c) ** 2) / (2 * 0.9**2))
    A = A * win

    U = np.array([
        d(A[2], 1) - d(A[1], 2),
        d(A[0], 2) - d(A[2], 0),
        d(A[1], 0) - d(A[0], 1),
    ])
    U /= np.abs(U).max()

    T = [[U[i] * U[j] for j in range(3)] for i in range(3)]
    S = np.zeros_like(U[0])
    for i in range(3):
        for j in range(3):
            S += d(d(T[i][j], i), j)

    dV = (L / n) ** 3
    xs = [X - c, Y - c, Z - c]
    scale = np.abs(S).max() * L**3

    divu = d(U[0], 0) + d(U[1], 1) + d(U[2], 2)
    mono = S.sum() * dV
    dip = [(xs[k] * S).sum() * dV for k in range(3)]
    quad = np.array([[(xs[a] * xs[b] * S).sum() * dV for b in range(3)] for a in range(3)])
    ref = np.array([[2 * T[a][b].sum() * dV for b in range(3)] for a in range(3)])

    print(f"  сетка {n}^3, локализованное соленоидальное поле, спектральные производные")
    print(f"  контроль связи:   max|div u| / max|u| = {np.abs(divu).max()/np.abs(U).max():.3e}")
    print()
    print(f"  монополь   int S dV          = {mono:+.6e}   (норм. {abs(mono)/scale:.2e})")
    dmax = max(abs(v) for v in dip)
    print(f"  диполь     max_k|int x_k S|  = {dmax:+.6e}   (норм. {dmax/scale/L:.2e})")
    print()
    print(f"  квадруполь int x_k x_l S  против  2 int T_kl:")
    for a in range(3):
        print("      [" + " ".join(f"{quad[a,b]:+11.4e}" for b in range(3)) + "]  vs  ["
              + " ".join(f"{ref[a,b]:+11.4e}" for b in range(3)) + "]")
    err = np.abs(quad - ref).max() / np.abs(ref).max()
    print(f"  относительное расхождение = {err:.2e}")
    print("""
  Монополь и диполь зануляются не приближённо, а тождественно: источник есть
  ДВОЙНАЯ дивергенция тензора напряжений, и оба интеграла сводятся к
  поверхностным. Это не малость, а закон сохранения импульса: замкнутая
  конфигурация среды не может излучить мгновенный сигнал ни как 1/r, ни как
  1/r^2. Первый разрешённый мультиполь — квадрупольный, 1/r^3, и он второго
  порядка по амплитуде.

  Это существенно для довода о сигнализации. Классический контрпример
  «толчок в торец трубы с несжимаемой жидкостью» требует ВНЕШНЕГО поршня.
  В замкнутой модели вакуума внешнего агента нет: любой «поршень» сам есть
  конфигурация u, и полный импульс сохраняется. Монопольный канал закрыт
  тождественно, а не подавлен численно.""")
    return abs(mono) / scale, dmax / scale / L, err


