"""
Классификация связи несжимаемости div u = 0 по Дираку (пункт T-12).

Постановка T-12 бинарна: связь первого рода (порождает калибровочные
преобразования, мгновенность принципиально ненаблюдаема) или второго
(отклик физичен)? Ответ вычисляется алгеброй скобок Пуассона.

Вся линейная алгебра ведётся в ТОЧНЫХ рациональных числах (fractions.Fraction),
поэтому тождества получаются точными, а не с точностью до округления.
Единственный численный блок — проверка правила отбора мультиполей на сетке.

Разделы:
  1. цепочка связей по Дираку и её замыкание
  2. матрица связей C_ab, определитель и ранг  ->  род связи
  3. род не зависит от потенциала: структурная теорема
  4. калибровочной свободы нет: два независимых довода
  5. скобка Дирака: поперечный проектор
  6. алгебра наблюдаемых E и B: ротор убивает нелокальную часть
  7. контраст с электродинамикой: связь на импульсе против связи на конфигурации
  8. правило отбора мультиполей: монополь и диполь зануляются тождественно

Расчёты к подглаве theory/01-6-mgnovennoe-pole-davleniya.md, раздел 1.6.8.
Запуск:  python DiracConstraints.py
"""

from fractions import Fraction as F

import numpy as np

# ------------------------------------------------------------------ утилиты

EPS = np.zeros((3, 3, 3), dtype=int)
for _a, _b, _c in [(0, 1, 2), (1, 2, 0), (2, 0, 1)]:
    EPS[_a, _b, _c] = 1
    EPS[_a, _c, _b] = -1

# несколько несоизмеримых волновых векторов с рациональными компонентами
K_SAMPLES = [
    (F(1), F(0), F(0)),
    (F(1), F(1), F(1)),
    (F(3), F(-2), F(5)),
    (F(1, 2), F(7, 3), F(-4, 5)),
    (F(11, 7), F(-13, 4), F(2, 9)),
]


def head(title):
    print()
    print("=" * 78)
    print(title)
    print("=" * 78)


def det_exact(M):
    """Определитель матрицы из Fraction методом Гаусса, без округления."""
    n = len(M)
    A = [row[:] for row in M]
    det = F(1)
    for col in range(n):
        piv = next((r for r in range(col, n) if A[r][col] != 0), None)
        if piv is None:
            return F(0)
        if piv != col:
            A[col], A[piv] = A[piv], A[col]
            det = -det
        det *= A[col][col]
        inv = F(1) / A[col][col]
        for r in range(col + 1, n):
            f = A[r][col] * inv
            if f:
                for c in range(col, n):
                    A[r][c] -= f * A[col][c]
    return det


def rank_exact(M):
    """Ранг матрицы из Fraction."""
    A = [row[:] for row in M]
    rows, cols = len(A), len(A[0])
    rank, row = 0, 0
    for col in range(cols):
        piv = next((r for r in range(row, rows) if A[r][col] != 0), None)
        if piv is None:
            continue
        A[row], A[piv] = A[piv], A[row]
        inv = F(1) / A[row][col]
        for r in range(rows):
            if r != row and A[r][col]:
                f = A[r][col] * inv
                for c in range(col, cols):
                    A[r][c] -= f * A[row][c]
        row += 1
        rank += 1
        if row == rows:
            break
    return rank


