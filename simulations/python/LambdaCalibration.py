"""Калибровка Λ по форме кривой семейства (T-34): где на однопараметрической
кривой узла сидит электрон и что это говорит о g и h среды.

Задача 2.5 имеет единственный безразмерный параметр Λ = λh/g² с окном
0 < Λ < 3/16; в секторной модели (TorusBVP: g = 2, h = 1) это Λ = -mu/4,
и вдоль семейства узлов n = 1 по заряду Q он пробегает Λ(Q). Три
физических масштаба задачи (длина l, время tau, амплитуда A) фиксируются
тремя свойствами среды; форма семейства от них не зависит, поэтому
любое БЕЗРАЗМЕРНОЕ отношение узла есть функция одного Q (или Λ).

Что считается:
  1. Λ(Q), mu/mu_inf, доли спина и орбиты S_z/Q, L_z/Q, аспект R/r_eff,
     толщина стенки delta (ширина 10–90 % профиля плотности поперёк
     кольца) и R/delta вдоль семейства из torusbvp_results.*;
  2. положение ориентиров (локализация 154, связывание 207, пересечение
     281) в Λ: узел, живущий ниже пересечения уровней, имеет
     Λ_e в 0.05…0.075, т.е. mu/mu_inf ≈ 0.27…0.40 — треть глубины окна,
     не дно; это и есть «калибровка по форме»: без единого числа среды
     семейство фиксирует, где на шкале размягчения стоит электрон;
  3. словарь g, h <-> закон деформирования среды: плотность энергии
     W(eps) = mu_s eps²/2 - (g'/4) eps^4 + (h'/6) eps^6 даёт узлу
     амплитуду плато eps_*² = 3g'/4h' (универсальную для всех узлов) и
     окно частот 0 < |mu| < 3g'²/16h' = (3/4) mu_s·(delta_soft/mu_s), где
     delta_soft — глубина размягчения модуля на плато. Знаки: квартичный
     член ОБЯЗАН быть размягчающим (g' > 0), секстический — упрочняющим
     (h' > 0); экспоненциальный слом Гука 3.4 (упрочнение) даёт h, а не g,
     g приходит из размягчения (гравитация 7, дрожание T-4).

Запуск:  python LambdaCalibration.py
"""

import json
import math
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
G_CUB, H_QUI = 2.0, 1.0
MU_INF = -3 * G_CUB ** 2 / (16 * H_QUI)      # -0.75
LAM_MAX = 3.0 / 16.0


def head(t):
    print(); print("=" * 78); print(t); print("=" * 78)


def wall_thickness(Q):
    """Ширина 10–90 % профиля плотности поперёк кольца (по rho через пик)."""
    p = os.path.join(HERE, f"torusbvp_results_Q{int(round(Q))}_n1_tube.npz")
    if not os.path.exists(p):
        return float("nan"), float("nan")
    d = np.load(p)
    rho, R, Z = d["rho"], d["R"], d["Z"]
    i, j = np.unravel_index(np.argmax(rho), rho.shape)
    line = rho[:, j]                       # по rho при z пика
    r = R[:, j]
    pk = line.max()
    # внешний склон: от пика наружу
    outer = np.where(line[i:] < 0.1 * pk)[0]
    o90 = np.where(line[i:] < 0.9 * pk)[0]
    d_out = float(r[i + outer[0]] - r[i + o90[0]]) if len(outer) and len(o90) else float("nan")
    # полная ширина на полувысоте по rho
    half = np.where(line >= 0.5 * pk)[0]
    fwhm = float(r[half[-1]] - r[half[0]]) if len(half) else float("nan")
    return d_out, fwhm


def main():
    head("КАЛИБРОВКА Λ ПО ФОРМЕ СЕМЕЙСТВА УЗЛОВ n = 1")
    rec = json.load(open(os.path.join(HERE, "torusbvp_results.json")))
    rows = sorted([r for r in rec.values() if r["n"] == 1], key=lambda r: r["Q"])
    print(f"\n  mu_inf = {MU_INF}, Λ = -mu h/g² = -mu/4, Λ_max = 3/16 = {LAM_MAX}\n")
    print("   Q     mu      Λ(Q)   Λ/Λmax  mu/mu_inf  S_z/Q  L_z/Q  R_core  r_eff  R/r_eff  d10-90  fwhm  R/d")
    table = []
    for r in rows:
        lam = -r["mu"] * H_QUI / G_CUB ** 2
        d1090, fwhm = wall_thickness(r["Q"])
        table.append((r["Q"], lam))
        print(f"  {r['Q']:5.0f} {r['mu']:+.4f}  {lam:.4f}  {lam / LAM_MAX:.3f}   {r['mu'] / MU_INF:.3f}    "
              f"{r['S_z'] / r['Q']:.3f}  {r['L_z'] / r['Q']:.3f}  {r['R_core']:5.2f}  {r['r_eff']:5.2f}  "
              f"{r['aspect']:5.2f}   {d1090:5.2f}  {fwhm:5.2f}  {r['R_core'] / fwhm if fwhm == fwhm else float('nan'):5.2f}")
    Qs = np.array([t[0] for t in table]); Ls = np.array([t[1] for t in table])
    print("\n  ориентиры кривой (2.9) в Λ:")
    for name, Qm in (("локализация капли (E)", 153.7), ("порог связывания (A)", 207.1),
                     ("пересечение уровней (B)", 281.4)):
        lam = float(np.interp(Qm, Qs, Ls))
        print(f"    {name:26s} Q = {Qm:6.1f}  Λ = {lam:.4f}  = {lam / LAM_MAX:.3f} Λmax  (mu/mu_inf = {lam / LAM_MAX:.3f})")
    print(f"""
  Чтение 1. Λ(Q) монотонна и медленно подходит к 3/16 (при Q = 1100 —
  лишь 0.53 Λmax): тонкостенный предел далеко. Узел ниже пересечения
  уровней (единственный кандидат в основное состояние, 2.8.5/2.9) стоит
  при Λ_e ≈ 0.05…0.075, т.е. на 27–40 % глубины окна размягчения.
  Доли спина и орбиты почти постоянны: S_z/Q = 0.40–0.43, L_z/Q = 0.57–0.60
  — форма узла жёсткая, «калибровать» ею нечего; аспект R/r_eff растёт
  0.28 -> 0.46 (тор толстостенный, R < r_eff).

  Чтение 2 (словарь). Если амплитуда поля узла — деформация eps среды,
  то W(eps) = mu_s eps²/2 - (g'/4) eps^4 + (h'/6) eps^6, и:
     плато  eps_*² = 3g'/4h'         — одна амплитуда у всех узлов;
     окно   |mu| < 3g'²/16h' = (3/4)·(g' eps_*²/4)  — треть глубины
            размягчения модуля на плато;
     электрон при Λ_e ~ 0.06: |mu_e| ~ 0.3 глубины окна = 0.1 глубины
            размягчения. То есть частота узла — сдвиг вниз от линейной
            ветви на ~10 % от максимального размягчения среды.
  Знаки обязательны: g' > 0 (квартичное РАЗМЯГЧЕНИЕ) — иначе нет
  фокусировки и локализованного узла; h' > 0 (секстическое упрочнение).
  Экспоненциальный слом Гука (3.4) — упрочнение: он даёт h, но не g.
  Размягчение у модели есть в других местах (гравитация как размягчение,
  7; дрожание, T-4): g' — коэффициент ЭТОГО размягчения по амплитуде.
  Численные g', h' требуют закона размягчения — он в модели не выписан;
  но два безразмерных отношения уже фиксированы формой семейства:
     eps_e / eps_* ≈ sqrt(rho_peak/1.5) = 0.93…1.0  (амплитуда электрона
            практически на плато) и mu_e/mu_inf ≈ 0.3…0.4.
""")


if __name__ == "__main__":
    main()
