"""
Слабый сектор: дублеты, W и Z, нейтрино. Проверки к подглаве 4.13.

Три вопроса, три разных исхода:
  - комплементарность занятых плоскостей в дублетах — подтверждается точно;
  - W и Z как «переходный процесс» — ОПРОВЕРГАЕТСЯ счётом;
  - правило «ранг -> заряд» — ограничивается контрпримером с фотоном.

Запуск:  python WeakSector.py
"""

from __future__ import annotations

import math
from fractions import Fraction

import numpy as np

import RotationPlanes as RP

HBAR_MEV_S = 6.582119569e-22        # МэВ*с
C_M_S = 299792458.0
LIGHT_YEAR_M = 9.4607e15

#: дублеты: (имя, n_П первого, n_П второго, заряд первого, заряд второго)
DOUBLETS = (
    ("(u, d)", 2, 1, Fraction(2, 3), Fraction(-1, 3)),
    ("(c, s)", 2, 1, Fraction(2, 3), Fraction(-1, 3)),
    ("(t, b)", 2, 1, Fraction(2, 3), Fraction(-1, 3)),
    ("(nu, e)", 0, 3, Fraction(0), Fraction(-1)),
)

#: (имя, масса МэВ, полная ширина МэВ)
RESONANCES = (
    ("W", 80377.0, 2085.0),
    ("Z", 91187.6, 2495.2),
    ("Delta(1232)", 1232.0, 117.0),
    ("хиггс", 125250.0, 4.1),
    ("pi0", 134.98, 7.81e-6),
)


def own_periods(mass_mev: float, width_mev: float) -> dict:
    """Сколько собственных периодов укладывается во время жизни."""
    tau = HBAR_MEV_S / width_mev
    period = 2.0 * math.pi * HBAR_MEV_S / mass_mev
    return {"tau": tau, "period": period, "ratio": tau / period}


def doublet_check() -> bool:
    """n_П + n_П' = 3 и |q| + |q'| = 1 во всех дублетах?"""
    return all(a + b == 3 and abs(q1) + abs(q2) == 1 and q1 - q2 == 1
               for _, a, b, q1, q2 in DOUBLETS)


def fermi_suppression(q_mev: float, m_w_mev: float = 80377.0) -> float:
    """Подавление вдали от резонанса: (Q / m_W)^2 — форма ферми-константы."""
    return (q_mev / m_w_mev) ** 2


def neutrino_speed_deficit(mass_ev: float, energy_ev: float) -> float:
    """1 - v/c для массивной частицы. Чистая СТО, никакой новой физики."""
    g = (mass_ev / energy_ev) ** 2
    return 1.0 - math.sqrt(max(0.0, 1.0 - g))


def photon_rank() -> dict:
    """Ранг свободной циркулярной волны — контрпример к правилу «ранг -> заряд»."""
    times = np.linspace(0.0, 2 * math.pi, 600, endpoint=False)
    om = RP.omega_from_displacement(RP.field_circular_wave(+1),
                                    (0.3, 0.2, 0.1), times)
    return RP.charge_from_rotation(om, (0, 0, 1))


def virtual_fraction() -> float:
    """
    Доля собственного оборота, доступная максимально виртуальному кванту.

    Если занимать всю массу целиком, dE = m c^2, то dt = hbar/dE, а собственный
    период T = 2 pi hbar / dE. Отношение сокращается до 1/(2 pi) — тождественно,
    при любой массе. Замкнуть цикл виртуальный квант не может в принципе.
    """
    return 1.0 / (2.0 * math.pi)


def yukawa_range_m(mass_mev: float) -> float:
    """Длина затухания эванесцентного отклика: R = hbar/(m c), в метрах."""
    return 197.3269804 / mass_mev * 1e-15


def report() -> None:
    print("=" * 76)
    print("СЛАБЫЙ СЕКТОР: ПРОВЕРКИ К 4.13")
    print("=" * 76)

    print("\n1. Дублеты: комплементарность занятых плоскостей")
    print(f"   {'дублет':>10} {'n':>4} {'n′':>4} {'сумма':>6} {'|q|':>6} "
          f"{'|q′|':>6} {'|q|+|q′|':>9} {'Δq':>4}")
    for nm, a, b, q1, q2 in DOUBLETS:
        print(f"   {nm:>10} {a:>4} {b:>4} {a + b:>6} {str(abs(q1)):>6} "
              f"{str(abs(q2)):>6} {str(abs(q1) + abs(q2)):>9} {str(q1 - q2):>4}")
    print(f"   n + n′ = 3 и |q| + |q′| = 1 во всех дублетах: {doublet_check()}")
    print("   заряд = n/3, поэтому комплементарность ТОЖДЕСТВЕННО даёт Δq = 1 —")
    print("   то самое свойство, которым определяется слабый изоспин")

    print("\n2. Успевают ли W и Z резонировать (по СОБСТВЕННЫМ часам)")
    print(f"   {'частица':>12} {'m, МэВ':>10} {'Г, МэВ':>10} {'тау, с':>11} "
          f"{'T, с':>11} {'тау/T':>9}")
    for nm, m, g in RESONANCES:
        o = own_periods(m, g)
        print(f"   {nm:>12} {m:>10.1f} {g:>10.4g} {o['tau']:>11.3e} "
              f"{o['period']:>11.3e} {o['ratio']:>9.4g}")
    w = own_periods(80377.0, 2085.0)["ratio"]
    d = own_periods(1232.0, 117.0)["ratio"]
    print(f"\n   W успевает {w:.1f} собственных колебания против {d:.1f} у Delta.")
    print("   Предположение «W и Z — переходный процесс, не резонанс»")
    print("   ОПРОВЕРГАЕТСЯ: по мерке модели они резонансы лучше, чем Delta.")
    print("   Ошибка возникает от сравнения с адронными временами: у W и")
    print("   собственный период во столько же раз короче, он тяжёлый.")

    print("\n2б. Но в обычных распадах W ВИРТУАЛЕН, и мерка другая")
    print(f"   {'процесс':>20} {'Q, МэВ':>10} {'q²/m_W²':>12}")
    for nm, q in (("распад нейтрона", 1.293), ("распад мюона", 105.66),
                  ("распад тау", 1776.86), ("рождение W", 80377.0)):
        print(f"   {nm:>20} {q:>10.3f} {(q / 80377.0) ** 2:>12.3e}")
    vf = virtual_fraction()
    print(f"\n   Максимально виртуальному кванту достаётся dt/T = 1/(2pi) = {vf:.6f}")
    print("   собственного оборота — ТОЖДЕСТВЕННО, при любой массе.")
    print("   Значит виртуальный W не успевает и шестой части оборота и по")
    print("   резонансному критерию частицей не является. Исходная догадка")
    print("   «в обычных реакциях W — переходный процесс» ПОДТВЕРЖДАЕТСЯ;")
    print("   опровергается лишь то же самое про РЕАЛЬНЫЙ W.")
    print()
    print("   Критерий сам проводит границу реальное/виртуальное:")
    print(f"     виртуальный W  dt/T = {vf:.3f}  -> процесс")
    print(f"     Delta(1232)    tau/T = {own_periods(1232.0, 117.0)['ratio']:.2f}"
          "  -> резонанс")
    print(f"     реальный W     tau/T = {own_periods(80377.0, 2085.0)['ratio']:.2f}"
          "  -> резонанс")

    print("\n2в. Радиус: эванесцентный отклик ниже резонанса")
    for nm, m in (("W", 80377.0), ("Z", 91187.6)):
        print(f"   {nm}: R = hbar/(mc) = {yukawa_range_m(m):.3e} м")
    print("   наблюдаемый радиус слабого взаимодействия ~2.5e-18 м — совпадает;")
    print("   это юкавская форма, прочитанная как ближнее поле, а не как обмен")

    print("\n3. Откуда брать подавление распада")
    for nm, q in (("нейтрон", 1.293), ("мюон", 105.66), ("тау", 1776.86)):
        print(f"   {nm:>10}: (Q/m_W)^2 = {fermi_suppression(q):.3e}")
    print("   форма ферми-подавления G_F ~ g^2/m_W^2 воспроизводится;")
    print("   сама величина m_W модели пока взять неоткуда")

    print("\n4. Скорость нейтрино — тождество СТО, а не механизм")
    print(f"   {'m, эВ':>7} {'E':>18} {'1 - v/c':>12}")
    for m_ev in (0.45, 0.1):
        for lbl, e_ev in (("0.5 МэВ (солнце)", 5e5), ("10 МэВ (SN1987A)", 1e7)):
            print(f"   {m_ev:>7.2f} {lbl:>18} "
                  f"{neutrino_speed_deficit(m_ev, e_ev):>12.3e}")
    dist = 168000 * LIGHT_YEAR_M
    for m_ev in (0.45, 0.1):
        dt = dist / C_M_S * neutrino_speed_deficit(m_ev, 1e7)
        print(f"   запаздывание от SN1987A при m = {m_ev} эВ: {dt:.3e} с")
    print("   при пределе KATRIN m < 0.45 эВ это миллисекунды на 168 000 св. лет —")
    print("   то есть совпадение с фотонами, которое и наблюдалось")

    print("\n5. Контрпример: циркулярно поляризованный фотон")
    p = photon_rank()
    print(f"   свободная циркулярная волна: rank = {p['rank']}, "
          f"правило дало бы |q| = {p['rank']}/3")
    print("   но фотон нейтрален => правило «ранг -> заряд» требует ЗАМКНУТОГО")
    print("   контура и к бегущим конфигурациям неприменимо")


if __name__ == "__main__":
    report()
