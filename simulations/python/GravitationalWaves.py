# --------------------------- 2. проверка гипотезы «продольная ветвь = ГВ»

def test_longitudinal():
    head("2. ПРОВЕРКА ГИПОТЕЗЫ «ПРОДОЛЬНАЯ ВЕТВЬ = ГВ»")
    print("""
  Три признака проверяются независимо, и все три дают отрицательный ответ.

  ПРИЗНАК 1: ТЕНЗОРНЫЙ РАНГ. Продольная волна есть смещение вдоль
  волнового вектора, u || k. Такое возбуждение описывается ОДНОЙ скалярной
  функцией — это спин 0. Гравитационная волна есть симметричный
  бесследовый поперечный тензор — спин 2. Различие по симметрии, а не по
  величине: никакой выбор параметров среды скаляр в тензор не превратит.

  ПРИЗНАК 2: СКОРОСТЬ. Совместная регистрация GW170817 и GRB 170817A даёт
  |c_gw/c - 1| <= 1e-15. Модель же требует от продольной ветви c_L >> c
  (в пределе несжимаемости — вообще не моды). Расхождение предельное.

  ПРИЗНАК 3: ЧИСЛО ПОЛЯРИЗАЦИЙ. Продольная ветвь даёт одну поляризацию,
  наблюдаются две. Сеть детекторов ограничивает примесь скалярной моды.

  ВЫВОД: гипотеза закрыта по трём независимым основаниям. Существенно,
  что она закрыта НЕ численно, а по симметрии — то есть окончательно.
""")
    print(f"  {'признак':>26} {'продольная ветвь':>22} {'наблюдение':>18} {'итог':>10}")
    for a, b, c, d in (
        ("тензорный ранг", "скаляр (спин 0)", "тензор (спин 2)", "ПРОТИВ"),
        ("скорость", ">> c или не мода", "= c до 1e-15", "ПРОТИВ"),
        ("поляризаций", "1", "2", "ПРОТИВ"),
    ):
        print(f"  {a:>26} {b:>22} {c:>18} {d:>10}")


# ------------------------------ 3. чем ГВ являются в модели на самом деле

def what_gw_are():
    head("3. ЧЕМ ГРАВИТАЦИОННЫЕ ВОЛНЫ ЯВЛЯЮТСЯ В МОДЕЛИ")
    print("""
  Ответ следует из того, чем в модели является сама гравитация. Она есть
  МОДУЛЯЦИЯ МОДУЛЯ СДВИГА (7.1):

      mu(r)/mu_inf = (1 - d<u^2>/<u^2>_L)^2

  Значит гравитационная волна есть распространяющаяся модуляция mu, то
  есть волна ИЗБЫТОЧНОГО ДРОЖАНИЯ. А поскольку дрожание описывается не
  вектором смещения, а его КОРРЕЛЯЦИОННЫМ ТЕНЗОРОМ

      h_ij  ~  d< u_i u_j >

  гравитационная волна есть волна корреляционного тензора, а не волна
  поля смещений. Это объект второго порядка по амплитуде — в точности
  того же порядка, в каком живёт вся гравитация модели (1.6.4).

  Отсюда все наблюдаемые признаки получаются сразу, и ни один не
  подгоняется.
""")
    print(f"  {'признак ГВ':>34} {'как получается в модели':>36}")
    for a, b in (
        ("симметричный тензор ранга 2", "<u_i u_j> симметричен по построению"),
        ("бесследовость (TT)", "след = <u^2>, а div u = 0 его вычищает"),
        ("поперечность", "носитель — сдвиговая ветвь"),
        ("скорость = c", "несёт та же ветвь, что и свет"),
        ("две поляризации", "счёт компонент, см. раздел 4"),
        ("квадрупольность", "двойная дивергенция источника (1.6.4)"),
        ("нет монополя и диполя", "сохранение импульса (1.6.4)"),
        ("второй порядок по амплитуде", "h ~ <u u>, а не ~ u"),
    ):
        print(f"  {a:>34} {b:>36}")
    print("""
  Существенно: признак «скорость = c» здесь не совпадение и не подгонка.
  Гравитация в модели идёт по СДВИГОВОЙ ветви — той же, по которой идёт
  свет (1.6.7), — поэтому проверку GW170817 она проходит ТОЖДЕСТВЕННО.
  Гипотеза же про продольную ветвь эту проверку проваливала бы на
  пятнадцати порядках.
""")


# ---------------------------------------------- 4. счёт поляризаций

def polarization_count():
    head("4. СЧЁТ ПОЛЯРИЗАЦИЙ: ПОЧЕМУ РОВНО ДВЕ")
    D = 3
    total = D * (D + 1) // 2
    after_transverse = total - D          # k_i h_ij = 0 — по одному условию на каждое j
    after_trace = after_transverse - 1    # след = <u^2>, вычищен связью div u = 0
    print(f"  симметричный тензор h_ij в D = {D}:                  {total} компонент")
    print(f"  минус поперечность k_i h_ij = 0 ({D} условия):        -{D}  ->  {after_transverse}")
    print(f"  минус след (материальная связь div u = 0):        -1  ->  {after_trace}")
    print()
    print(f"  ИТОГО независимых поляризаций: {after_trace}   — совпадает с наблюдаемым")
    print(f"  (для волны вдоль z остаются h_xx = -h_yy и h_xy — это h_+ и h_x)")
    print("""
  Ключевой шаг — второй. Бесследовость гравитационной волны в общей
  теории относительности вводится КАЛИБРОВКОЙ (TT-калибровка). Здесь она
  не выбирается, а следует из несжимаемости: след тензора <u_i u_j> есть
  <u^2>, а связь div u = 0 запрещает объёмную деформацию.

  То есть условие TT, которое в ОТО есть удобный выбор, в модели есть
  МАТЕРИАЛЬНАЯ СВЯЗЬ. Это содержательное различие, и оно проверяемо:
  при отказе от строгой несжимаемости появилась бы третья, скалярная
  поляризация — ровно то, что ограничивает сеть детекторов.
""")
    return after_trace


# ------------------------------------------- 5. числовая сверка с LIGO

def ligo_check():
    head("5. ЧИСЛОВАЯ СВЕРКА С СОБЫТИЯМИ LIGO")
    print(f"  характерная амплитуда:      h ~ {H_TYPICAL:.0e}")
    print(f"  в модели h есть d<u^2>/<u^2>_L, то есть доля пути к расклиниванию")
    print(f"  => у Земли волна сдвигает среду на {H_TYPICAL:.0e} этого пути")
    print()
    dL = H_TYPICAL * LIGO_ARM
    print(f"  смещение плеча LIGO: dL = h * L = {dL:.3e} м")
    print(f"  для сравнения, размер протона ~ 1e-15 м:  dL/r_p = {dL/1e-15:.2e}")
    print()
    r_s_sun = 2 * G_N * M_SUN / C**2
    print(f"  гравитационный радиус Солнца r_s = {r_s_sun:.4f} м")
    print(f"  на орбите Земли (1.496e11 м):  r_s/r = {r_s_sun/1.496e11:.3e}")
    print(f"  то есть d<u^2>/<u^2>_L у Земли от Солнца = {r_s_sun/1.496e11:.3e}")
    print("""
  Порядки согласуются с картиной: постоянное поле Солнца сдвигает среду
  на 2e-8 пути к расклиниванию, а проходящая волна — ещё на 1e-21 сверх
  того. Среда у Земли находится глубоко в заклиненной фазе, и линейное
  приближение (1 - x)^2 ~ 1 - 2x здесь заведомо законно.
""")


# --------------------------- 6. что измеряет интерферометр

def what_ligo_measures():
    head("6. ОНТОЛОГИЧЕСКОЕ СЛЕДСТВИЕ: ЧТО ИЗМЕРЯЕТ ИНТЕРФЕРОМЕТР")
    print("""
  В общей теории относительности интерферометр измеряет деформацию
  пространства-времени. В модели пространство не деформируется — оно
  вообще не является объектом. Измеряется другое:

      проходящая волна дрожания модулирует mu
        -> модулирует локальную скорость света c = sqrt(mu/rho)
          -> модулирует время пробега луча по плечу
            -> сдвигает интерференционную полосу

  То есть LIGO измеряет НЕ РАСТЯЖЕНИЕ ПРОСТРАНСТВА, а модуляцию скорости
  света бегущей волной избыточного дрожания среды. Наблюдаемая величина
  та же, онтология другая.

  Это даёт модели проверяемое различение, которого у неё не было:
  в ОТО деформация действует на ЛИНЕЙКУ и на ЛУЧ одинаково (потому эффект
  и выражается через безразмерное h), тогда как в среде модуляция mu
  действует на скорость волны напрямую, а на размеры вещества — через
  перестройку равновесия связанных состояний. Совпадают ли эти два
  действия ТОЧНО — вопрос, который модель обязана проверить: расхождение
  проявилось бы как зависимость отклика детектора от материала плеч.

  Это самостоятельный фальсифицируемый след, и он не посчитан.
""")


def report():
    observed()
    test_longitudinal()
    what_gw_are()
    n = polarization_count()
    ligo_check()
    what_ligo_measures()

    head("СВОДКА")
    print(f"""
  1. ГИПОТЕЗА «ПРОДОЛЬНАЯ ВЕТВЬ = ГВ» ЗАКРЫТА, и закрыта по симметрии,
     а не численно: продольная волна есть скаляр (спин 0), а
     гравитационная — симметричный бесследовый тензор (спин 2). Плюс
     независимо: скорость (c_L >> c против c_gw = c до 1e-15) и число
     поляризаций (1 против 2).

  2. НО ГРАВИТАЦИОННЫЕ ВОЛНЫ В МОДЕЛИ ЕСТЬ, и до сих пор о них не было
     сказано ни слова. Это волна КОРРЕЛЯЦИОННОГО ТЕНЗОРА дрожания
     h_ij ~ d<u_i u_j>, а не волна поля смещений.

  3. Все признаки получаются без подгонки: ранг 2 из симметрии <u_i u_j>;
     поперечность и скорость c — от сдвигового носителя; квадрупольность
     и запрет монополя-диполя — из двойной дивергенции источника (1.6.4);
     второй порядок по амплитуде — потому что h ~ <u u>.

  4. Поляризаций ровно {n}. Условие бесследовости, которое в ОТО есть
     КАЛИБРОВКА, здесь есть МАТЕРИАЛЬНАЯ СВЯЗЬ div u = 0. При отказе от
     строгой несжимаемости появилась бы третья, скалярная поляризация —
     то самое, что ограничивает сеть детекторов. Несжимаемость получает
     ещё один, пятый по счёту, независимый мотив.

  5. Новый фальсифицируемый след: в ОТО деформация действует на линейку
     и на луч одинаково, в среде — по разным механизмам. Расхождение
     проявилось бы как зависимость отклика детектора от материала плеч.
     Не посчитано.
""")


if __name__ == "__main__":
    report()
