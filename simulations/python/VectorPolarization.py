"""
Поляризация моды из уравнений поля: векторная задача поверх радиальной.

Подглава 2.5 решает СКАЛЯРНУЮ задачу для профиля f(r) при f(r) e^{i omega t}.
Но заряд по 5.2 определяется тем, сколько плоскостей вращения задействовано,
а это свойство ВЕКТОРНОГО поля смещений — его поляризации. Здесь поляризация
вводится как переменная и находится из минимума энергии.

Анзац эллиптической поляризации:

    u(r, t) = A(r) [ e1 cos(omega t + ...) + lam * e2 sin(omega t + ...) ]

    lam = 0 — линейная поляризация  -> ось вращения стоит  -> rank 1 -> |q|=1/3
    lam = 1 — круговая              -> ось ходит по дуге   -> rank 2 -> |q|=2/3

Существенно: скалярное решение 2.5 с |u| = f(r) = const по времени — это уже
СКРЫТО круговой случай lam = 1. Вопрос «какая поляризация» там не задавался.

Усреднение по времени даёт (проверено символьно ниже):

    <|u|^2> = N = A^2 (1 + lam^2) / 2
    <|u|^4> = N^2 P4(lam),   P4 = [3(1+lam^4) + 2 lam^2] / (2 (1+lam^2)^2)
    <|u|^6> = N^3 P6(lam),   P6 = [5(1+lam^6) + 3 lam^2 + 3 lam^4] / (2 (1+lam^2)^3)

    P4(0) = 3/2, P4(1) = 1;   P6(0) = 5/2, P6(1) = 1

Градиентный, массовый и кинетический члены зависят только от N, поэтому
поляризацию отбирают ровно два нелинейных члена, и они тянут в РАЗНЫЕ стороны:

    E(lam) = const - (g/4) P4(lam) I2 + (h/6) P6(lam) I3,
    I2 = int N^2 dV,  I3 = int N^3 dV

Кубический (притягивающий) член выигрывает от ЛИНЕЙНОЙ поляризации,
квинтический (отталкивающий) — от КРУГОВОЙ. Порог считается точно.

Запуск:  python VectorPolarization.py
"""

from __future__ import annotations

import math

import numpy as np

import CubicQuintic as CQ


def P4(lam):
    lam = np.asarray(lam, dtype=float)
    return (3.0 * (1.0 + lam ** 4) + 2.0 * lam ** 2) / (2.0 * (1.0 + lam ** 2) ** 2)


def P6(lam):
    lam = np.asarray(lam, dtype=float)
    return ((5.0 * (1.0 + lam ** 6) + 3.0 * lam ** 2 + 3.0 * lam ** 4)
            / (2.0 * (1.0 + lam ** 2) ** 3))


def check_averages(lam: float, num: int = 200001) -> dict:
    """Прямая проверка формул усреднения по времени."""
    t = np.linspace(0.0, 2 * math.pi, num)
    a = np.cos(t)
    b = lam * np.sin(t)
    sq = a ** 2 + b ** 2
    N = float(np.mean(sq))
    return {"N": N, "P4": float(np.mean(sq ** 2)) / N ** 2,
            "P6": float(np.mean(sq ** 3)) / N ** 3,
            "P4_formula": float(P4(lam)), "P6_formula": float(P6(lam)),
            "N_formula": (1.0 + lam ** 2) / 2.0}


def energy_of_polarization(lam, I2: float, I3: float,
                           g: float = 1.0, h: float = 1.0):
    """Часть энергии, зависящая от поляризации (остальное от lam не зависит)."""
    return -(g / 4.0) * P4(lam) * I2 + (h / 6.0) * P6(lam) * I3


def uniform_threshold(g: float = 1.0, h: float = 1.0) -> float:
    """
    Порог для однородного случая: E(0) - E(1) = -(g/8) N^2 + (h/4) N^3.
    Ниже порога выгодна линейная поляризация, выше — круговая.
    """
    return g / (2.0 * h)


def profile_moments(Lam: float, g: float = 1.0, h: float = 1.0):
    """Моменты I2 = int N^2 dV и I3 = int N^3 dV по решению 2.5."""
    f0 = CQ.find_ground_state(Lam, g, h)
    if f0 is None:
        return None
    _, sol = CQ._shoot(f0, Lam, g, h, fast=False)
    rr, ff = sol.t, sol.y[0]
    cut = int(np.argmin(np.abs(ff)))
    rr, ff = rr[:cut + 1], ff[:cut + 1]
    N = ff ** 2                       # у скалярного решения |u|^2 = f^2
    I2 = 4 * math.pi * float(np.trapezoid(N ** 2 * rr ** 2, rr))
    I3 = 4 * math.pi * float(np.trapezoid(N ** 3 * rr ** 2, rr))
    I1 = 4 * math.pi * float(np.trapezoid(N * rr ** 2, rr))
    return {"f0": f0, "I1": I1, "I2": I2, "I3": I3,
            "N_eff": I3 / I2, "R": float(rr[-1])}


def select_polarization(Lam: float, g: float = 1.0, h: float = 1.0):
    """Минимум E(lam) на отрезке [0, 1] для профиля с данным Lam."""
    m = profile_moments(Lam, g, h)
    if m is None:
        return None
    lam = np.linspace(0.0, 1.0, 2001)
    E = energy_of_polarization(lam, m["I2"], m["I3"], g, h)
    i = int(np.argmin(E))
    return {**m, "lam_star": float(lam[i]), "E_lin": float(E[0]),
            "E_circ": float(E[-1]), "E_min": float(E[i])}


def report() -> None:
    print("=" * 78)
    print("ПОЛЯРИЗАЦИЯ МОДЫ ИЗ МИНИМУМА ЭНЕРГИИ")
    print("=" * 78)

    print("\n1. Контроль формул усреднения")
    print(f"   {'lam':>5} {'N числ.':>9} {'N форм.':>9} {'P4 числ.':>9} "
          f"{'P4 форм.':>9} {'P6 числ.':>9} {'P6 форм.':>9}")
    worst = 0.0
    for lam in (0.0, 0.3, 0.7, 1.0):
        c = check_averages(lam)
        worst = max(worst, abs(c["P4"] - c["P4_formula"]),
                    abs(c["P6"] - c["P6_formula"]),
                    abs(c["N"] - c["N_formula"]))
        print(f"   {lam:>5.1f} {c['N']:>9.5f} {c['N_formula']:>9.5f} "
              f"{c['P4']:>9.5f} {c['P4_formula']:>9.5f} "
              f"{c['P6']:>9.5f} {c['P6_formula']:>9.5f}")
    print(f"   максимальное расхождение {worst:.2e}")

    print("\n2. Кто что предпочитает (однородный случай, g = h = 1)")
    print("   E(0) - E(1) = -(g/8) N^2 + (h/4) N^3")
    print(f"   порог N* = g/(2h) = {uniform_threshold():.4f}")
    print(f"   {'N':>7} {'E(0)-E(1)':>12} {'выбор':>10}")
    for N in (0.2, 0.4, 0.5, 0.6, 1.0):
        d = -(1 / 8) * N ** 2 + (1 / 4) * N ** 3
        print(f"   {N:>7.2f} {d:>12.5f} {'линейная' if d < 0 else 'круговая':>10}")
    print("   кубический член тянет к ЛИНЕЙНОЙ, квинтический — к КРУГОВОЙ")

    print("\n3. На реальном профиле 2.5 (моменты по решению)")
    print(f"   {'Lam':>6} {'f0':>10} {'I2':>11} {'I3':>11} {'N_эфф':>8} "
          f"{'lam*':>7} {'выбор':>10}")
    for Lam in (0.02, 0.05, 0.08, 0.10):
        s = select_polarization(Lam)
        if s is None:
            print(f"   {Lam:>6.3f}   ветвь не найдена")
            continue
        choice = ("линейная" if s["lam_star"] < 0.05
                  else ("круговая" if s["lam_star"] > 0.95 else "эллипт."))
        print(f"   {Lam:>6.3f} {s['f0']:>10.6f} {s['I2']:>11.4f} "
              f"{s['I3']:>11.4f} {s['N_eff']:>8.4f} {s['lam_star']:>7.3f} "
              f"{choice:>10}")

    print("\n4. Что это значит для модели")
    print("   Поляризация НЕ свободна: её отбирает баланс кубического и")
    print("   квинтического членов, и отбор зависит от амплитуды, то есть от")
    print("   Lam, то есть от частоты моды. Механизм найден и считается.")
    print()
    print("   Но проверка на модели даёт ОБРАТНОЕ соответствие. По 5.3")
    print("   omega_d = omega_u / 2, значит у d частота НИЖЕ, Lam БОЛЬШЕ,")
    print("   амплитуда БОЛЬШЕ — и по найденному критерию d должен быть")
    print("   КРУГОВЫМ (две плоскости, |q| = 2/3), а u — линейным (1/3).")
    print("   В 5.2 записано наоборот.")
    print()
    print("\n5. Инверсия — это не опровержение, а другая частица")
    from fractions import Fraction as F
    print("   Знак задаётся намоткой и от поляризации не зависит:")
    print("   у пары (керн) он +, у одиночной (маятник) −. Меняется модуль.")
    print()
    print(f"   {'кто ниже по частоте':>24} {'заряды':>22} {'сумма':>7} {'частица':>9}")
    for nm, pair, single in (("пара (керн)", F(2,3), F(1,3)),
                             ("одиночная (маятник)", F(1,3), F(2,3))):
        q = 2 * pair - single
        who = "протон" if q == 1 else ("нейтрон" if q == 0 else "?")
        print(f"   {nm:>24} {f'+{pair} +{pair} −{single}':>22} {str(q):>7} {who:>9}")
    print()
    print("   Одна конструкция даёт ОБА нуклона; различает их только расклад")
    print("   частот. omega_d = omega_u/2 ставит вниз одиночную моду, то есть")
    print("   описывает нейтрон. Это структурное различие n и p, которого в")
    print("   модели до сих пор не было вовсе.")

    print("\n6. Барьера между поляризациями нет")
    lam = np.linspace(0.0, 1.0, 1001)
    print(f"   {'N':>6} {'E(0)':>10} {'E(1)':>10} {'барьер':>11}")
    for N in (0.30, 0.45, 0.50, 0.55, 0.70):
        E = -(1 / 4) * P4(lam) * N ** 2 + (1 / 6) * P6(lam) * N ** 3
        print(f"   {N:>6.2f} {E[0]:>10.5f} {E[-1]:>10.5f} "
              f"{float(E.max() - max(E[0], E[-1])):>11.3e}")
    print("   E(lam) монотонна: минимум всегда в ЧИСТОЙ поляризации, линейной")
    print("   либо круговой. Эллиптических состояний нет, ранг равен 1 или 2 и")
    print("   никогда не «между» — заряд защищён формой энергии, не барьером.")
    print("   Обратная сторона: медленность распада нейтрона отсюда НЕ следует.")
    print("   Слабого сектора в модели нет вовсе — T-38.")

    print("\n   Оговорки, без которых вывод переоценят: анзац монохроматический,")
    print("   профиль взят от скалярного решения и по lam не пересчитывался,")
    print("   мёбиусова намотка в угловую часть не введена. Но знак эффекта")
    print("   от этих уточнений вряд ли перевернётся: он задан отношением")
    print("   P4(0)/P4(1) = 3/2 против P6(0)/P6(1) = 5/2.")


