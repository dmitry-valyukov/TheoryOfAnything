def missing_generations():
    head("3. ЧЕГО НЕ ХВАТАЕТ ДЛЯ ПОКОЛЕНИЙ")
    print("  ЧИСЛО поколений получено (= 3). Не хватает того, ЧЕМ они различаются.")
    print()
    print(f"  {'кандидат':>36} {'статус':>34}")
    for a, b in (
        ("число радиальных узлов", "ЗАКРЫТ: p = 3...5 против 7.6 (T-7)"),
        ("число намоток (индекс Хопфа)", "не проверен — требует задачи на торе"),
        ("поляризация моды", "проверен, соответствие ИНВЕРТИРОВАНО (2.5.7)"),
        ("соотношение сторон тора R/r", "не проверен — требует задачи на торе"),
    ):
        print(f"  {a:>36} {b:>34}")
    print()
    r_mu, r_tau = M_MU / M_E, M_TAU / M_E
    p_mu = math.log(r_mu) / math.log(2)
    p_tau = math.log(r_tau) / math.log(3)
    print(f"  что обязан дать механизм:")
    print(f"      m_mu/m_e  = {r_mu:9.3f}   =>  p = {p_mu:.3f}  (если m ~ n^p)")
    print(f"      m_tau/m_e = {r_tau:9.3f}   =>  p = {p_tau:.3f}")
    print("""
  Существенно, что ДВА оставшихся кандидата — число намоток и соотношение
  сторон — проверяются ОДНИМ И ТЕМ ЖЕ расчётом: решением задачи на торе.
  Если у неё есть дискретное семейство решений, индексированное намоткой,
  то это и есть механизм поколений, а отношения энергий — отношения масс.
""")


